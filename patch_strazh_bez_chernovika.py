# -*- coding: utf-8 -*-
"""
ПАТЧ: STRAZH_BEZ_CHERNOVIKA_V1 — убрать мёртвую функцию.

`uslovie_otkat_do_urovnya` писалась под гипотезу «Василий = сторож,
ждущий касания уровня Брута». Гипотеза ОТМЕНЕНА (§5к/§5л, подтверждено
картинкой Котина в §5н): Василий — не сторож на уровень, а МИНИ-ИСКРА,
рекурсивно та же машинерия, что и крупная Искра, на масштаб мельче.

Функция была помечена черновиком с самого начала, никуда не вживлена,
никем не вызывается. Держать её — значит оставлять на виду тупиковую
гипотезу, за которую кто-нибудь потом ухватится.

`nablyudat_za_tochkoy` и `uslovie_novy_fraktal` НЕ ТРОГАЕМ — они живые
и нужны: дыра §5к (Совет просыпается один раз, а фрактал волны 1
рождается через 4-25 баров) сегодняшним разговором не закрыта.

ЗАПУСК: из корня репо
    python patch_strazh_bez_chernovika.py

Идемпотентно. Бэкап рядом (.bak).
"""
import ast
import shutil
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent
TARGET = REPO / "Биржа" / "strazh.py"
MARKER = "STRAZH_BEZ_CHERNOVIKA_V1"

HEAD = ("# ════════════════════════════════════════════════════════════\n"
        "# УСЛОВИЕ 2 — для Василия: откат до уровня фрактала Брута\n"
        "# ════════════════════════════════════════════════════════════")

ZAMENA = '''# ════════════════════════════════════════════════════════════
# УСЛОВИЕ 2 — для Василия — УБРАНО (STRAZH_BEZ_CHERNOVIKA_V1)
# ════════════════════════════════════════════════════════════
# Здесь жила `uslovie_otkat_do_urovnya` — черновик под гипотезу
# «Василий ждёт касания уровня Брута». Гипотеза ОТМЕНЕНА: Василий —
# не сторож на уровень, а МИНИ-ИСКРА (§5к/§5л, подтверждено картинкой
# Котина §5н). Волна 2, приближенная на меньший ТФ, сама разворачивается
# в свою структуру со своим разворотом на конце — Василий ловит ЕГО.
#
# Это отдельная стройка, сопоставимая по объёму с самой Искрой, и она
# НЕ начата. Когда начнётся — это будет не условие для сторожа, а
# собственный мини-спуск + свежий Морж + свежий Паникёр на своём
# масштабе. Держать здесь тупиковый черновик — только путать.
'''


def main():
    if not TARGET.exists():
        print(f"[ПАТЧ] ✗ не найден: {TARGET}")
        print("[ПАТЧ]   запускать из КОРНЯ репо Grondheim-Ecosystem")
        return 1

    src = TARGET.read_text(encoding="utf-8")

    if MARKER in src:
        print(f"[ПАТЧ] ✓ {MARKER} уже применён — ничего не делаю")
        return 0

    if HEAD not in src:
        print("[ПАТЧ] ✗ якорь не найден — файл уже другой, ничего не трогаю")
        return 1

    if "def uslovie_otkat_do_urovnya" not in src:
        print("[ПАТЧ] ✓ функции уже нет — ставлю только маркер")
        src += f"\n# {MARKER} - marker\n"
    else:
        a = src.index(HEAD)
        src = src[:a] + ZAMENA + f"\n# {MARKER} - marker\n"

    try:
        ast.parse(src)
    except SyntaxError as e:
        print(f"[ПАТЧ] ✗ результат не парсится: {e}")
        return 1

    shutil.copy2(TARGET, TARGET.with_suffix(".py.bak"))
    TARGET.write_text(src, encoding="utf-8")
    print(f"[ПАТЧ] ✓ {MARKER} применён")
    print("[ПАТЧ]   убрана uslovie_otkat_do_urovnya (мёртвый черновик)")
    print("[ПАТЧ]   nablyudat_za_tochkoy и uslovie_novy_fraktal — нетронуты")
    return 0


if __name__ == "__main__":
    sys.exit(main())
