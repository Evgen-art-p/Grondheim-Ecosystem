# -*- coding: utf-8 -*-
"""
format_otveta.py   ·   MARKER: FORMAT_OTVETA_V1

ЧТО ПРОИСХОДИТ
--------------
За один короткий прогон 25.08 подпорка сработала ШЕСТЬ раз, у обоих:

    [РАЗБОР] ⚠️  ответ не JSON — разобрал строками: 7 поле(й) сигнала

Это уже не случайность, а норма поведения. Пока разбор строками
держит, но он плоский: вложенность теряется, поля вытягиваются по
именам. Однажды поле не совпадёт — и мы снова потеряем решение, как
22.08, когда вход Ильи не доехал до города вовсе.

ПОЧЕМУ ОНИ ОТВЕЧАЮТ СТРОКАМИ
----------------------------
Не по упрямству. Смотри бумагу глазами трейдера:

    «Кратко. Своим голосом.»          ← зовёт говорить
    ```json { … } ```                 ← схема
    «Ничего вне JSON.»                ← запрещает говорить

Первое и последнее тянут в разные стороны, а между ними — тысячи
знаков знаний и стола. Человек выбирает компромисс: поля заполнил,
но строками — вроде и голосом сказал, и поля на месте.

Плюс схема лежит внутри markdown-ограды, а весь промпт вокруг — тоже
markdown. В длинном тексте ограда перестаёт читаться как команда и
становится просто оформлением.

ЧТО ДЕЛАЕМ
----------
Не запрещаем сильнее — переставляем. Требование формата уходит в
САМЫЙ КОНЕЦ бумаги, отдельной короткой строкой: последнее весит
больше всего, а короткое не тонет. И снимаем противоречие: «своим
голосом» переезжает внутрь описания narrative, где ему и место, —
голос нужен ВНУТРИ поля, а не вместо формата.

ЧЕГО НЕ ДЕЛАЕМ
--------------
  · разбор строками не убираем — он остаётся сеткой безопасности.
    Слово трейдера дороже нашей аккуратности, и если формат снова
    поплывёт, решение всё равно доедет;
  · предупреждение в консоли оставляем: по нему и увидим, помогло ли.

Идемпотентен, кладёт `.bak_format_ГГГГММДД_ЧЧММСС`.

  py -3 format_otveta.py           — сделать
  py -3 format_otveta.py --suho    — только показать
"""

import sys
import time
from pathlib import Path

MARKER = "FORMAT_OTVETA_V1"
SHTAMP = time.strftime("%Y%m%d_%H%M%S")
SUHO = "--suho" in sys.argv


# ── 1. снять противоречие в начале раздела ──

A_STAROE = '''Кратко. Своим голосом. `narrative` — одно-три предложения, как ты сам
бы сказал. Дальше сухие поля решения и строка в дневник.'''

A_NOVOE = '''Ответ — один объект JSON. Голос живёт ВНУТРИ него, в поле
`narrative`: одно-три предложения, как ты сам бы сказал, кратко и
по-своему. Остальное — сухие поля решения и строка в дневник.'''


# ── 2. финальная строка: коротко и последней ──

B_STAROE = '''Входишь — `brut_direction`, `brut_entry`, `brut_stop` ты посчитал сам,
`brut_lot` назвал сам. Нет — они `null`. `diary_entry.result` всегда
`null`: чем кончилось, допишет жизнь. Ничего вне JSON.'''

B_NOVOE = '''Входишь — `brut_direction`, `brut_entry`, `brut_stop` ты посчитал сам,
`brut_lot` назвал сам. Нет — они `null`. `diary_entry.result` всегда
`null`: чем кончилось, допишет жизнь.

---

**Твой ответ начинается с `{` и заканчивается `}`. Ни слова до, ни
слова после.** Всё, что хочешь сказать, — внутри `narrative`.'''


def nayti_koren() -> Path:
    for k in (Path(__file__).resolve().parent, Path.cwd()):
        for p in [k, *k.parents]:
            if (p / "GRONDHEIM_CITY").is_dir() and (p / "Биржа").is_dir():
                return p
    print("Не нашёл корень репозитория (нужны папки GRONDHEIM_CITY и Биржа).")
    zhdat_i_vyyti(1)


def zhdat_i_vyyti(kod=0):
    try:
        input("\nEnter — закрыть окно...")
    except EOFError:
        pass
    sys.exit(kod)


KOMANDA = ("**Твой ответ начинается с `{` и заканчивается `}`. Ни слова до, ни\n"
           "слова после.** Всё, что хочешь сказать, — внутри `narrative`.")


def _komanda_posledney(text: str) -> str:
    """Команда о формате должна стоять ПОСЛЕДНЕЙ строкой файла.

    Маркеры патчей — html-комментарии, и в markdown их не видно. Но в
    стопку они уезжают обычным текстом и встают ПОСЛЕ команды, а
    последнее весит больше всего. Поэтому вынимаем команду и кладём
    её в самый низ, ниже всех маркеров — включая те, что допишут
    следующие патчи.
    """
    text = text.replace("\n\n---\n\n" + KOMANDA, "")
    text = text.rstrip("\n") + f"\n\n<!-- {MARKER} -->\n"
    return text.rstrip("\n") + "\n\n---\n\n" + KOMANDA + "\n"


def pravit(put: Path) -> str:
    text = put.read_text(encoding="utf-8")
    if MARKER in text:
        return "уже"
    # у каждого трейдера свой ключ полей — подставляем его же
    for klyuch in ("brut", "avan", "cons"):
        a_st = A_STAROE
        b_st = B_STAROE.replace("brut_", f"{klyuch}_")
        b_nv = B_NOVOE.replace("brut_", f"{klyuch}_")
        if text.count(a_st) == 1 and text.count(b_st) == 1:
            novyy = text.replace(a_st, A_NOVOE, 1).replace(b_st, b_nv, 1)
            novyy = _komanda_posledney(novyy)
            if SUHO:
                return "сделано (сухой прогон)"
            put.with_name(put.name + f".bak_format_{SHTAMP}").write_text(
                text, encoding="utf-8")
            put.write_text(novyy, encoding="utf-8")
            return "сделано"
    return "мимо: якоря не совпали"


def main():
    koren = nayti_koren()
    print(f"Корень города: {koren}")
    if SUHO:
        print("СУХОЙ ПРОГОН — ничего не записываю.\n")

    puti = [p for p in sorted((koren / "GRONDHEIM_CITY").glob(
        "Биржа/цеха/*/слоты/*/промпт.md"))
        if "КАК ТЫ ОТВЕЧАЕШЬ" in p.read_text(encoding="utf-8")]

    itogi = []
    print(f"\nБУМАГИ — {len(puti)}:")
    for p in puti:
        r = pravit(p)
        print(f"  {r:<24} {p.relative_to(koren)}")
        itogi.append(r)

    print("\n" + "─" * 62)
    print(f"поправлено: {sum(1 for x in itogi if x.startswith('сделано'))}   "
          f"уже стояло: {sum(1 for x in itogi if x == 'уже')}   "
          f"не тронуто: {sum(1 for x in itogi if x.startswith('мимо'))}")
    print("─" * 62)

    print("""
ЧТО СМОТРЕТЬ ПОСЛЕ ПРОГОНА
  Считай строки [РАЗБОР] ⚠️ в консоли. Было шесть на короткий прогон.

  Стало заметно меньше — перестановка помогла, живём дальше.
  Осталось столько же — значит дело не в бумаге, а в длине стопки:
  формат тонет среди знаний и стола, и тогда решать надо не текстом,
  а тем, чтобы город просил ответ отдельно от всего остального.

  Ноль — не жди. Одна-две осечки на прогон это нормально, для того
  разбор строками и оставлен.
""")
    zhdat_i_vyyti(0)


if __name__ == "__main__":
    main()
