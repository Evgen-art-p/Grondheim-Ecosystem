def _pravka(slot: str) -> int:
    p = SLOTY / slot / "мозг.py"
    if not p.exists():
        print(f"  {slot}: файла нет")
        return 0
    txt = p.read_text(encoding="utf-8")
    if MARKER in txt:
        print(f"  {slot}: уже стоит")
        return 0

    novy, sdelano = txt, []

    para = KUSKI.get(slot)
    if para and novy.count(para[0]) == 1:
        novy = novy.replace(para[0], para[1], 1)
        sdelano.append("три места и счёт цены убраны")

    # дальше — отдельные фразы, каждая проверяется на единственность.
    # Идут ВСЕГДА, а не «если предыдущее не сработало»: у A08 крупный
    # кусок и фраза про счёт цены лежат в разных местах, и по первой
    # версии патча вторая оставалась висеть.
    if True:
        odinochki = [
            ('"Решаешь только ты. Три места входа лежат у тебя в знаниях, "',
             '"Решаешь только ты. Место у тебя одно: конец хода — "\n'
             '        "разворотный бар, который тебя разбудил. "'),
            ('"— называешь сторону, СЧИТАЕШЬ entry и stop сам из чисел стола; где "',
             '"— называешь сторону, а цену и стоп отдаёшь В ПРИКАЗЕ, рукой; где "'),
            ('"Входишь — называешь сторону, СЧИТАЕШЬ entry и stop сам из чисел "',
             '"Входишь — называешь сторону, а цену и стоп отдаёшь в ПРИКАЗЕ "'),
        ]
        for staroe, novoe in odinochki:
            if novy.count(staroe) == 1:
                novy = novy.replace(staroe, novoe, 1)
                sdelano.append(staroe[:34].strip('"') + "…")

    if not sdelano:
        print(f"  {slot}: ! знакомых кусков не нашлось — не трогаю")
        return 0

    novy = novy.rstrip("\n") + f"\n\n# {MARKER} - marker\n"
    try:
        ast.parse(novy)
    except SyntaxError as e:
        print(f"  {slot}: ОТКАЗ — синтаксис сломан ({e})")
        return 0

    if not SUHO:
        shutil.copy2(p, p.with_suffix(".py.bak_uroven"))
        p.write_text(novy, encoding="utf-8")
    print(f"  {slot}: {'готов' if SUHO else 'поправлен'} — "
          + "; ".join(sdelano))
    return 1


