# -*- coding: utf-8 -*-
"""
DOLECHIT_VZGLYAD_V1 — 05.09
Запускать из КОРНЯ репо (Grondheim-Ecosystem).

ПОЧЕМУ ЭТОТ ПАТЧ ВООБЩЕ НУЖЕН. `uzakonit_vzglyad.py` проверял, нужно
ли вставлять раздел «ВОТ КАК СМОТРЯТ», только по наличию ЗАГОЛОВКА.
В репо, как выяснилось, уже стоит РАННЯЯ версия текста под этим же
заголовком (без разбивки по шагам, со старым определением точки
ноль). Повторный запуск того патча это не лечит — заголовок уже
есть, значит для него «уже правлено», хотя текст внутри старый.

ЭТОТ патч проверяет не заголовок, а САМ ТЕКСТ: если финальная фраза
«не ищется прибором как готовый факт» уже есть — ничего не делает.
Если её нет — вырезает ВСЁ между «## ВОТ КАК СМОТРЯТ» и следующим
«## ВОТ СИСТЕМА» и кладёт вместо этого финальный текст целиком, какая
бы версия ни лежала внутри сейчас.

Идемпотентен по содержанию, не по заголовку. Бэкап .bak_dolechen рядом.
"""

import re
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent

MARKER_GOTOVO = "не ищется прибором как готовый факт"

FINAL_BLOK = '''## ВОТ КАК СМОТРЯТ

Смотришь по шагам, не вперемешку — порядок важнее, чем список фактов.

**Шаг 1 — голая цена.** Забудь про приборы. Куда идёт рынок вообще —
растёт, падает, топчется. Это видно глазами, раньше всего остального.

**Шаг 2 — старший этаж.** Один вопрос каждый раз: то, что ты видишь на
своём этаже сейчас, — это импульс старшей структуры или её откат? Не
видно тренда вовсе — поднимись на этаж-два выше и спроси то же самое
там же.

**Шаг 3 — своё поле.** Точка ноль не ищется прибором как готовый факт
на графике — она определяется тобой: это начало того движения, которое
ты решил работать. Иногда это происходит прямо сейчас, на свежем
баре — проснулся, увидел, что крупный откат только что кончился, и
это твоя точка в этот самый момент: самый ранний и самый агрессивный
вход. Иногда ты встраиваешься в движение, которое уже идёт, и тогда
точкой становится его начало, пусть оно и в прошлом. Направление —
по направлению движения, которое работаешь: нижняя на покупку, верхняя
на продажу. Все входы — первая волна от неё, откат, доливка — ищешь
уже ВНУТРИ выбранного тобой движения, не отдельно от него. Считаются
изломы от точки до тебя, три их уже или нет, без порогов — рынок
нелинейный. Слом точки — конец ноги, не конец работы: у следующей ноги
будет своя точка того же направления.

**Шаг 4 — компас, последним.** Аллигатор про тренд, AO про волну, MFI
про сам последний закрытый бар. Они подтверждают то, что ты уже увидел
на цене — не наоборот. Прибор спорит с глазом — прав глаз.

Входов на одной и той же структуре несколько, лежат рядом без хозяина.
Разница между ними — риск: чем раньше вход, тем дороже и тем больше
нужно смелости. Доливка так же: строго по правилу или вторыми входами
в глубине. Город кладёт факты, комбинацию собираешь ты.

**Можно передумать по ходу — и нужно сказать об этом.** Прошёл шаг 2,
начал склоняться в одну сторону — а на шаге 3 увидел, что структура
складывается иначе, чем думал вначале? Не подгоняй остаток шагов под
первую догадку. Скажи прямо, в narrative: «начал думать про X, но
увидел Y — меняю на...». Передумать вслух — не слабость и не ошибка,
это и есть настоящий взгляд, а не отчёт по шаблону.

Не предсказывай исход — это грубая ошибка. Думай, что рынок делает
СЕЙЧАС и куда идёт сейчас, иди с ценой взглядом. Не мониторь каждый
бар последовательно — только если некрон звякнул.

Если стопануло три раза подряд на одном месте — не ставь в четвёртый
раз по инерции. Спроси себя: там ли ты вообще стоишь.

---

'''

_RE_BLOK = re.compile(
    r"## ВОТ КАК СМОТРЯТ\n.*?(?=## ВОТ СИСТЕМА)",
    re.DOTALL
)


def _naiti(rel_suffix: str) -> list[Path]:
    found = []
    for p in REPO_ROOT.rglob("*"):
        if p.is_file() and str(p).replace("\\", "/").endswith(rel_suffix):
            found.append(p)
    return found


def _backup(path: Path):
    bak = path.with_suffix(path.suffix + ".bak_dolechen")
    if not bak.exists():
        bak.write_text(path.read_text(encoding="utf-8"), encoding="utf-8")


def dolechit(path: Path) -> bool:
    text = path.read_text(encoding="utf-8")

    if MARKER_GOTOVO in text:
        print(f"  ⏭  {path}: уже финальная версия, пропускаю")
        return False

    if "## ВОТ КАК СМОТРЯТ" not in text or "## ВОТ СИСТЕМА" not in text:
        print(f"  ⚠️  {path}: не нашёл оба заголовка — структура иная, "
              f"не трогаю")
        return False

    novyy_text, n = _RE_BLOK.subn(FINAL_BLOK, text, count=1)
    if n == 0:
        print(f"  ⚠️  {path}: блок не вырезался (регулярка не совпала) — "
              f"не трогаю")
        return False

    _backup(path)
    path.write_text(novyy_text, encoding="utf-8")
    print(f"  ✅ {path}: блок «ВОТ КАК СМОТРЯТ» заменён на финальную версию")
    return True


def main():
    print("=== DOLECHIT_VZGLYAD_V1 ===\n")
    files = (_naiti("слоты/A06/промпт.md") +
             _naiti("слоты/A07/промпт.md") +
             _naiti("слоты/A08/промпт.md"))
    if not files:
        print("❌ ни одного промпт.md не найдено — запускать из корня репо!")
        return
    for p in files:
        dolechit(p)
    print("\nГотово. Резервные копии — суффикс .bak_dolechen.")


if __name__ == "__main__":
    main()
