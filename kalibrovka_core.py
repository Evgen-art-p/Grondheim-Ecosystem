    print("═══ КАЛИБРОВКА · ЯДРО — самопроверка ═══")
    proby = [
        ("чистая оптика",        {"_charge": 0.0,  "DNA_Static": {"Stubbornness": 0.5}}),
        ("лёгкая муть, кроткий", {"_charge": 0.4,  "DNA_Static": {"Stubbornness": 0.3}}),
        ("лёгкая муть, упрямый", {"_charge": 0.4,  "DNA_Static": {"Stubbornness": 0.9}}),
        ("сильная муть",         {"_charge": 0.7,  "DNA_Static": {"Stubbornness": 0.5}}),
        ("призму залило",        {"_charge": -0.95, "DNA_Static": {"Stubbornness": 0.9}}),
        ("Вера (реальный)",      {"_charge": 0.0,  "DNA_Static": {"Stubbornness": 0.9}}),
        ("битый паспорт",        {}),
    ]
    for name, p in proby:
        r = compute_mode(p)
        plan = "план" if stroit_plan(r["mode"]) else "молчит"
        print(f"  {name:22} → {r['mode']:9} [{plan}] · {r['почему']}")
    print("═══ конец ═══")
