"""
КАЛИБРОВКА · ЯДРО — физика единицы, одна на весь город.

ЧТО ЭТО (метафора Шефа): перед тем как войти в рабочий такт, единица
протирает призму (Характер + Заряд), чтобы смотреть на факты без
искажений вчерашнего дня. Ядро отвечает на ОДИН вопрос:
  «Насколько чиста твоя оптика прямо сейчас?» → режим.

ЗАКОН ФРАКТАЛА: расчёт режима — это физика ЕДИНИЦЫ, не здания.
Житель есть житель: сила считается по его ручкам одинаково — торгует
он на Бирже или рисует в Студии. Поэтому compute_mode живёт в ЯДРЕ
(корень репо), а Биржа/Студия его ЗОВУТ, не копируют. Иначе два здания
разведут две копии формулы — ровно болезнь -2.

ЧЕСТНОСТЬ ПОЛЕЙ: считаем по тому, что РЕАЛЬНО есть в паспорте нового
города — 6 канонных ручек (DNA_Static) + живой заряд (_charge от
dvizhok). Никаких Stress/Internal_Light/Patience — это порода старого
города (-2), в Грондхейме её нет. Не читаем несуществующее.

БЕЗ LLM. БЕЗ ГОРОДА. Чистая математика. Детерминировано (тот же
паспорт → тот же режим всегда).

Режимы (перенесены смыслом из morning_checkout.py -2):
  GENIUS   — оптика чиста / упрям сверх меры → полная сила, творит
  NORMAL   — рабочий такт, ровно
  SAFE     — оптика мутит → осторожно, не рисковать
  RECOVERY — призму залило вчерашним → эту сессию пропускает,
             не строит план, не торгует (само-ограничение —
             тот самый Закон Трибунала: не превращать эмоцию в позицию)

`шесть·проверено·до·корня`
"""


def _f(x, default=0.0):
    """Мягкое чтение числа: битое/пустое → default, не падение."""
    try:
        return float(x)
    except (TypeError, ValueError):
        return default


def compute_mode(passport: dict) -> dict:
    """Режим единицы по её паспорту. Физика оптики.

    Читает (всё реально есть в паспорте нового города):
      _charge            — живой заряд от dvizhok (−1..+1). |заряд| =
                           насколько вчерашнее искажает взгляд сегодня.
      DNA_Static.Stubbornness   — упрямец тянется выше сил.
      DNA_Static.Autonomy_Level — насколько сам решает.

    Возвращает:
      {"mode": ..., "муть": float, "почему": str}
      муть = |заряд| — насколько замылена призма (0 чисто .. 1 залито).
    """
    charge = _f(passport.get("_charge", 0.0))
    mut = abs(charge)                       # грязь на призме
    dna = passport.get("DNA_Static", {}) or {}
    stubborn = _f(dna.get("Stubbornness", 0.5), 0.5)

    # ── Призма чиста → полная сила ────────────────────────────
    if mut < 0.25:
        return {"mode": "GENIUS", "муть": round(mut, 3),
                "почему": f"муть={mut:.2f} — оптика чиста, взгляд ясен"}

    # ── Средняя муть ──────────────────────────────────────────
    if mut < 0.55:
        if stubborn > 0.6:
            # Упрямец не признаёт мути. Тянется в полную силу.
            # Заплатит потом — но сегодня идёт как GENIUS.
            return {"mode": "GENIUS", "муть": round(mut, 3),
                    "почему": f"упрямство={stubborn:.2f} сильнее мути={mut:.2f}"}
        return {"mode": "NORMAL", "муть": round(mut, 3),
                "почему": f"муть={mut:.2f} — рабочий такт, ровно"}

    # ── Сильная муть, но ещё держится ─────────────────────────
    if mut < 0.8:
        return {"mode": "SAFE", "муть": round(mut, 3),
                "почему": f"муть={mut:.2f} — призму мутит, осторожно, не рисковать"}

    # ── Призму залило ─────────────────────────────────────────
    return {"mode": "RECOVERY", "муть": round(mut, 3),
            "почему": f"муть={mut:.2f} — залито вчерашним, эту сессию пропустить"}


# Строит ли режим план на такт? RECOVERY — нет (не до планов).
_PLANIRUET = {"GENIUS", "NORMAL", "SAFE"}


def stroit_plan(mode: str) -> bool:
    """RECOVERY-единица план не строит — ей бы выжить, не творить."""
    return mode in _PLANIRUET


