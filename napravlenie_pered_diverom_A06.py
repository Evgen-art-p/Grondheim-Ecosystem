# Кладётся в КОРЕНЬ репозитория, рядом с main.py.
# Запуск из PowerShell, из корня:
#     python napravlenie_pered_diverom_A06.py
#
# ═══ ЧТО НАШЛОСЬ ═══
#
# В прогоне 16.09 Синди сделала 17 входов — ВСЕ SHORT, на растущем
# евро. И на каждом писала «дивергенция по AO» одной и той же фразой.
#
# А вот чего в её словах нет НИ РАЗУ за все 17: растёт цена или
# падает. Направление не названо ни в одном входе.
#
# Троица в бумаге названа ВЕРНО, и будильник из неё выведен верно:
# НЕКРОН — не факт из трёх, а сигнал начать смотреть; условия — ход
# цены, дивер AO, приседающий. Сломано другое.
#
# ХОД И ДИВЕР СТОЯЛИ КАК ДВА ОТДЕЛЬНЫХ ФАКТА. Между ними не было
# связи. А связь и есть главное:
#
#     направление говорит, ГДЕ ИСКАТЬ ДИВЕР.
#     Цена растёт — сравниваем вершины.
#     Цена падает — сравниваем впадины.
#
# Слово Шефа: «тебе дивер нужно искать, значит знать нужно направление
# цены». Без направления сравнивать нечего — не «трудно решить», а
# нечего даже посмотреть: неизвестно, вершины брать или впадины.
#
# Оттого «дивергенция по AO» и объявлялась 17 раз подряд, ничем не
# подтверждённая: две точки не выбраны, потому что не задана сторона.
#
# И ВТОРОЕ: в примерах отказа хода не было. «Дивера нет» — причина,
# «приседающих нет» — причина, а про ход ни слова. Выходило, что
# отказать из-за хода как бы и не полагается.
#
# ═══ ЧТО СТАВИМ ═══
#
# 1. Два пункта связаны в порядок: ход СПЕРВА, дивер ОТ НЕГО. С
#    прямым указанием, какую сторону сравнивать при каком ходе.
# 2. Названо вслух: объявил дивер — скажи, куда шла цена и какие две
#    точки сравнил. Не сказал — дивера нет.
# 3. Ход добавлен в примеры отказа.
#
# ЧЕГО НЕ ДЕЛАЕМ. Воду третьим условием НЕ ставим. Слово Шефа: вода
# просто показывает текущее направление, она не разрешает и не
# запрещает. Ставить её условием — та же подмена, что была с
# будильником, только наоборот.
#
# Только A06. Файл знаний AO.md не трогаем: там верно сказано, ЧТО
# сравнивать (вершину с вершиной, дно с дном), не хватало только
# КАК ВЫБРАТЬ СТОРОНУ — это и дописывается здесь, в задании.
#
# БЕЗОПАСНО. Правит только текст задания, ни строчки кода. Рядом
# кладёт промпт.md.bak_napravlenie.
# Запускать можно сколько угодно раз.

import shutil
import sys
from pathlib import Path

KOREN = Path(__file__).resolve().parent
MARKER = "<!-- NAPRAVLENIE_PERED_DIVEROM_V1 -->"

PUT = (KOREN / "GRONDHEIM_CITY" / "Биржа" / "цеха" / "торговый_хаос"
       / "слоты" / "A06" / "промпт.md")

STAROE_1 = (
    "**ЦЕНА — ход.** Растут фракталы-хаи и фракталы-лои или падают —\n"
    "молодой ход или выдохшийся (`TREND_PO_TSENE.md`).\n"
    "\n"
    "**AO — дивер.** Самый выраженный горб или яма против следующего,\n"
    "пока цена продолжает: меньше прежнего — дивер (`AO.md`).\n"
)

NOVOE_1 = (
    "**ЦЕНА — ход. СМОТРИТСЯ ПЕРВЫМ.** Растут фракталы-хаи и\n"
    "фракталы-лои или падают — молодой ход или выдохшийся\n"
    "(`TREND_PO_TSENE.md`).\n"
    "\n"
    "Первым — не для порядка. Направление говорит, ГДЕ ИСКАТЬ ДИВЕР:\n"
    "\n"
    "    цена РАСТЁТ  → сравниваем ВЕРШИНЫ: новый максимум выше\n"
    "                   прежнего, а горб AO ниже прежнего горба\n"
    "    цена ПАДАЕТ  → сравниваем ВПАДИНЫ: новый минимум ниже\n"
    "                   прежнего, а яма AO мельче прежней\n"
    "\n"
    "Не знаешь направления — сравнивать нечего. Не «трудно решить», а\n"
    "нечего даже посмотреть: неизвестно, вершины брать или впадины.\n"
    "\n"
    "**AO — дивер. ИЩЕТСЯ ПО ТОЙ СТОРОНЕ, КОТОРУЮ ДАЛ ХОД.** Самый\n"
    "выраженный горб или яма против следующего, пока цена продолжает:\n"
    "меньше прежнего — дивер (`AO.md`).\n"
    "\n"
    "Объявил дивер — скажи, КУДА ШЛА ЦЕНА и КАКИЕ ДВЕ ТОЧКИ ты сравнил.\n"
    "«Дивергенция по AO» само по себе — не наблюдение, а слово. Не\n"
    "назвал сторону и две точки — дивера у тебя нет.\n"
)

STAROE_2 = (
    "**Отказываешься — НАЗОВИ, ЧЕГО НЕ ХВАТИЛО.** Одной из трёх. «Дивера\n"
    "нет» — причина. «Приседающих нет» — причина. «Нет чёткого сигнала» —\n"
    "не причина, такой отказ не принимается.\n"
)

NOVOE_2 = (
    "**Отказываешься — НАЗОВИ, ЧЕГО НЕ ХВАТИЛО.** Одной из трёх. «Ход\n"
    "не читается, фракталы вразнобой» — причина. «Дивера нет» —\n"
    "причина. «Приседающих нет» — причина. «Нет чёткого сигнала» — не\n"
    "причина, такой отказ не принимается.\n"
)


def podozhdat():
    """Чтобы окно не захлопнулось при запуске двойным кликом."""
    try:
        input("\nГотово. Нажми Enter, чтобы закрыть окно.")
    except Exception:
        pass


def nayti():
    """Ищет задание Синди сам. Руками путь прописывать не надо."""
    if PUT.exists():
        return PUT
    musor = ("_ARCHIVE", "_OLD", "_АРХИВ", "_УБОРКА", ".bak")
    nashlos = [p for p in KOREN.rglob("промпт.md")
               if "A06" in str(p) and not any(m in str(p) for m in musor)]
    if len(nashlos) == 1:
        print(f"Нашёл: {nashlos[0]}")
        return nashlos[0]
    if len(nashlos) > 1:
        print("Нашёл несколько заданий A06:")
        for nomer, p in enumerate(nashlos, 1):
            print(f"  {nomer}. {p}")
        otvet = input("Какое правим? номер: ").strip()
        if otvet.isdigit() and 1 <= int(otvet) <= len(nashlos):
            return nashlos[int(otvet) - 1]
    return None


def main():
    put = nayti()
    if put is None:
        print("✗ не нашёл задание A06 — запускай из корня репозитория")
        return 1

    tekst = put.read_text(encoding="utf-8")

    if MARKER in tekst:
        print("· уже сделано")
        return 0

    pravki = [(STAROE_1, NOVOE_1), (STAROE_2, NOVOE_2)]
    for nomer, (staroe, _) in enumerate(pravki, 1):
        if tekst.count(staroe) != 1:
            print(f"✗ правка {nomer}: нашёл {tekst.count(staroe)} мест "
                  f"вместо одного. Ничего не тронул.")
            print("  Скажи Брату, поправим по месту.")
            return 1

    novyy = tekst
    for staroe, novoe in pravki:
        novyy = novyy.replace(staroe, novoe, 1)
    novyy = novyy.rstrip("\n") + "\n" + MARKER + "\n"

    kopiya = put.with_suffix(put.suffix + ".bak_napravlenie")
    if not kopiya.exists():
        shutil.copy2(put, kopiya)
        print(f"  (копия старого: {kopiya.name})")
    put.write_text(novyy, encoding="utf-8")

    print("✓ направление встало перед дивером:")
    print("    · ход смотрится первым — он говорит, где искать дивер")
    print("    · растёт цена — вершины, падает — впадины")
    print("    · объявил дивер — назови сторону и две точки")
    print("    · ход добавлен в причины отказа")
    print()
    print("Перезапусти Кабинет (main.py) и запусти прогон.")
    print("Смотреть в её словах одно: называет ли она, КУДА ШЛА ЦЕНА.")
    print("Раньше — ни разу из семнадцати входов.")
    return 0


if __name__ == "__main__":
    kod = main()
    podozhdat()
    sys.exit(kod)
