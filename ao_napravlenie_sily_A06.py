# Кладётся в КОРЕНЬ репозитория, рядом с main.py.
# Запуск из PowerShell, из корня:
#     python ao_napravlenie_sily_A06.py
#
# ЗАЧЕМ. Слово Шефа 16.09: «самый большой AO в 3 волне, AO уходит к нулю,
# потом растёт — уход к нулю не показатель, а НАПРАВЛЕНИЕ».
#
# Что было сломано в знании. Файл говорил, ЧТО ТАКОЕ дивер (цена ушла
# дальше, а горб меньше прежнего), но нигде не говорил, что такое ОДИН
# горб. Для трейдера вся гистограмма была одним сплошным предметом с
# биографией — и он пересказывал её путь: «был в минусе, поднялся,
# сейчас опускается». Сравнивать было нечего, потому что не дали, чем
# делить.
#
# Что встаёт вместо. Гистограмма читается по НАПРАВЛЕНИЮ силы: растёт
# или падает. Ноль ничего не меряет — дошёл, пересёк, встал на полпути,
# всё равно. Горб — один ход силы вверх целиком, яма — вниз. Цвет —
# способ увидеть направление, а не отдельное правило; одиночный столбик
# другого цвета внутри хода — рябь.
#
# БЕЗОПАСНО. Ничего не дописывает вслепую: сначала проверяет, что нашёл
# оба края старого куска. Рядом кладёт копию AO.md.bak_napravlenie.
# Запускать можно сколько угодно раз: второй запуск скажет «уже сделано».

import shutil
import sys
from pathlib import Path

KOREN = Path(__file__).resolve().parent
PUT = (KOREN / "GRONDHEIM_CITY" / "Биржа" / "цеха" / "торговый_хаос"
       / "слоты" / "A06" / "знания" / "AO.md")

MARKER = "<!-- AO_NAPRAVLENIE_SILY_V1 -->"

# Края старого куска. Режем от первого до второго, второй остаётся.
KRAY_NACHALO = "Столбики над нулём и под нулём — горбы и провалы."
KRAY_KONEC = "<!-- ZNANIYA_PERVOGO_UROVNYA_A06_V1 -->"

NOVOE = """Столбики над нулём и под нулём. Их величина — сила толчка.

## Направление силы

Смотреть на гистограмму надо не по столбикам, а по направлению: сила
сейчас растёт или падает.

После сильного хода AO идёт к нулю — и не обязательно доходит. Дойдёт,
пересечёт, остановится на полпути — неважно, мерить тут нечего. Важно,
что сила пошла вниз. Потом она снова растёт — это уже новый горб.

Цвет столбика — способ увидеть направление. Красные идут вниз, зелёные
вверх. Величина тут ни при чём: столбик может быть огромным и красным.
Одиночный столбик другого цвета внутри хода — рябь, направление от
него не меняется.

Горб — это один ход силы вверх целиком, от разворота до разворота.
Яма — один ход вниз. Ноль в счёт не идёт: горб может целиком лежать
под нулём, ямой он от этого не станет.

## Дивергенция

Дивергенция — это не ослабление отдельных столбиков AO.

Это расхождение: цена продолжает движение и обновляет край, а сила за
ней уже не поспевает — новый горб ниже прежнего, новая яма мельче
прежней.

Сравнивают однородное: вершину горба с вершиной прошлого горба, дно
ямы с дном прошлой ямы. Горб против ямы — не сравнение.

На одной картинке таких расхождений может быть несколько — от больших
до совсем маленьких. Они не требуют отдельного разбора.

Пересказать путь AO — не то же самое, что увидеть дивер. «Был в
минусе, поднялся, опускается» — это рассказ про один прибор. В дивере
всегда двое: цена и сила.

"""


def podozhdat():
    """Чтобы окно не захлопнулось при запуске двойным кликом."""
    try:
        input("\nГотово. Нажми Enter, чтобы закрыть окно.")
    except Exception:
        pass


def nayti():
    """Ищет знание само. Руками путь прописывать не надо."""
    if PUT.exists():
        return PUT
    musor = ("_ARCHIVE", "_OLD", "_АРХИВ", "_УБОРКА", ".bak")
    nashlos = [p for p in KOREN.rglob("AO.md")
               if not any(m in str(p) for m in musor)]
    if len(nashlos) == 1:
        print(f"Нашёл: {nashlos[0]}")
        return nashlos[0]
    if len(nashlos) > 1:
        print("Нашёл несколько AO.md:")
        for nomer, put in enumerate(nashlos, 1):
            print(f"  {nomer}. {put}")
        otvet = input("Какой правим? номер: ").strip()
        if otvet.isdigit() and 1 <= int(otvet) <= len(nashlos):
            return nashlos[int(otvet) - 1]
    return None


def main():
    put = nayti()
    if put is None:
        print("✗ не нашёл AO.md — запускай из корня репозитория")
        return 1

    tekst = put.read_text(encoding="utf-8")

    if MARKER in tekst:
        print("· уже сделано")
        return 0

    i = tekst.find(KRAY_NACHALO)
    j = tekst.find(KRAY_KONEC)
    if i < 0 or j < 0 or j <= i:
        print("✗ не нашёл ожидаемое место — знание могло измениться.")
        print("  Ничего не тронул. Покажи AO.md Брату, поправим по месту.")
        return 1

    novyy = tekst[:i] + NOVOE + tekst[j:]
    if not novyy.rstrip().endswith(">"):
        print("✗ хвост файла выглядит не так, как ожидалось. Ничего не пишу.")
        return 1
    novyy = novyy.rstrip("\n") + "\n" + MARKER + "\n"

    kopiya = put.with_suffix(put.suffix + ".bak_napravlenie")
    if not kopiya.exists():
        shutil.copy2(put, kopiya)
        print(f"  (копия старого: {kopiya.name})")
    put.write_text(novyy, encoding="utf-8")

    print("✓ AO переписан:")
    print("    · гистограмма читается по направлению силы, не по столбикам")
    print("    · ноль перестал быть меркой — он показывает, куда идёт сила")
    print("    · горб и яма названы как один ход целиком")
    print("    · цвет объяснён как способ увидеть направление, рябь названа")
    print("    · добавлено: пересказ пути AO — не дивер")
    print()
    print("Перезапусти Кабинет (main.py) и прогони Илью по живому кадру.")
    print("Смотреть надо одно: назовёт он ДВЕ точки или снова расскажет путь.")
    return 0


if __name__ == "__main__":
    kod = main()
    podozhdat()
    sys.exit(kod)
