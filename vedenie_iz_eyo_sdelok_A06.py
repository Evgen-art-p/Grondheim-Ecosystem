def podozhdat():
    try:
        input("\nГотово. Нажми Enter, чтобы закрыть окно.")
    except Exception:
        pass


def nayti():
    if PUT.exists():
        return PUT
    musor = ("_ARCHIVE", "_OLD", "_АРХИВ", "_УБОРКА", ".bak")
    nash = [p for p in KOREN.rglob("промпт.md")
            if "A06" in str(p) and not any(m in str(p) for m in musor)]
    if len(nash) == 1:
        print(f"Нашёл: {nash[0]}")
        return nash[0]
    if len(nash) > 1:
        print("Нашёл несколько заданий A06:")
        for n, p in enumerate(nash, 1):
            print(f"  {n}. {p}")
        o = input("Какое правим? номер: ").strip()
        if o.isdigit() and 1 <= int(o) <= len(nash):
            return nash[int(o) - 1]
    return None


def main():
    put = nayti()
    if put is None:
        print("✗ не нашёл задание A06 — запускай из корня репозитория")
        return 1

    tekst = put.read_text(encoding="utf-8")
    if MARKER in tekst:
        print("· уже сделано")
        return 0

    if "VEDENIE_GLAZOM_V1" not in tekst:
        print("✗ сперва накати vedenie_glazom_A06.py — этот идёт следом.")
        return 1

    pravki = [(STAROE_1, NOVOE_1), (STAROE_2, NOVOE_2)]
    for n, (s, _) in enumerate(pravki, 1):
        if tekst.count(s) != 1:
            print(f"✗ правка {n}: нашёл {tekst.count(s)} мест вместо одного.")
            if n == 2 and "VYHOD_PO_DVUM_V1" in tekst:
                print("  Похоже, накатан vyhod_i_sorazmerno — он уже поменял")
                print("  это место. Скажи Брату, сведу оба.")
            print("  Ничего не тронул.")
            return 1

    novyy = tekst
    for s, nn in pravki:
        novyy = novyy.replace(s, nn, 1)
    novyy = novyy.rstrip("\n") + "\n" + MARKER + "\n"

    kopiya = put.with_suffix(put.suffix + ".bak_vedenie_ona")
    if not kopiya.exists():
        shutil.copy2(put, kopiya)
        print(f"  (копия старого: {kopiya.name})")
    put.write_text(novyy, encoding="utf-8")

    print("✓ ведение выведено из её сделок:")
    print("    · в плюсе увидела встречный разворотник с приседающим —")
    print("      закрывается, дивера не ждёт")
    print("    · её же слова из сделок 182 и 156 как пример")
    print("    · сигнал в нуле — шум, держать")
    print("    · про стоп сказана правда: его ведёт код за Зубами")
    print("    · переворот без изменений")
    print()
    print("Перезапусти Кабинет (main.py) и прогони ТОТ ЖЕ отрезок 2025.")
    print("Считать: CLOSE должен появиться (сейчас 0), а крупные ходы —")
    print("закрываться ближе к пику, а не на откате.")
    return 0


if __name__ == "__main__":
    kod = main()
    podozhdat()
    sys.exit(kod)
