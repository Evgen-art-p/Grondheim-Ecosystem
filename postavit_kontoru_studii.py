def _teper() -> str:
    return datetime.now().strftime("%Y%m%d_%H%M%S")


def naiti_koren() -> Path:
    """Корень репо по стабильным ориентирам, что были до патча."""
    starty = [Path(__file__).resolve().parent, Path.cwd().resolve()]
    for start in starty:
        for kand in [start, *start.parents]:
            if (kand / "GRONDHEIM_CITY" / "локации").is_dir() \
                    and (kand / "ГОРОД" / "rabota.py").is_file():
                return kand
    raise SystemExit(
        "Не нашёл корень репо.\n"
        "Ищу папку, где рядом лежат GRONDHEIM_CITY/локации и ГОРОД/rabota.py.\n"
        "Запусти патч из корня Grondheim-Ecosystem."
    )


def polozhit_manifest(put: Path, dannye: dict) -> str:
    """Кладём манифест. Совпал — молчим. Отличается — старый в .bak."""
    novyy = json.dumps(dannye, ensure_ascii=False, indent=2) + "\n"
    if put.exists():
        staryy = put.read_text(encoding="utf-8")
        if staryy == novyy:
            return "уже стоит, не трогал"
        bak = put.with_suffix(put.suffix + f".bak_{_teper()}")
        shutil.copyfile(put, bak)
        put.write_text(novyy, encoding="utf-8")
        return f"обновлён, старый в {bak.name}"
    put.parent.mkdir(parents=True, exist_ok=True)
    put.write_text(novyy, encoding="utf-8")
    return "создан"


def proverit_skanerom(koren: Path) -> None:
    """Спрашиваем сам город: видит он контору или нет.

    Зовём kartridzhi() из ГОРОД/rabota.py — тот самый сканер, которым
    живёт весь город. Если он контору не увидел, значит манифест лёг
    не туда или не так, и лучше узнать это сейчас.
    """
    import importlib.util

    put = koren / "ГОРОД" / "rabota.py"
    try:
        spec = importlib.util.spec_from_file_location("_rabota_probe", put)
        if spec is None or spec.loader is None:
            print("  · сканер не завёлся (не смог загрузить rabota.py)")
            return
        mod = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(mod)  # type: ignore[union-attr]
    except Exception as e:
        print(f"  · сканер не завёлся: {e}")
        print("    (не страшно — проверь глазами в кабинете)")
        return

    try:
        vse = mod.kartridzhi()
    except Exception as e:
        print(f"  · kartridzhi() споткнулась: {e}")
        return

    nashi = [k for k in vse if k.get("папка_квартала") == "Студия"]
    print(f"  · сканер города видит цехов всего: {len(vse)}")
    if not nashi:
        print("  · КОНТОРУ НЕ ВИДИТ — разбираемся, дальше не идём")
        return
    for k in nashi:
        sloty = ", ".join(s.get("слот", "?") for s in k.get("слоты", []))
        print(f"  · Студия/{k['цех']} → здание {k.get('здание') or '—'}, "
              f"места: {sloty}")

    try:
        mesta = [m for m in mod.mesta() if m.get("цех") == "контора"]
        print(f"  · мест-вакансий по конторе: {len(mesta)}")
        for m in mesta:
            kto = m.get("кто_сидит") or "вакантно"
            print(f"      {m['id']} · {m['название']} · {kto}")
    except Exception as e:
        print(f"  · mesta() споткнулась: {e}")


