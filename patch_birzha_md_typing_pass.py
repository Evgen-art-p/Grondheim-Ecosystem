def main():
    if not TARGET.exists():
        print(f"НЕ НАЙДЕН: {TARGET} (запусти из корня Grondheim-Ecosystem)")
        sys.exit(1)

    src = TARGET.read_text(encoding="utf-8")

    if MARKER in src:
        print("Уже применено — идемпотентность держит, ничего не меняю.")
        return

    missing = []
    if OLD_TABLE_ROW not in src:
        missing.append("строка таблицы tester_express.py")
    if OLD_ANCHOR not in src:
        missing.append("якорь перед §8 (Где что лежит)")

    if missing:
        print("⚠️  Не нашёл фрагменты (файл менялся с момента диагностики):")
        for m in missing:
            print("   ", m)
        print("Ничего не режу — правь руками или пришли свежий БИРЖА.md.")
        sys.exit(1)

    backup = TARGET.with_suffix(f".md.bak_{datetime.now():%Y%m%d_%H%M%S}")
    shutil.copy2(TARGET, backup)
    print(f"Бэкап: {backup}")

    src = src.replace(OLD_TABLE_ROW, NEW_TABLE_ROW, 1)
    src = src.replace(OLD_ANCHOR, NEW_SECTION, 1)
    src += f"\n<!-- {MARKER} -->\n"

    TARGET.write_text(src, encoding="utf-8")
    print("Готово: БИРЖА.md обновлён — §5 строка + новый §7а (гигиена типов).")


if __name__ == "__main__":
    main()
