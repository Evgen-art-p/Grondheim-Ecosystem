def pravit(put: Path, zameny, hvost: str = "") -> str:
    if not put.is_file():
        return "мимо: файла нет"
    text = put.read_text(encoding="utf-8")
    if MARKER in text:
        return "уже"
    for staroe, _ in zameny:
        n = text.count(staroe)
        if n != 1:
            kusok = staroe.strip().splitlines()[0][:50]
            return f"мимо: якорь «{kusok}…» встретился {n} раз"
    novyy = text
    for staroe, novoe in zameny:
        novyy = novyy.replace(staroe, novoe, 1)
    if hvost:
        novyy = novyy.rstrip("\n") + "\n" + hvost
    novyy = novyy.rstrip("\n") + f"\n\n# {MARKER} - marker\n"
    try:
        ast.parse(novyy)
    except SyntaxError as e:
        return f"мимо: правка ломает синтаксис ({e.lineno}: {e.msg})"
    if SUHO:
        return "сделано (сухой прогон)"
    put.with_name(put.name + f".bak_volnamassh_{SHTAMP}").write_text(
        text, encoding="utf-8")
    put.write_text(novyy, encoding="utf-8")
    return "сделано"


def zhdat_i_vyyti(kod=0):
    try:
        input("\nEnter — закрыть окно...")
    except EOFError:
        pass
    sys.exit(kod)


