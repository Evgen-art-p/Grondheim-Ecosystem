# -*- coding: utf-8 -*-
# STARSHIY_NE_VOROTA_V1
"""
СТАРШИЙ ЭТАЖ УХОДИТ ИЗ ВОРОТ. ХОЧЕТ ПОНЯТЬ — ПУСТЬ ПОТОМ ИЩЕТ.

Слово Шефа 09.09:

> Ведь компас на старший этаж тормозит его — будет всё его искать…
> Вот потом хочет понять, пусть после ищет.

═══ ЧТО БЫЛО НЕ ТАК ═══

Старший этаж стоял ШАГОМ ВТОРЫМ, до собственного поля. Из-за этого:

  · не пришёл этаж — «компаса нет», и трейдер наполовину парализован
    (живой лог 09.09: «⚠ компаса нет: старший этаж M30 не пришёл»);
  · пришёл — он подгоняет под него свой ход: «на старшем медвежий,
    значит в лонг рано», хотя ход на ЕГО этаже мог кончиться.

То есть компас не помогал выбрать, а ОТМЕНЯЛ собственное решение.
Трейдер искал разрешения снаружи вместо того, чтобы смотреть на свой
ход. То же зеркало, что и раньше, только отражало не слова Шефа, а
чужой этаж.

**А по канону старший этаж для входа и не нужен.** Место — конец хода,
а конец виден там, где ход обведён. Старший этаж — это про МАСШТАБ (не
влез ход в кадр — поднимись), то есть про выбор этажа, а не про
разрешение войти.

═══ ЧТО ПАТЧ ДЕЛАЕТ ═══

Шаг «старший этаж» вынимается из порядка взгляда и переносится ПОСЛЕ
шагов — как справка по желанию. Оставлено ровно то, что верно:
подняться значит взять рукой; «не смотрел» — законный ответ; назвать
этаж, которого не запрашивал, — то же, что выдумать цену.

Шаги перенумерованы: было 1 цена → 2 старший → 3 своё поле → 4 компас.
Стало **1 цена → 2 своё поле → 3 компас**.

═══ ЧЕГО ПАТЧ НЕ ДЕЛАЕТ ═══

Ничего не выбрасывает: старший этаж остаётся доступен рукой и остаётся
нужен для выбора масштаба. Не трогает закон входа, спреды, стоп,
правило трёх, формат ответа, руки.

Запускать из корня репозитория:
    python postavit_starshiy_ne_vorota.py

Идемпотентен (маркер STARSHIY_NE_VOROTA_V1). Рядом .bak.
"""
from __future__ import annotations
from pathlib import Path

MARKER = "STARSHIY_NE_VOROTA_V1"
BAZA = "GRONDHEIM_CITY/Биржа/цеха/торговый_хаос/слоты"
SLOTY = ("A06", "A07", "A08")


# ── 1) вынуть шаг 2 из порядка ──────────────────────────────────────
SHAG2_OLD = """**Шаг 2 — старший этаж.** Один вопрос каждый раз: то, что ты видишь на
своём этаже сейчас, — это импульс старшей структуры или её откат? Не
видно тренда вовсе — поднимись на этаж-два выше и спроси то же самое
там же.

Подняться — значит ВЗЯТЬ РУКОЙ. Перед тобой кадр только твоего
рабочего этажа; недельки и дневки на нём нет и быть не может. Нужны —
позови `pokazat_etazh` или `stol_na_etazhe`. Не позвал — ты про них
ничего не знаешь, и знать неоткуда.

**Не сходил — так и скажи: «старший не смотрел».** Это законный ответ,
ровно такой же законный, как «работы не вижу». Никто не ждёт от тебя
знания обо всех этажах на каждом взгляде.

А назвать старший этаж, которого не запрашивал, — то же самое, что
выдумать цену. Ты не ошибёшься — ты соврёшь, и по этому вранью потом
будет принято решение.

<!-- STARSHIY_TOLKO_RUKOY_V1 -->

**Шаг 3 — своё поле.**"""

SHAG2_NEW = """**Шаг 2 — своё поле.**"""


# ── 2) перенумеровать шаг 4 ─────────────────────────────────────────
SHAG4_OLD = """**Шаг 4 — компас, последним.**"""

SHAG4_NEW = """**Шаг 3 — компас, последним.**"""


# ── 3) старший этаж — после шагов, как справка ──────────────────────
ZAKON_OLD = """## ЗАКОН ВХОДА"""

ZAKON_NEW = """## СТАРШИЙ ЭТАЖ — ПОСЛЕ, И ТОЛЬКО ЕСЛИ САМ ЗАХОЧЕШЬ

Старший этаж НЕ ворота. Он не даёт и не отнимает разрешения войти:
место — конец хода, а конец виден там, где ты этот ход обвёл.

Он нужен для другого — для МАСШТАБА. Ход не влезает в твой кадр —
поднимись; занял три бара — спустись. И ещё он пригодится ПОСЛЕ входа,
когда ведёшь и прикидываешь, сколько ещё можно пройти.

Захотел посмотреть — **подняться значит ВЗЯТЬ РУКОЙ**. Перед тобой
кадр только твоего этажа; недельки и дневки на нём нет и быть не
может. Нужны — позови `pokazat_etazh` или `stol_na_etazhe`. Не позвал —
ты про них ничего не знаешь, и знать неоткуда.

**Не сходил — так и скажи: «старший не смотрел».** Это законный ответ,
ровно такой же законный, как «работы не вижу». Никто не ждёт от тебя
знания обо всех этажах на каждом взгляде, и ждать чужого этажа, чтобы
решиться, тоже не надо.

А назвать старший этаж, которого не запрашивал, — то же самое, что
выдумать цену. Ты не ошибёшься — ты соврёшь, и по этому вранью потом
будет принято решение.

<!-- STARSHIY_TOLKO_RUKOY_V1 -->

---

## ЗАКОН ВХОДА"""


PRAVKI = [
    ("шаг 2 вынут из порядка", SHAG2_OLD, SHAG2_NEW),
    ("шаг 4 → шаг 3", SHAG4_OLD, SHAG4_NEW),
    ("старший этаж как справка", ZAKON_OLD, ZAKON_NEW),
]


def main() -> None:
    root = Path(__file__).resolve().parent
    fayly = [(root / BAZA / s / "промпт.md", s) for s in SLOTY]

    net = [f for f, _ in fayly if not f.exists()]
    if net:
        print("НЕ НАШЁЛ файлы (запускать из корня репозитория):")
        for f in net:
            print("   ", f)
        return

    plan, uzhe, bracket = [], [], []
    for f, slot in fayly:
        t = f.read_text(encoding="utf-8")
        if MARKER in t:
            uzhe.append(slot)
            continue
        novyy, ploho = t, None
        for imya, old, new in PRAVKI:
            if novyy.count(old) != 1:
                ploho = f"«{imya}» — совпадений {novyy.count(old)} (нужно 1)"
                break
            novyy = novyy.replace(old, new, 1)
        if ploho:
            bracket.append((slot, ploho))
            continue
        plan.append((f, slot, t,
                     novyy.rstrip("\n") + f"\n\n<!-- {MARKER} -->\n"))

    if uzhe and not plan and not bracket:
        print("уже накачен во всех бумагах — ничего не трогаю")
        return

    if bracket:
        print("⚠ Файлы отличаются от ожидаемого — НИЧЕГО не меняю:")
        for slot, prichina in bracket:
            print(f"   {slot}: {prichina}")
        print("\nПришли Брату эти бумаги — доведу под них.")
        return

    for f, slot, staroe, novoe in plan:
        bak = f.with_suffix(f.suffix + ".bak_starshiy_ne_vorota")
        if not bak.exists():
            bak.write_text(staroe, encoding="utf-8")
        f.write_text(novoe, encoding="utf-8")
        print(f"✔ {slot}/промпт.md — старший этаж вышел из ворот")

    if uzhe:
        print("(пропущены, уже накачены: " + ", ".join(uzhe) + ")")

    print("\nПорядок взгляда теперь короче:")
    print("  1 — голая цена · 2 — своё поле · 3 — компас последним")
    print("\nСтарший этаж — отдельным разделом ПОСЛЕ, как справка:")
    print("нужен для масштаба и для ведения, не для разрешения войти.")
    print("\nЧто должно измениться: «компаса нет, старший не пришёл»")
    print("перестанет быть событием — ждать было нечего.")


if __name__ == "__main__":
    main()
