from __future__ import annotations
from pathlib import Path

MARKER = "IDTI_S_HODOM_V1"
BAZA = "GRONDHEIM_CITY/Биржа/цеха/торговый_хаос/слоты"
SLOTY = ("A06", "A07", "A08")


# ── 1) рамка: идти с ходом ──────────────────────────────────────────
RAMKA_OLD = """Смотришь по шагам, не вперемешку — порядок важнее, чем список фактов."""

RAMKA_NEW = """**Твоя работа — идти с ходом.** Не угадывать, куда пойдёт рынок, и не
искать сигнал. Видеть, где ход сейчас.

Первый вопрос всегда один: **иду я с чем-нибудь или нет?** Цена
топчется, линии переплелись, идти не с чем — так и скажи, на этом
всё. Нет хода — нечему и кончаться.

Есть ход — назови его: вот это движение, началось там, идёт оттуда
досюда. Пока не назвал, понимать нечего. Дальше смотри, где он:
только начался, в разгаре или уже тянется из последних сил.

Какая это волна по счёту, C она или не C, импульс или коррекция —
**сейчас не спрашивается.** Важно одно: ход кончился или нет. Разметка
и номера пригодятся ПОСЛЕ входа, когда будешь вести и прикидывать,
сколько ещё можно пройти. До входа они только сбивают.

Смотришь по шагам, не вперемешку — порядок важнее, чем список фактов."""


# ── 2) убрать счёт изломов из шага 3 ────────────────────────────────
IZLOMY_OLD = """уже ВНУТРИ выбранного тобой движения, не отдельно от него. Считаются
изломы от точки до тебя, три их уже или нет, без порогов — рынок
нелинейный. Слом точки"""

IZLOMY_NEW = """уже ВНУТРИ выбранного тобой движения, не отдельно от него. Слом точки"""


# ── 3) некрон как вопрос — в шаг 4 ──────────────────────────────────
NEKRON_OLD = """**Шаг 4 — компас, последним.** Аллигатор про тренд, AO про волну, MFI
про сам последний закрытый бар. Они подтверждают то, что ты уже увидел
на цене — не наоборот. Прибор спорит с глазом — прав глаз."""

NEKRON_NEW = """**Шаг 4 — компас, последним.** Аллигатор про тренд, AO про волну, MFI
про сам последний закрытый бар. Они подтверждают то, что ты уже увидел
на цене — не наоборот. Прибор спорит с глазом — прав глаз.

**Разворотный бар — это ВОПРОС, а не событие.** Он значит одно: цену
сводили далеко и вернули. А что это значит — решает то, ГДЕ он стоит.

Ход молодой, AO только пошёл, сил полно — некрон это **передышка**.
Цена остановилась перевести дух, дальше пойдёт. Спи, жди следующего.

Ход выдохся — горбы мельчают, а цена всё лезет за край — тот же самый
некрон становится **местом**. Не потому что он изменился, а потому что
изменилось всё вокруг него.

Приседающий бар читается в паре с ним так же: в молодом ходе набирают,
сейчас пойдут; в выдохшемся толкают, а не идёт. Один и тот же столбик,
разный смысл.

**Дивер тоже не команда разворачиваться.** Он говорит только, что
импульс кончается: место близко. Отдышится и пойдёт дальше или
развернётся — покажет рынок, не прибор. Ложных диверов не бывает, и
считать их не надо.

**Не взяло — значит ход ещё не кончился.** Это не ошибка и не приговор:
смотри дальше и жди следующего места. Вход — не событие, которое надо
заслужить, это вопрос рынку, и стоп — цена ответа."""


# ── 4) три места входа → одно ───────────────────────────────────────
MESTA_OLD = """Про входы главное: их три, они лежат рядом, и ни одно не закреплено за
тобой. Одно — на конце коррекции, самое раннее и самое дорогое. Второе —
по первой волне нового движения, без подтверждения. Третье — в конце
первого отката ОТ этой волны, позже и дешевле по риску. Что ты ждёшь и чем
платишь за каждое — написано в знаниях, читай там.

Выбираешь ты, и выбор от раза к разу может быть разным — это твоё
право, а не сбой."""

MESTA_NEW = """Про входы главное: **место одно — конец хода.** Раньше ты его возьмёшь
или позже — это про твой вкус к риску, а не разные фигуры с разными
именами. Чем раньше вход, тем дороже и тем больше нужно смелости; чем
позже, тем дешевле и тем меньше остаётся хода. В знаниях расписано, что
ты ждёшь и чем платишь за каждый — читай там.

Выбираешь ты, и выбор от раза к разу может быть разным — это твоё
право, а не сбой."""


PRAVKI = [
    ("рамка «идти с ходом»", RAMKA_OLD, RAMKA_NEW),
    ("счёт изломов убран", IZLOMY_OLD, IZLOMY_NEW),
    ("некрон как вопрос", NEKRON_OLD, NEKRON_NEW),
    ("три места → одно", MESTA_OLD, MESTA_NEW),
]


def main() -> None:
    root = Path(__file__).resolve().parent
    fayly = [(root / BAZA / s / "промпт.md", s) for s in SLOTY]

    net = [f for f, _ in fayly if not f.exists()]
    if net:
        print("НЕ НАШЁЛ файлы (запускать из корня репозитория):")
        for f in net:
            print("   ", f)
        return

    plan, uzhe, bracket = [], [], []
    for f, slot in fayly:
        text = f.read_text(encoding="utf-8")
        if MARKER in text:
            uzhe.append(slot)
            continue
        novyy, ploho = text, None
        for imya, old, new in PRAVKI:
            if novyy.count(old) != 1:
                ploho = f"«{imya}» — совпадений {novyy.count(old)} (нужно 1)"
                break
            novyy = novyy.replace(old, new, 1)
        if ploho:
            bracket.append((slot, ploho))
            continue
        novyy = novyy.rstrip("\n") + f"\n\n<!-- {MARKER} -->\n"
        plan.append((f, slot, text, novyy))

    if uzhe and not plan and not bracket:
        print("уже накачен во всех бумагах — ничего не трогаю")
        return

    if bracket:
        print("⚠ Файлы на диске отличаются от ожидаемого — НИЧЕГО не меняю:")
        for slot, prichina in bracket:
            print(f"   {slot}: {prichina}")
        print("\nПришли Брату эти бумаги — доведу под них.")
        return

    for f, slot, staroe, novoe in plan:
        bak = f.with_suffix(f.suffix + ".bak_idti_s_hodom")
        if not bak.exists():
            bak.write_text(staroe, encoding="utf-8")
        f.write_text(novoe, encoding="utf-8")
        print(f"✔ {slot}/промпт.md — 4 правки легли")

    if uzhe:
        print("(пропущены, уже накачены: " + ", ".join(uzhe) + ")")

    print("\nГотово. Что должно измениться в его ответах:")
    print("  · вместо «входа не вижу» — «мой ход в начале, конца ждать")
    print("    рано» или «ход выдыхается, вот место»;")
    print("  · про некрон посреди хода скажет «передышка», а не")
    print("    «не разворотный, сигнала нет»;")
    print("  · номерами волн до входа сыпать перестанет.")


if __name__ == "__main__":
    main()
