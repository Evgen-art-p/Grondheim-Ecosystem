"""
ОТРЫВ ГЛАЗАМИ НЕ ПРОВЕРЯЮТ · ПАСТЬ ЧИТАЕТСЯ В МАСШТАБЕ

СЛУЧАЙ 10.09. Трейдер сказал: «разворотный бар отмечен, но он ВНУТРИ
пасти, а не оторван от линий. По канону разворотник должен стоять в
стороне от Аллигатора» — и забраковал верный бар.

ПРОВЕРЕНО ПО КОДУ (`williams_core.detect_necron_bar`): условие там
дословно такое — весь бар ЦЕЛИКОМ выше всех трёх линий (для
продажи) или ЦЕЛИКОМ ниже всех трёх (для покупки). Не касается, не
пересекает — целиком, вместе с тенями. Бар внутри переплетения через
эту формулу не проходит НИКОГДА.

Значит отмечен — уже вне пасти. Трейдер глазами проверял то, что
прибор проверил до него, и отказался. Та же болезнь, что была со
«спит — флэт»: бумага велит перепроверять проверенное, и он честно
отказывает.

ВТОРОЕ, слово Шефа: свойства Аллигатора — пасть и ангуляция —
читаются в масштабе, где ход укладывается в 100-140 баров. На кадре,
куда попал случайно, «Аллигатор спит» говорит не про рынок, а про
то, что смотрят не с того этажа.

ЧТО ДЕЛАЕТ ПАТЧ: дописывает в раздел про кадр, к жёлтым стрелкам,
два абзаца — про то, что отрыв уже внутри формулы, и про масштаб.
Ничего не удаляет.

ТРЕБУЕТ: CHTO_NA_KADRE_V1.

БЕЗОПАСНОСТЬ: .bak_pasti, идемпотентен, `--suho` не трогает диск.

    python postavit_nekron_vne_pasti.py --suho
    python postavit_nekron_vne_pasti.py

`шесть·проверено·до·корня`
"""
import shutil
import sys
from pathlib import Path

MARKER = "NEKRON_UZHE_VNE_PASTI_V1"
SUHO = "--suho" in sys.argv

_REPO = Path(__file__).resolve().parent
SLOTY = _REPO / "GRONDHEIM_CITY" / "Биржа" / "цеха" / "торговый_хаос" / "слоты"

YAKOR = '''**Жёлтый кружок.** Обведён последний найденный разворотный бар. Именно
последний, а не сегодняшний: если свежих не было, он может висеть на
вчерашнем и позавчерашнем. Смотри, где он стоит, прежде чем считать
его своим.
'''

DOPISKA = '''
**Отрыв от Аллигатора глазами НЕ проверяют.** Это уже внутри формулы:
разворотным считается только тот бар, что стоит ЦЕЛИКОМ выше всех
трёх линий или ЦЕЛИКОМ ниже всех трёх, вместе с тенями. Бар в
переплетении отмечен не будет никогда. Отмечен — значит оторван, и
перепроверять это не надо. Твой вопрос не «оторван ли», а ГДЕ он
стоит: в молодом ходе или в выдохшемся.

**Пасть и ангуляция читаются только в своём масштабе** — там, где ход
укладывается примерно в 100-140 баров. На кадре, куда ты попал
случайно, «Аллигатор спит» говорит не про рынок, а про то, что ты
смотришь не с того этажа. Не с чего судить о пасти — поднимись и
посмотри, где ход виден целиком.
'''


def _pravka(slot: str) -> int:
    p = SLOTY / slot / "промпт.md"
    if not p.exists():
        print(f"  {slot}: файла нет")
        return 0
    txt = p.read_text(encoding="utf-8")
    if MARKER in txt:
        print(f"  {slot}: уже стоит")
        return 0
    if "CHTO_NA_KADRE_V1" not in txt:
        print(f"  {slot}: ОТКАЗ — сперва postavit_chto_na_kadre.py")
        return -1
    if txt.count(YAKOR) != 1:
        print(f"  {slot}: ОТКАЗ — якорь встречается {txt.count(YAKOR)} раз(а)")
        return 0

    novy = txt.replace(YAKOR, YAKOR + DOPISKA, 1)
    novy = novy.rstrip("\n") + f"\n\n<!-- {MARKER} -->\n"
    if not SUHO:
        shutil.copy2(p, p.with_suffix(".md.bak_pasti"))
        p.write_text(novy, encoding="utf-8")
    print(f"  {slot}: {'готов' if SUHO else 'поправлен'}")
    return 1


def main():
    print()
    print("НЕКРОН УЖЕ ВНЕ ПАСТИ" + ("  · СУХОЙ ПРОГОН" if SUHO else ""))
    print("корень:", _REPO)
    print()
    if not SLOTY.exists():
        print("!! слотов нет — запускать из корня репы")
        return
    vsego = 0
    for s in ("A06", "A07", "A08"):
        r = _pravka(s)
        if r < 0:
            return
        vsego += r
    print()
    if SUHO:
        print("Сухой прогон: на диске ничего не изменилось.")
    else:
        print(f"Тронуто бумаг: {vsego}. Бэкапы — .bak_pasti")
    print("Отмечен — значит оторван. Перепроверять не надо.")
    print()


if __name__ == "__main__":
    main()
