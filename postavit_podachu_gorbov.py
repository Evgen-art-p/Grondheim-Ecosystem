def _pravki(imya_fayla: str):
    if imya_fayla == "INDIKATORY.md":
        return [(AO_OLD, AO_NEW)]
    return [(VOLNA_OLD, VOLNA_NEW)]


def main() -> None:
    root = Path(__file__).resolve().parent
    fayly = []
    for slot in SLOTY:
        for imya in ("INDIKATORY.md", "PATTERNY.md"):
            fayly.append((root / BAZA / slot / "знания" / imya, slot, imya))

    net = [f for f, _, _ in fayly if not f.exists()]
    if net:
        print("НЕ НАШЁЛ файлы (запускать из корня репозитория):")
        for f in net:
            print("   ", f)
        return

    plan, uzhe, bracket = [], [], []
    for f, slot, imya in fayly:
        text = f.read_text(encoding="utf-8")
        metka = f"{slot}/{imya}"
        if MARKER in text:
            uzhe.append(metka)
            continue
        novyy = text
        ploho = None
        for nomer, (old, new) in enumerate(_pravki(imya), start=1):
            if novyy.count(old) != 1:
                ploho = f"кусок {nomer} найден {novyy.count(old)} раз (нужно 1)"
                break
            novyy = novyy.replace(old, new, 1)
        if ploho:
            bracket.append((metka, ploho))
            continue
        novyy = novyy.rstrip("\n") + f"\n\n<!-- {MARKER} -->\n"
        plan.append((f, text, novyy, metka))

    if uzhe and not plan and not bracket:
        print("уже накачен во всех знаниях — ничего не трогаю")
        return

    if bracket:
        print("⚠ Файлы на диске отличаются от ожидаемого — НИЧЕГО не меняю:")
        for metka, prichina in bracket:
            print(f"   {metka}: {prichina}")
        print("\nПришли Брату эти файлы — доведу под них.")
        return

    for f, staroe, novoe, metka in plan:
        bak = f.with_suffix(f.suffix + ".bak_podacha")
        if not bak.exists():
            bak.write_text(staroe, encoding="utf-8")
        f.write_text(novoe, encoding="utf-8")
        print(f"✔ {metka} — подача обновлена")

    if uzhe:
        print("(пропущены, уже накачены: " + ", ".join(uzhe) + ")")

    print("\nГотово. Как проверить — спроси Илью прямо:")
    print("  «что значит горб на AO?»")
    print("     должен сказать про силу/размах движения, а не про")
    print("     форму, и что горб весит лишь в сравнении с соседним;")
    print("  «а если цена падает — как выглядит ослабление?»")
    print("     должен сказать: ямы становятся МЕЛЬЧЕ, поднимаются")
    print("     к нулю, и это убыль размаха, а не прибавка.")


if __name__ == "__main__":
    main()
