def pravit(put: Path, zameny, hvost="", kod=False) -> str:
    if not put.is_file():
        return "мимо: файла нет"
    text = put.read_text(encoding="utf-8")
    if MARKER in text:
        return "уже"
    for staroe, _ in zameny:
        n = text.count(staroe)
        if n != 1:
            return f"мимо: якорь «{staroe.strip().splitlines()[0][:38]}…» × {n}"
    novyy = text
    for staroe, novoe in zameny:
        novyy = novyy.replace(staroe, novoe, 1)
    if hvost:
        novyy = novyy.rstrip("\n") + "\n" + hvost
    metka = f"# {MARKER} - marker" if kod else f"<!-- {MARKER} -->"
    novyy = novyy.rstrip("\n") + f"\n\n{metka}\n"
    if kod:
        try:
            ast.parse(novyy)
        except SyntaxError as e:
            return f"мимо: правка ломает синтаксис ({e.lineno}: {e.msg})"
    if SUHO:
        return "сделано (сухой прогон)"
    put.with_name(put.name + f".bak_slom_{SHTAMP}").write_text(
        text, encoding="utf-8")
    put.write_text(novyy, encoding="utf-8")
    return "сделано"


