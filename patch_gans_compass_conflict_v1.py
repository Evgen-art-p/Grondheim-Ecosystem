# -*- coding: utf-8 -*-
"""
patch_gans_compass_conflict_v1.py
────────────────────────────────────────────────────────────────────
ЧИНИТ (разбор канона Котина, 2026-07-11): Ганс (A04) в промте честно
учит «BULL → добыча наверху, BEAR → внизу», но у него был ФОЛЛБЭК
только на случай «компаса нет» — «смотри обе стороны, бери
действительный». Отдельного правила на случай КОНФЛИКТА (компас есть
и говорит одно, а валидный фрактал сформировался по ДРУГУЮ сторону)
не было. По логам тестера (XAUUSD H1/H4) Ганс в такой ситуации
докладывал «добычу» не по стороне компаса — судя по всему, скатываясь
в тот же фоллбэк не по адресу.

Котин (первоисточник, «Торговый Хаос» через А. Котина): фрактал —
первый сигнал входа, но только ДЕЙСТВИТЕЛЬНЫЙ и ТОЛЬКО в сторону
уже поставленного компаса разворота — фрактал против объявленного
разворота на этом этапе читается как шум, не как добыча.

ЛЕЧЕНИЕ: явное третье правило — конфликт компаса и фрактала — рядом
с уже существующим правилом «если компаса нет». Голос и геометрия
Ганса не тронуты — добавлена одна строка правила на его языке.

Идемпотентно. Маркер GANS_COMPASS_CONFLICT_V1. Бэкап рядом (.bak).
Запуск из КОРНЯ репы (Windows/PowerShell):
    python patch_gans_compass_conflict_v1.py
"""
from __future__ import annotations
import sys
from pathlib import Path

MARKER = "GANS_COMPASS_CONFLICT_V1"
TARGET = (Path("GRONDHEIM_CITY") / "Биржа" / "цеха" / "торговый_хаос" /
          "слоты" / "A04" / "промпт.md")

OLD = (
    "**Компас Искры подсказывает сторону.** BULL → твоя добыча наверху.\n"
    "BEAR → внизу. Если компаса нет — смотри обе стороны, бери действительный.\n"
)

NEW = (
    "**Компас Искры подсказывает сторону.** BULL → твоя добыча наверху.\n"
    "BEAR → внизу. Если компаса нет — смотри обе стороны, бери действительный.\n"
    "\n"
    "<!-- " + MARKER + " -->\n"
    "**Компас ЕСТЬ, но действительный фрактал — по ДРУГУЮ сторону "
    "(компас BEAR, а валиден только верхний, или наоборот)?** Это НЕ "
    "твоя добыча. Против объявленного разворота фрактал молчит как шум, "
    "не как охота. Доложи честно: добычи по стороне компаса пока нет. "
    "Не подменяй её тем, что нашлось по другую сторону.\n"
)


def main() -> int:
    if not TARGET.exists():
        print(f"✗ не нашёл {TARGET}")
        print("  запусти из КОРНЯ репы (там, где папка GRONDHEIM_CITY).")
        return 1

    src = TARGET.read_text(encoding="utf-8")

    if MARKER in src:
        print(f"✓ уже пропатчено ({MARKER}) — ничего не делаю.")
        return 0

    if OLD not in src:
        print("✗ не нашёл ожидаемый блок правила компаса в промте A04.")
        print("  Возможно, промт уже правился вручную. Проверь раздел "
              "«КАК ТЫ ОХОТИШЬСЯ» в GRONDHEIM_CITY/.../A04/промпт.md.")
        return 2

    bak = TARGET.with_suffix(TARGET.suffix + ".bak")
    if not bak.exists():
        bak.write_text(src, encoding="utf-8")
        print(f"• бэкап: {bak}")
    else:
        print(f"• бэкап уже был: {bak} (не перезаписываю)")

    TARGET.write_text(src.replace(OLD, NEW, 1), encoding="utf-8")
    print(f"✓ {TARGET}: добавлено правило конфликта компас/фрактал.")
    print(f"  Маркер идемпотентности: {MARKER}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
