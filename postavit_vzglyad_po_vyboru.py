def main() -> None:
    root = Path(__file__).resolve().parent
    p = root / FAYL
    if not p.exists():
        print(f"НЕ НАШЁЛ: {p}")
        print("Запускать из корня репозитория (там, где лежит main.py).")
        return

    t = p.read_text(encoding="utf-8")
    if MARKER in t:
        print("уже накачен — маркер на месте, ничего не трогаю")
        return

    if t.count(OLD) != 1:
        print(f"⚠ Файл отличается от ожидаемого: совпадений {t.count(OLD)} "
              "(нужно ровно 1). НИЧЕГО не меняю.")
        print("Пришли Брату свой Биржа/ui_torg.py — доведу под него.")
        return

    t = t.replace(OLD, NEW, 1).rstrip("\n") + f"\n\n# {MARKER} - marker\n"

    try:
        import ast
        ast.parse(t)
    except SyntaxError as e:
        print(f"⚠ СИНТАКСИС СЛОМАН: {e} — НЕ сохраняю")
        return

    bak = p.with_suffix(p.suffix + ".bak_vzglyad_po_vyboru")
    if not bak.exists():
        bak.write_text(p.read_text(encoding="utf-8"), encoding="utf-8")
    p.write_text(t, encoding="utf-8")

    print("✔ кнопка «Взгляд» теперь показывает выбор Шефа")
    print("  Бэкап рядом:", bak.name)
    print("\nКак проверить: ткни на полке слева другой инструмент или")
    print("этаж и жми «👁 Взгляд» — кадр должен смениться на него.")
    print("Потом спроси трейдера «покажи кадр M5» — панель сменится")
    print("на его картинку с подписью «смотрит рукой».")


if __name__ == "__main__":
    main()
