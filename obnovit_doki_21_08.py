def _pravit(f: Path, tekst: str, kuda_yakor: str | None) -> bool:
    t = f.read_text(encoding="utf-8")
    if MARKER in t:
        print(f"· {f.name}: маркер уже стоит — пропускаю")
        return True
    if kuda_yakor:
        if t.count(kuda_yakor) != 1:
            print(f"✗ {f.name}: якорь найден {t.count(kuda_yakor)} раз")
            return False
        novyy = t.replace(kuda_yakor, tekst + kuda_yakor, 1)
    else:
        novyy = t.rstrip() + "\n" + tekst
    if SUHO:
        print(f"· {f.name}: правка готова (сухой прогон)")
        return True
    bak = f.with_name(f"{f.name}.bak_21_08_{datetime.now():%Y%m%d_%H%M%S}")
    shutil.copy2(f, bak)
    f.write_text(novyy, encoding="utf-8")
    print(f"✓ {f.name}: обновлён (копия: {bak.name})")
    return True


