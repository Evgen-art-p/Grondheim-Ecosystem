"""
ne_est_konec_volny.py   ·   MARKER: KONEC_VOLNY_NE_SYEDEN_V1

ЧТО НАШЛОСЬ
-----------
В логе 22.08 конец первой волны случился дважды — и оба раза был съеден
на том же баре, той же ценой:

    [ВОЛНА 1] ⛰ кончилась @ 1.13845 · бар 2026.07.13 04:00
    [ТОЧКА]  ✦ родилась BULL @ 1.13845 · бар 2026.07.13 04:00
    [КЛЮЧ]   🔑 A06: точка родилась: BULL @ 1.13845

Виновата не математика. Виноват порядок в прогоне:

    1. молчаливый шаг: рука рынка ведёт точку, находит конец волны 1,
       ключ говорит «волна 1 кончилась» — правильно;
    2. СЛЕДОМ безусловно зовётся zabyt_tochku() и стирает ячейку точки
       целиком: и отметку конца волны, и защиту «один бар — одно
       решение»;
    3. Совет заново судит ТОТ ЖЕ бар на чистой доске — тот же
       разворотник читается уже как новая точка ноль, и трейдера зовут
       словами «точка родилась».

Отметка конца волны 1 стирается ровно в тот миг, когда появляется. А
откат отсчитывается ОТ неё — значит третье событие, момент того, кто
работает откат, не может наступить в принципе. Отсюда год без ордеров:
человеку просто ни разу не сказали его слово.

ПОЧЕМУ ЧИСТКА ВООБЩЕ СТОИТ
--------------------------
Она правильная и нужная — для ИСКАТЕЛЯ. Тот прыгает по найденным
местам через недели и месяцы, и точка, рождённая полгода назад, к
новому месту отношения не имеет: заново не родится, а проверка тут же
похоронит её структурным сломом.

Но сплошной прогон НЕ прыгает. Он идёт баром за баром, как живой
город, — и точка обязана жить между барами, иначе никакой истории у
неё нет. Чистка попала на общий путь и стала бить по тому, для кого не
предназначалась.

ЧТО ДЕЛАЕМ
----------
Одна проверка: на сплошном ходу точку не забываем. Прыжкам чистка
остаётся как была.

ЧЕГО НЕ ТРОГАЕМ
---------------
  · саму математику точки, волны и отката — она посчитала верно;
  · защиту «один бар — одно решение» — она цела, её просто стирали
    вместе с ячейкой;
  · ключ и то, кого он будит.

Идемпотентен, кладёт `.bak_konvolny_ГГГГММДД_ЧЧММСС`.

  py -3 ne_est_konec_volny.py           — сделать
  py -3 ne_est_konec_volny.py --suho    — только показать
"""

import ast
import sys
import time
from pathlib import Path

MARKER = "KONEC_VOLNY_NE_SYEDEN_V1"
SHTAMP = time.strftime("%Y%m%d_%H%M%S")
SUHO = "--suho" in sys.argv


STAROE = '''                # TOCHKA_NE_TASHCHITSYA_V1: прогон прыгнул в другой
                # момент истории — точка с прошлого места сюда не
                # едет. Иначе она формально жива, заново не рождается,
                # и ключ молчит на честном разворотнике.
                try:
                    import hooks as _h
                    _h.zabyt_tochku(_sym, _tf)
                except Exception as _ez:
                    print(f"[ПРОГОН] точку забыть не вышло: {_ez}")'''

NOVOE = '''                # TOCHKA_NE_TASHCHITSYA_V1: прогон прыгнул в другой
                # момент истории — точка с прошлого места сюда не
                # едет. Иначе она формально жива, заново не рождается,
                # и ключ молчит на честном разворотнике.
                #
                # KONEC_VOLNY_NE_SYEDEN_V1: но только на ПРЫЖКАХ. На
                # сплошном ходу чистка стояла здесь же и стирала
                # ячейку точки сразу после того, как молчаливый шаг
                # нашёл конец первой волны, — вместе с отметкой и с
                # защитой «один бар — одно решение». Совет судил тот же
                # бар начисто, тот же разворотник читался уже как новая
                # точка, и трейдеру говорили «точка родилась» вместо
                # «волна 1 кончилась». За год событие случилось дважды
                # и оба раза было съедено; а откат считается ОТ этой
                # отметки, значит третьего события не бывало вовсе.
                #
                # Сплошной прогон не прыгает: он идёт баром за баром,
                # как живой город, и точка обязана жить между барами.
                if not k.get("подряд"):
                    try:
                        import hooks as _h
                        _h.zabyt_tochku(_sym, _tf)
                    except Exception as _ez:
                        print(f"[ПРОГОН] точку забыть не вышло: {_ez}")'''


def nayti_koren() -> Path:
    for k in (Path(__file__).resolve().parent, Path.cwd()):
        for p in [k, *k.parents]:
            if (p / "GRONDHEIM_CITY").is_dir() and (p / "Биржа").is_dir():
                return p
    print("Не нашёл корень репозитория (нужны папки GRONDHEIM_CITY и Биржа).")
    zhdat_i_vyyti(1)


def zhdat_i_vyyti(kod=0):
    try:
        input("\nEnter — закрыть окно...")
    except EOFError:
        pass
    sys.exit(kod)


def main():
    koren = nayti_koren()
    print(f"Корень города: {koren}")
    if SUHO:
        print("СУХОЙ ПРОГОН — ничего не записываю.\n")

    put = koren / "Биржа" / "ui_torg.py"
    if not put.is_file():
        print("  мимо: Биржа/ui_torg.py не найден")
        zhdat_i_vyyti(1)

    text = put.read_text(encoding="utf-8")
    if MARKER in text:
        print("\n  уже стояло — правка на месте, ничего не делаю.")
        zhdat_i_vyyti(0)

    skolko = text.count(STAROE)
    if skolko != 1:
        print(f"\n  мимо: якорь встретился {skolko} раз, а нужен ровно один.")
        print("  Файл НЕ тронут. Покажи это Брату.")
        zhdat_i_vyyti(1)

    novyy = text.replace(STAROE, NOVOE, 1)
    novyy = novyy.rstrip("\n") + f"\n\n# {MARKER} - marker\n"
    try:
        ast.parse(novyy)
    except SyntaxError as e:
        print(f"\n  мимо: правка ломает синтаксис ({e.lineno}: {e.msg})")
        zhdat_i_vyyti(1)

    if SUHO:
        print("\n  сделано (сухой прогон)   Биржа/ui_torg.py")
    else:
        put.with_name(put.name + f".bak_konvolny_{SHTAMP}").write_text(
            text, encoding="utf-8")
        put.write_text(novyy, encoding="utf-8")
        print("\n  сделано                  Биржа/ui_torg.py")

    print("""
ЧТО ДОЛЖНО ПОЯВИТЬСЯ В ЛОГЕ
  Раньше на баре конца волны шли подряд две строки — «⛰ кончилась» и
  сразу «✦ родилась» по той же цене. Теперь второй быть не должно, а
  ключ обязан сказать:

      [КЛЮЧ] 🔑 A06: волна 1 кончилась, вершина @ … (N бар. от точки)

  И следом, через несколько баров, должно наконец появиться третье
  событие, которого не было ни разу:

      [ОТКАТ] ↩ EURUSD H4: кончился @ … · N бар(ов) от вершины
      [КЛЮЧ]  🔑 A06: откат кончился @ …

  Если «откат» так и не появится — это уже разговор о самой мерке
  отката, а не о съедании. Но сперва посмотрим: событие теперь
  доживает до трейдера.
""")
    zhdat_i_vyyti(0)


if __name__ == "__main__":
    main()
