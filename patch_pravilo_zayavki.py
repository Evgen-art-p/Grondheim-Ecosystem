# -*- coding: utf-8 -*-
"""
patch_pravilo_zayavki.py
════════════════════════════════════════════════════════════════════
ПРАВИЛО ЗАЯВКИ В ПРОМПТ ТРЁМ ТРЕЙДЕРАМ (вход по рынку НЕ существует)

БОЛЕЗНЬ (лог): Илья написал «приседающего нет, но бар сильный. Вхожу
ПО РЫНКУ» и взял лот 0.1. В промпте про механику входа НЕ сказано
ничего — трейдер не знает, что входа по рынку в системе нет. Механика
его страхует (рождение позиции ВСЕГДА PENDING), но мыслит он неверно:
называет текущую цену «по рынку» вместо цены ЗАЯВКИ на пробое, и
рационализирует вход на неполном сигнале.

ЛЕЧЕНИЕ: прописать всем троим (Брут/Илья/Василий) железное правило —
вход ТОЛЬКО заявкой (Buy Stop выше / Sell Stop ниже), рынок сам берёт
её пробоем или нет. «По рынку» не существует. Не дошёл рынок — сделки
нет, и это правильно. Это вправляет мышление: entry становится
осознанной ценой заявки, а не «текущей ценой сейчас».

Вставляется после фразы про «Никто не подложит тебе готовую цену».
Два варианта якоря (у A06/A07 одна разбивка строк, у A08 другая).

ИДЕМПОТЕНТЕН (маркер PRAVILO_ZAYAVKI_V1). Бэкапы — по файлу.
Запуск из корня Grondheim-Ecosystem:
    python patch_pravilo_zayavki.py
"""
import io
import sys
from pathlib import Path

MARKER = "PRAVILO_ZAYAVKI_V1"
SLOTS = ("A06", "A07", "A08")

RULE = (
    '\n\n'
    '=== ЗАКОН ВХОДА (железно, без исключений) ===\n'
    'Входа ПО РЫНКУ в этой системе НЕТ. Вход — всегда ОТЛОЖЕННАЯ ЗАЯВКА:\n'
    '  • LONG  → Buy Stop ВЫШЕ цены (рынок должен пробить вверх);\n'
    '  • SHORT → Sell Stop НИЖЕ цены (рынок должен пробить вниз).\n'
    'Ты называешь ЦЕНУ ЗАЯВКИ — рынок сам возьмёт её пробоем или нет.\n'
    'Не «вхожу по рынку», а «ставлю заявку на такой-то цене». Если рынок\n'
    'до неё не дойдёт — СДЕЛКИ НЕ БУДЕТ, и это ПРАВИЛЬНО: система сама\n'
    'подтверждает твою правоту движением. Заявка на неполном сигнале\n'
    '(нет приседающего, нет разворотного бара) — это не смелость, а\n'
    'нарушение канона. Сильный бар "прямо сейчас" — не повод входить\n'
    'по текущей цене: назови уровень пробоя и жди, возьмёт ли его рынок.\n'
)


def find_brain(aid):
    for c in (Path("GRONDHEIM_CITY") / "Биржа" / "цеха" / "торговый_хаос" / "слоты" / aid / "мозг.py",
              Path("Биржа") / "цеха" / "торговый_хаос" / "слоты" / aid / "мозг.py"):
        if c.exists():
            return c
    return None


# два варианта якоря — по концу фразы про «готовую цену»
ANCHORS = [
    # A06 (Брут) — короткий вариант
    ('        "входишь — verdict REJECTED. Никто не подложит тебе готовую цену. "\n'),
    # A07
    ('        "REJECTED. Никто не подложит тебе готовую цену и не скажет, как "\n'
     '        "поступить.\\n\\n"\n'),
    # A08
    ('        "verdict REJECTED. Никто не подложит тебе готовую цену и не скажет, "\n'),
]


def main():
    fixed = False
    for aid in SLOTS:
        path = find_brain(aid)
        if not path:
            print(f"[ПАТЧ] ⚠️  {aid}: мозг.py не найден — пропуск")
            continue
        src = path.read_text(encoding="utf-8")
        if MARKER in src:
            print(f"[ПАТЧ] ✓ {aid}: правило заявки уже есть")
            continue

        # найти конец строкового литерала фразы про «готовую цену» и
        # вставить RULE как отдельный строковый литерал сразу за ним.
        hit = None
        for a in ANCHORS:
            if a in src:
                hit = a
                break
        if not hit:
            print(f"[ПАТЧ] ⚠️  {aid}: якорь входа не найден — проверь вручную")
            continue

        # RULE оформляем как продолжение конкатенации строк промпта:
        # добавляем новый строковый литерал с маркером.
        rule_literal = (
            '        # ' + MARKER + ': вход только заявкой, по рынку — нет.\n'
            '        "' + RULE.replace('\\', '\\\\').replace('"', '\\"')
                             .replace('\n', '\\n') + '"\n'
        )
        src = src.replace(hit, hit + rule_literal, 1)

        # проверить синтаксис ДО записи
        import ast
        try:
            ast.parse(src)
        except SyntaxError as e:
            print(f"[ПАТЧ] ✗ {aid}: правка ломает синтаксис ({e}) — НЕ пишу")
            continue

        bak = path.with_suffix(".py.bak_zayavka_rule")
        if not bak.exists():
            bak.write_text(path.read_text(encoding="utf-8"), encoding="utf-8")
        path.write_text(src, encoding="utf-8")
        print(f"[ПАТЧ] ✓ {aid}: закон входа вписан")
        fixed = True

    if fixed:
        print("[ПАТЧ] ✅ Трейдеры теперь знают: вход только заявкой.")
        print("[ПАТЧ]    «По рынку» уйдёт из их мышления и формулировок.")
    else:
        print("[ПАТЧ] ✓ Изменять нечего (или уже вписано).")


if __name__ == "__main__":
    try:
        sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
    except Exception:
        pass
    main()
