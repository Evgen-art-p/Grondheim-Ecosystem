def main() -> int:
    if not ZNANIYA.exists():
        print(f"✗ нет папки {ZNANIYA} — запускать из корня репозитория")
        return 1

    sdelano, uzhe = 0, 0

    # 1. новые файлы
    for imya, soderzhimoe in NOVYE_FAYLY.items():
        put = ZNANIYA / imya
        if put.exists() and put.read_text(encoding="utf-8") == soderzhimoe:
            print(f"· уже стоит — {imya}")
            uzhe += 1
            continue
        put.write_text(soderzhimoe, encoding="utf-8")
        print(f"✓ записан {imya}")
        sdelano += 1

    # 2. старые файлы — в уборку
    stamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    otnositelnyy = ZNANIYA.relative_to(KOREN)
    kuda_koren = KOREN / "_УБОРКА" / stamp / otnositelnyy

    dvinuto = []
    for imya in STARYE_FAYLY:
        otkuda = ZNANIYA / imya
        if not otkuda.exists():
            print(f"· уже убран — {imya}")
            uzhe += 1
            continue
        kuda_koren.mkdir(parents=True, exist_ok=True)
        kuda = kuda_koren / imya
        shutil.move(str(otkuda), str(kuda))
        dvinuto.append(imya)
        print(f"✓ в уборку: {imya} → _УБОРКА/{stamp}/{otnositelnyy}/{imya}")
        sdelano += 1

    # 3. промпт — фиолетовые стрелки
    if PROMPT_PATH.exists():
        tekst = PROMPT_PATH.read_text(encoding="utf-8")
        if "Фиолетовые стрелки" in tekst:
            print("· уже дописано — фиолетовые стрелки в промпте")
            uzhe += 1
        elif PROMPT_BYLO in tekst:
            tekst = tekst.replace(PROMPT_BYLO, PROMPT_STALO, 1)
            kopiya = PROMPT_PATH.with_suffix(
                PROMPT_PATH.suffix + ".bak_znaniya_uroven1")
            if not kopiya.exists():
                shutil.copy2(PROMPT_PATH, kopiya)
                print(f"  (копия старого: {kopiya.name})")
            PROMPT_PATH.write_text(tekst, encoding="utf-8")
            print("✓ промпт: фиолетовые стрелки (фракталы) объяснены")
            sdelano += 1
        else:
            print("✗ не нашёл место в промпте для фиолетовых стрелок — "
                  "допиши руками или скажи Брату")
    else:
        print(f"✗ не нашёл {PROMPT_PATH}")

    print()
    print(f"ИТОГ: сделано {sdelano}, было уже в порядке {uzhe}")
    if dvinuto:
        print(f"В уборке: _УБОРКА/{stamp}/{otnositelnyy}/ "
              f"({', '.join(dvinuto)})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
