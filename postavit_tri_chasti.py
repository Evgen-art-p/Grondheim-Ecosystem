def _pravka(slot: str) -> int:
    p = SLOTY / slot / "промпт.md"
    if not p.exists():
        print(f"  {slot}: файла нет")
        return 0
    txt = p.read_text(encoding="utf-8")
    if MARKER in txt:
        print(f"  {slot}: уже стоит")
        return 0
    if "ALLIGATOR_NE_EGO_UROVEN_V1" not in txt:
        print(f"  {slot}: ОТКАЗ — сперва ubrat_alligatora.py")
        return -1

    novy, sdelano = txt, []
    for imya, staroe, novoe in (("первый вопрос", STAROE_VOPROS, NOVOE_VOPROS),
                                ("три части", STAROE_SHAGI, NOVOE_SHAGI)):
        n = novy.count(staroe)
        if n != 1:
            print(f"  {slot}: ! «{imya}» — якорь встречается {n} раз(а)")
            continue
        novy = novy.replace(staroe, novoe, 1)
        sdelano.append(imya)

    if not sdelano:
        return 0
    novy = novy.rstrip("\n") + f"\n\n<!-- {MARKER} -->\n"
    if not SUHO:
        shutil.copy2(p, p.with_suffix(".md.bak_tri"))
        p.write_text(novy, encoding="utf-8")
    print(f"  {slot}: {'готово' if SUHO else 'поправлено'} — "
          + "; ".join(sdelano))
    return 1


