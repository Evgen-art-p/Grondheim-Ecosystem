def _eto_koren(p: Path) -> bool:
    return (p / "БИРЖА.md").exists()


def nayti_koren() -> Path:
    zdes = Path(__file__).resolve().parent
    for kand in (zdes, Path.cwd(), *zdes.parents):
        if _eto_koren(kand):
            return kand
    put = input("Не нашёл корень. Перетащи сюда папку репо и Enter:\n> ")
    p = Path(put.strip().strip('"').strip("'"))
    if _eto_koren(p):
        return p
    print("✗ Это не корень репо")
    sys.exit(1)


def _est_na_diske(koren: Path, marker: str) -> bool:
    for f in koren.rglob("*.py"):
        s = str(f)
        if ".bak" in s or "_УБОРКА" in s or "_АРХИВ" in s or "_ПЕРЕЕЗД" in s:
            continue
        if f.name.startswith(("postavit_", "pochinit_", "obnovit_")):
            continue
        try:
            if marker in f.read_text(encoding="utf-8", errors="ignore"):
                return True
        except Exception:
            continue
    return False


def main():
    koren = nayti_koren()
    print(f"Город: {koren}\n")
    f = koren / "БИРЖА.md"
    t = f.read_text(encoding="utf-8")

    if MARKER in t:
        print("· маркер уже стоит — пропускаю")
        return 0

    print("── сверяю с диском ──")
    stroki = []
    for marker, chto in RABOTA:
        if _est_na_diske(koren, marker):
            stroki.append(f"- {chto}")
            print(f"  ✓ {chto}")
        else:
            print(f"  ✗ {chto} — на диске не найден, в док не пишу")

    tekst = RAZDEL.format(spisok="\n".join(stroki))

    yakor = "## Что сделано 20–21.08 <!-- DOKI_21_08_V1 -->"
    if t.count(yakor) != 1:
        print(f"✗ якорь найден {t.count(yakor)} раз — жду ровно один")
        return 1

    novyy = t.replace(yakor, tekst + yakor, 1)
    if SUHO:
        print("\n· правка готова (сухой прогон)")
        return 0

    bak = f.with_name(f"{f.name}.bak_vecher_{datetime.now():%Y%m%d_%H%M%S}")
    shutil.copy2(f, bak)
    f.write_text(novyy, encoding="utf-8")
    print(f"\n✓ БИРЖА.md обновлена (копия: {bak.name})")
    return 0


if __name__ == "__main__":
    kod = main()
