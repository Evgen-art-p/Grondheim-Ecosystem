def _primenit(path: Path, pravki: list):
    text = path.read_text(encoding="utf-8")
    if MARKER in text:
        return None, "уже накачен"
    for imya, old, _new in pravki:
        if text.count(old) != 1:
            return None, f"«{imya}» — совпадений {text.count(old)} (нужно 1)"
    for _imya, old, new in pravki:
        text = text.replace(old, new, 1)
    text = text.rstrip("\n") + f"\n\n# {MARKER} - marker\n"
    try:
        import ast
        ast.parse(text)
    except SyntaxError as e:
        return None, f"после правки синтаксис ломается: {e}"
    return text, None


def main() -> None:
    root = Path(__file__).resolve().parent
    zadachi = [(root / KARTINA, PRAVKI_KARTINA), (root / RUKI, PRAVKI_RUKI)]

    net = [f for f, _ in zadachi if not f.exists()]
    if net:
        print("НЕ НАШЁЛ файлы (запускать из корня репозитория):")
        for f in net:
            print("   ", f)
        return

    plan, uzhe, bracket = [], [], []
    for f, pravki in zadachi:
        novyy, prichina = _primenit(f, pravki)
        if prichina == "уже накачен":
            uzhe.append(f.name)
        elif prichina:
            bracket.append((f.name, prichina))
        else:
            plan.append((f, novyy))

    if uzhe and not plan and not bracket:
        print("уже накачен — ничего не трогаю")
        return

    if bracket:
        print("⚠ Файлы на диске отличаются от ожидаемого — НИЧЕГО не меняю:")
        for imya, prichina in bracket:
            print(f"   {imya}: {prichina}")
        print("\nПришли Брату эти файлы — доведу под них.")
        return

    for f, novoe in plan:
        bak = f.with_suffix(f.suffix + ".bak_kartina_hoda")
        if not bak.exists():
            bak.write_text(f.read_text(encoding="utf-8"), encoding="utf-8")
        f.write_text(novoe, encoding="utf-8")
        print(f"✔ {f.name} — правки легли, синтаксис цел")

    if uzhe:
        print("(пропущены, уже накачены: " + ", ".join(uzhe) + ")")

    print("\nЧто теперь помнит картина:")
    print("  · какой ход — направление и ГДЕ он начался;")
