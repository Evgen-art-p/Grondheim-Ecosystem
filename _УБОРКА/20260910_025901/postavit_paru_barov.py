# PARA_BAROV_I_ZHDAT_V1
"""
Пара «разворотник + приседающий» ложится в знания, а лазейка
«подожду» закрывается по смыслу, а не по формулировке.

═══ ЧТО СЛУЧИЛОСЬ 09.09 ═══

Трейдер увидел на дне бычий разворотный бар вместе с приседающим — и
забраковал место словами: «приседающий рядом с разворотным говорит о
борьбе и неопределённости, явного разворота нет, надо дождаться, пока
рынок сам покажет».

Проверено по полке: он не сочинял на пустом месте. Про приседающий
там написано «борьба, толпа упёрлась друг в друга». Про разворотник —
«это вопрос, смысл даёт место». А ЧТО ЗНАЧАТ ЭТИ ДВОЕ ВМЕСТЕ — не
написано НИГДЕ, ни в одном файле знаний. Он сложил «борьбу» с
«вопросом» и получил «неопределённость». Иначе и не могло выйти:
дыру в бумаге он заткнул собой.

А канон говорит обратное (слово Шефа 08.09): это ОДИН И ТОТ ЖЕ бар с
двух сторон. Разворотник — про форму (сходил за край и вернулся),
приседающий — про итог того же бара (объёма влили много, а сдвига
нет). Совпали — значит вернули против давления, там дрались: такой
разворотник СИЛЬНЕЕ, а не мутнее.

═══ ВТОРОЕ, ХУЖЕ ═══

«Дождаться, пока рынок сам покажет» — это вчерашняя лазейка «жду
подтверждения» в новой одежде. Мы закрыли её БУКВОЙ: запретили
конкретную фразу. Он сказал то же самое другими словами и прошёл
мимо запрета.

Значит запрещать надо не формулировку, а сам ход мысли: ясности
заранее не будет, как её ни называй.

═══ ЧТО ПАТЧ ДЕЛАЕТ ═══

  1. знания/RAZVOROTNYY_BAR.md — новый раздел про пару, словами Шефа.
     Ничего не удаляется, только дописывается;
  2. промпт.md — блок про «жду подтверждения» переписан по смыслу:
     любая отсрочка ради ясности — одно и то же, и это не решение.

«Работы не вижу» остаётся законным ответом. Закрывается только
отсрочка при готовом месте.

Запускать из корня репозитория:
    python postavit_paru_barov.py

Идемпотентен (маркер PARA_BAROV_I_ZHDAT_V1). Рядом .bak. Есть --suho.
"""
from __future__ import annotations

import sys
from pathlib import Path

MARKER = "PARA_BAROV_I_ZHDAT_V1"
SUHO = "--suho" in sys.argv

SLOTY = Path("GRONDHEIM_CITY") / "Биржа" / "цеха" / "торговый_хаос" / "слоты"

# ── 1. знания: пара баров ────────────────────────────────────────

RB_OLD = """---

## Три вещи, которые идут против чутья"""

RB_NEW = """---

## Разворотник и приседающий — один бар с двух сторон

Это не два прибора, спорящих между собой. Это одна и та же свеча,
описанная с разных сторон:

- **разворотный** — про ФОРМУ: цена сходила за край и вернулась,
  закрылась в другой половине;
- **приседающий** — про ИТОГ того же бара: объёма влили много, а
  от начала до конца цена почти не сдвинулась.

Поэтому они и совпадают так часто — это одно событие, увиденное
дважды.

**Совпали — бар СИЛЬНЕЕ, а не мутнее.** Много объёма и никакого
результата значит, что цену вернули против давления: там дрались, и
верх взяли те, в чью сторону бар закрылся. Разворотник без
приседающего — просто форма; с приседающим — форма, за которую
заплатили.

Читать это как «борьбу, а значит неопределённость» — ошибка ровно
наоборот. Борьба тут не мешает, она и есть содержание бара.

Смысл, как всегда, даёт МЕСТО: та же пара в середине молодого хода —
вдох перед продолжением; на пределе выдохшегося хода — место.

---

## Три вещи, которые идут против чутья"""

# ── 2. промпт: ждать нечего, как это ни назови ───────────────────

PR_OLD = """**Но «жду подтверждения разворота» — не ответ.** Подтверждения не
будет: рынок его не даёт и не обещал. Конец хода И ЕСТЬ то, чего ты
ждал. Если ход выдохся и разворотный бар стоит — называй цену заявки;
она и есть твоя проверка, а стоп — её цена. Не взяло — значит ход ещё
не кончился, и это не ошибка."""

PR_NEW = """**Но ждать ясности — не ответ.** Как ты это ни назови — «жду
подтверждения разворота», «пусть рынок сам покажет», «пока есть
неопределённость», «явного разворота не видно», — это одно и то же и
это не решение, а отсрочка. Ясности заранее не бывает ни в каком
виде: разворот становится явным только тогда, когда он уже прошёл, и
взять его будет уже негде.

Конец хода И ЕСТЬ то, чего ты ждал. Если ход выдохся и разворотный
бар стоит — называй цену заявки: она и есть твой вопрос рынку, а стоп
— цена ответа. Не взяло — значит ход ещё не кончился, и это не ошибка.

Разница простая: «работы не вижу» — это ответ, ты посмотрел и решил.
«Подожду, пока станет понятнее» — не ответ, потому что понятнее не
станет."""


def nayti_koren() -> Path:
    kandidat = Path(__file__).resolve().parent
    for papka in [kandidat, *kandidat.parents]:
        if (papka / SLOTY).is_dir():
            return papka
    print("Не нашёл папку слотов рядом со скриптом.")
    print("Положи скрипт в корень репозитория и запусти оттуда.")
    input("Enter — закрыть...")
    sys.exit(1)


def pravka(fayl: Path, staroe: str, novoe: str, imya: str) -> str:
    if not fayl.exists():
        return f"{imya}: нет файла"
    tekst = fayl.read_text(encoding="utf-8")
    if MARKER in tekst:
        return f"{imya}: уже сделано"
    skolko = tekst.count(staroe)
    if skolko != 1:
        return f"{imya}: ⚠ совпадений {skolko}, нужно 1 — НЕ трогал"
    novyy = tekst.replace(staroe, novoe, 1).rstrip("\n")
    novyy += f"\n\n<!-- {MARKER} -->\n"
    if SUHO:
        return f"{imya}: ✔ готов к правке (сухой прогон)"
    bak = fayl.with_suffix(fayl.suffix + ".bak_para")
    if not bak.exists():
        bak.write_text(tekst, encoding="utf-8")
    fayl.write_text(novyy, encoding="utf-8")
    return f"{imya}: ✔ поправлено"


def main() -> None:
    koren = nayti_koren()
    print(f"Корень: {koren}\n")

    for papka in sorted((koren / SLOTY).iterdir()):
        if not papka.is_dir():
            continue
        promt = papka / "промпт.md"
        bar = papka / "знания" / "RAZVOROTNYY_BAR.md"
        if not promt.exists() and not bar.exists():
            continue
        print(f"{papka.name}:")
        print("   ", pravka(bar, RB_OLD, RB_NEW, "разворотный бар"))
        print("   ", pravka(promt, PR_OLD, PR_NEW, "промпт"))

    print("\nКак проверить: покажи место, где на дне стоит разворотник")
    print("вместе с приседающим. Раньше он звал это неопределённостью")
    print("и уходил ждать.")
    input("\nEnter — закрыть...")


if __name__ == "__main__":
    main()
