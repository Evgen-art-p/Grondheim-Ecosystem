# -*- coding: utf-8 -*-
# FLET_NE_ZAPRET_V1
"""
Сомкнутая пасть перестаёт быть запретом.

═══ ЧТО СЛУЧИЛОСЬ 09.09 ═══

Трейдер на живом рынке сказал: цена упала, дивергенция есть,
приседающий есть, разворотный бар есть — и тут же сам всё отменил:
«Аллигатор спит, линии переплетены, разворотник в спящей пасти
неинформативен, хода нет, работы тоже».

Он ничего не выдумал. Он послушный — прочитал то, что ему написано.

Пишут это два места:
  · промпт: «Спит — флэт, работы нет»;
  · знания, паттерны: «Флэт — где работы нет… разворотных баров
    здесь найдётся сколько угодно, и ни один не работает».

А рядом, в индикаторах, лежит верная оговорка: спящая пасть сама по
себе ничего не запрещает, и на рабочем этаже в момент входа линии
как раз и должны быть сомкнуты. Два противоположных утверждения на
одной полке — он взял то, что короче и категоричнее.

═══ ПОЧЕМУ ЭТО ВАЖНО, А НЕ ПРИДИРКА ═══

Конец хода — это и есть место, где пасть закрывается: движение
выдохлось, линии сошлись. Считать сомкнутую пасть отказом — значит
запретить ровно то место, которое мы учим находить.

Правило «спит — работы нет» родом из другого: не лезь в середину
болота. Про конец хода оно не про то.

═══ ЧТО ПАТЧ ДЕЛАЕТ ═══

Разводит две картинки, которые выглядят похоже, а значат
противоположное. Различает их не пасть, а ЦЕНА и то, что было слева:

  ФЛЭТ        — цена ходит поперёк линий в узкой полосе, края нет,
                до этого ничего не приходило: ход не кончился, его
                не было;
  КОНЕЦ ХОДА  — до этого был ход, цена ушла далеко и стоит на
                пределе, горб мельче прежнего, рядом приседающий и
                разворотный бар.

Правки:
  1. промпт.md каждого слота — фраза про фазу пасти переписана: пасть
     читают, но вердикта «работы нет» она не выносит;
  2. знания/PATTERNY.md каждого слота — раздел про флэт становится
     разделом про ОТЛИЧИЕ флэта от конца хода. Сам флэт никуда не
     девается: в болото по-прежнему не лезем.

Ничего не удаляется. «Работы не вижу» остаётся законным ответом —
закрывается только отговорка «пасть сомкнута, значит нельзя».

Запускать из корня репозитория:
    python postavit_flet_ne_zapret.py

Идемпотентен (маркер FLET_NE_ZAPRET_V1). Рядом .bak. Есть --suho.
"""
from __future__ import annotations

import sys
from pathlib import Path

MARKER = "FLET_NE_ZAPRET_V1"
SUHO = "--suho" in sys.argv

SLOTY = Path("GRONDHEIM_CITY") / "Биржа" / "цеха" / "торговый_хаос" / "слоты"

# ── 1. промпт: пасть читают, но она не выносит вердикта ──────────

PROMT_OLD = """Спит — флэт, работы нет. Зевнула — движение только начинается."""

PROMT_NEW = """Спит — линии переплелись, и это значит только одно: прямо сейчас
никто никуда не идёт. Само по себе это НЕ запрет. У конца хода пасть
закрыта всегда — движение выдохлось, линии успели сойтись. Пустое
болото и выдохшийся ход выглядят похоже, а различает их не пасть, а
цена и то, что было слева: в болоте цена ходит поперёк линий в узкой
полосе и до этого ничего не приходило; в конце хода до этого был ход,
цена ушла далеко и стоит на пределе, горб мельче прежнего, рядом
приседающий и разворотный бар. Зевнула — движение только начинается."""

# ── 2. знания: флэт против конца хода ────────────────────────────

PAT_OLD = """## Флэт — где работы нет

Линии переплелись и лежат горизонтально, порядок между ними не
разобрать. Столбики AO мелкие и пляшут у нуля, ни один не выделяется
на фоне соседа. Цена ходит поперёк линий в узкой полосе.

Разворотных баров здесь найдётся сколько угодно, и ни один не работает.
Правильный ответ — уйти."""

PAT_NEW = """## Флэт и конец хода — выглядят похоже, значат разное

Линии переплелись и лежат горизонтально, порядок между ними не
разобрать. Столбики AO мелкие и пляшут у нуля, ни один не выделяется
на фоне соседа. Цена ходит поперёк линий в узкой полосе.

Это флэт. Разворотных баров здесь найдётся сколько угодно, и ни один
не работает. Правильный ответ — уйти.

**Но сомкнутые линии сами по себе не запрет.** В конце хода пасть
закрыта точно так же: движение выдохлось, и линии успели сойтись.
Если читать сомкнутую пасть как отказ, откажешься ровно от того
места, которое искал.

Различает не пасть, а ЦЕНА и то, что было слева:

- **флэт** — цена ходит поперёк линий в узкой полосе, края нет, и до
  этого ничего не приходило: ход не кончился, его не было;
- **конец хода** — до этого был ход, цена ушла далеко и стоит на
  пределе, горб мельче прежнего, рядом приседающий и разворотный бар.

Пасть отвечает только на вопрос «идёт ли кто-то прямо сейчас».
Кончился ли ЧЕЙ-ТО ход — отвечает цена слева, а не линии."""


def nayti_koren() -> Path:
    kandidat = Path(__file__).resolve().parent
    for papka in [kandidat, *kandidat.parents]:
        if (papka / SLOTY).is_dir():
            return papka
    print("Не нашёл папку слотов рядом со скриптом.")
    print("Положи скрипт в корень репозитория и запусти оттуда.")
    input("Enter — закрыть...")
    sys.exit(1)


def pravka(fayl: Path, staroe: str, novoe: str, imya: str) -> str:
    """Одна правка одного файла. Возвращает слово о том, что вышло."""
    if not fayl.exists():
        return f"нет файла {imya}"
    tekst = fayl.read_text(encoding="utf-8")
    if MARKER in tekst:
        return f"{imya}: уже сделано"
    skolko = tekst.count(staroe)
    if skolko != 1:
        return f"{imya}: ⚠ совпадений {skolko}, нужно 1 — НЕ трогал"
    novyy = tekst.replace(staroe, novoe, 1)
    novyy = novyy.rstrip("\n") + f"\n\n<!-- {MARKER} -->\n"
    if SUHO:
        return f"{imya}: ✔ готов к правке (сухой прогон)"
    bak = fayl.with_suffix(fayl.suffix + ".bak_flet")
    if not bak.exists():
        bak.write_text(tekst, encoding="utf-8")
    fayl.write_text(novyy, encoding="utf-8")
    return f"{imya}: ✔ поправлено"


def main() -> None:
    koren = nayti_koren()
    print(f"Корень: {koren}\n")

    for papka in sorted((koren / SLOTY).iterdir()):
        if not papka.is_dir():
            continue
        promt = papka / "промпт.md"
        patterny = papka / "знания" / "PATTERNY.md"
        if not promt.exists() and not patterny.exists():
            continue
        print(f"{papka.name}:")
        print("   ", pravka(promt, PROMT_OLD, PROMT_NEW, "промпт"))
        print("   ", pravka(patterny, PAT_OLD, PAT_NEW, "паттерны"))

    print("\nКак проверить: спроси трейдера про место, где ход выдохся,")
    print("а линии сомкнуты. Раньше он отвечал «пасть спит, работы нет».")
    input("\nEnter — закрыть...")


if __name__ == "__main__":
    main()
