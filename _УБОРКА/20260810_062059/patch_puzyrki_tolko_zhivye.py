# -*- coding: utf-8 -*-
# PUZYRKI_TOLKO_ZHIVYE_V1
"""
ПУЗЫРЬКИ — ТОЛЬКО ЖИВЫЕ. Сенсоры уходят с верхней панели.

РЕШЕНИЕ ШЕФА (06.08): «сноси все пузырьки, оставь для трёх трейдеров,
каждый подключается независимо, архивариус один, исполнитель один».

ПОЧЕМУ. Живые голоса из индикаторов убраны: Искра, Морж, Паникёр и
Ганс становятся математикой, а математике аватар не нужен — она не
личность и разговаривать с ней не о чем. Пузырёк над кодом только
путает: выглядит как собеседник, а собеседника там нет.

Остаются те, у кого есть характер и своё слово:
    три трейдера — каждый решает сам, независимо от других;
    Архивариус — его дело история;
    Исполнитель — рука.

ЧТО МЕНЯЕТСЯ ТЕХНИЧЕСКИ
    Весь состав панели задан одним списком ROSTER_SPEC — правим только
    его. Клик по пузырьку по-прежнему делает жителя активным, и теперь
    активным можно сделать ровно того, с кем есть о чём говорить.

    Активный по умолчанию переезжает с Искры (её больше нет на панели)
    на первого трейдера.

ЧТО НЕ ЛОМАЕТСЯ
    Слоты сенсоров на диске целы, их код никуда не делся — исчезает
    только аватар в шапке. Если где-то в кабинете остались ссылки на
    имена A01–A04, они честно вернут сам код слота вместо имени: это
    видно и не падает.

ЗАПУСК из корня репо:
    python patch_puzyrki_tolko_zhivye.py
"""
import ast
import py_compile
import shutil
import sys
from pathlib import Path

MARKER = "PUZYRKI_TOLKO_ZHIVYE_V1"
TARGET = Path("Биржа") / "ui_torg.py"
BAK = Path("Биржа") / "ui_torg.py.bak_puzyrki"

A1_OLD = '''ROSTER_SPEC = [
    ("торговый_хаос", "A01",         "A01", "✴️"),
    ("торговый_хаос", "A02",         "A02", "🦭"),
    ("торговый_хаос", "A03",         "A03", "😱"),
    ("торговый_хаос", "A04",         "A04", "🎯"),
    ("контора",       "архивариус",  "A05", "📚"),
    ("торговый_хаос", "A06",         "A06", "🪨"),
    ("торговый_хаос", "A07",         "A07", "🎲"),
    ("торговый_хаос", "A08",         "A08", "⚖️"),
    ("контора",       "исполнитель", "A09", "🎬"),
]
'''

A1_NEW = '''# PUZYRKI_TOLKO_ZHIVYE_V1: на панели только те, у кого есть своё слово.
# Сенсоры (A01 Искра, A02 Морж, A03 Паникёр, A04 Ганс) стали
# математикой — аватар над формулой только путает: выглядит как
# собеседник, а собеседника там нет. Их слоты на диске целы.
ROSTER_SPEC = [
    ("торговый_хаос", "A06",         "A06", "🪨"),
    ("торговый_хаос", "A07",         "A07", "🎲"),
    ("торговый_хаос", "A08",         "A08", "⚖️"),
    ("контора",       "архивариус",  "A05", "📚"),
    ("контора",       "исполнитель", "A09", "🎬"),
]
'''

A2_OLD = '''        "active_agent": "A01",
'''

A2_NEW = '''        # PUZYRKI_TOLKO_ZHIVYE_V1: Искры на панели больше нет —
        # активным по умолчанию встаёт первый трейдер.
        "active_agent": "A06",
'''


def main() -> int:
    if not TARGET.exists():
        print(f"✗ не нашёл {TARGET} — запускать из КОРНЯ репо")
        return 1

    src = TARGET.read_text(encoding="utf-8")
    if MARKER in src:
        print(f"✓ {MARKER} уже стоит — патч идемпотентен, ничего не делаю")
        return 0

    novyy = src
    for imya, old, new in (("состав панели", A1_OLD, A1_NEW),
                           ("активный по умолчанию", A2_OLD, A2_NEW)):
        n = novyy.count(old)
        if n != 1:
            print(f"✗ якорь «{imya}»: найден {n} раз (нужно 1). "
                  f"Файл изменился — патч НЕ применён, оригинал цел.")
            return 1
        novyy = novyy.replace(old, new, 1)
        print(f"  · {imya} — ок")

    try:
        ast.parse(novyy)
    except SyntaxError as e:
        print(f"✗ ast.parse упал: {e}. Ничего не записал.")
        return 1

    shutil.copy2(TARGET, BAK)
    TARGET.write_text(novyy, encoding="utf-8")

    try:
        py_compile.compile(str(TARGET), doraise=True)
    except py_compile.PyCompileError as e:
        shutil.copy2(BAK, TARGET)
        print(f"✗ py_compile упал: {e}. Откатил из {BAK.name}.")
        return 1

    print(f"\n✓ {MARKER} применён")
    print(f"  бэкап: {BAK}")
    print("\n  В шапке теперь пять: 🪨 🎲 ⚖️ трейдеры, 📚 Архивариус, 🎬 Исполнитель.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
