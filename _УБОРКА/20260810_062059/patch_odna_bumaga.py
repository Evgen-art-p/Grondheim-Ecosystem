def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--suho", action="store_true")
    a = ap.parse_args()

    print("═" * 60)
    print("ОДНА БУМАГА НА ТРОИХ" + ("   [СУХОЙ ПРОГОН]" if a.suho else ""))
    print("═" * 60)

    if not SLOTY.exists():
        print("✗ не вижу слоты торгового_хаоса — запускай из КОРНЯ репо")
        return 1

    sbylos = False
    for slot, pref in SLOTS.items():
        put = SLOTY / slot / "промпт.md"
        if not put.exists():
            print(f"  {slot}: бумаги нет — пропускаю")
            continue
        staroe = put.read_text(encoding="utf-8")
        if MARKER in staroe:
            print(f"  {slot}: уже одна бумага")
            continue
        novoe = BUMAGA.format(slot=slot, p=pref)
        # проверка, что не потеряли поля решения: их ждёт разборщик
        for hvost in ("_action", "_verdict", "_reason", "_direction",
                      "_entry", "_stop", "_lot", "_new_stop", "_add_lot"):
            if f"{pref}{hvost}" not in novoe:
                print(f"  ✗ {slot}: потерялось поле {pref}{hvost} — не пишу")
                return 1
        if a.suho:
            print(f"  {slot}: ✓ ляжет ({len(staroe)} → {len(novoe)} символов, "
                  f"поля {pref}_* на месте)")
            sbylos = True
            continue
        shutil.copy2(put, put.with_suffix(put.suffix + BAK))
        put.write_text(novoe, encoding="utf-8")
        print(f"  {slot}: ✓ бумага заменена (старая рядом: *{BAK})")
        sbylos = True

    print("─" * 60)
    if not sbylos:
        print("Всё уже стоит.")
        return 0
    if a.suho:
        print("Сухой прогон прошёл. Накатывать: python patch_odna_bumaga.py")
        return 0
    print("Готово. Жми РЫНОК и смотри, что скажут трое по одной бумаге.")
    print("Пока за столом один человек — голоса будут похожи; разноголосица")
    print("появится, когда на местах будут разные люди.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
