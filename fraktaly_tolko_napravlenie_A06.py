# fraktaly_tolko_napravlenie_A06.py — фрактал линейка, а не сигнал.
#
# Кладётся в КОРЕНЬ репозитория, рядом с main.py.
# Запуск из PowerShell, из корня:
#     python fraktaly_tolko_napravlenie_A06.py
#
# ВАЖНО: идёт после napravlenie_pered_diverom_A06.py.
#
# ═══ ЧТО НАШЛОСЬ ═══
#
# Слово «фрактал» стоит в 92 местах из 130 за прогон. Слово Шефа:
# «фракталы только для направления цены, а не ориентиры входов и
# сигналы». В её же словах видно оба употребления сразу.
#
# ВЕРНО — фрактал как линейка направления:
#   «фракталы показывают восходящий ход»
#   «идут вразнобой, нет чёткого направленного хода»
#
# НЕВЕРНО — фрактал сам стал судьёй:
#   «разворотный бар с приседающим на новом максимуме, ФРАКТАЛЫ НЕ
#    РАСТУТ, дивергенция AO» — 4 раза. Здесь «фракталы не растут»
#    поставлено третьим условием ВМЕСТО хода: прибор занял место
#    того, что им меряют.
#   «фракталы показывают восходящий ход, НЕСМОТРЯ НА разворотный,
#    приседающий и ослабление AO» — прибор спорит с условиями,
#    будто он четвёртый голос.
#   «фракталы обновляются УЖЕ НЕ ТАК УВЕРЕННО» — прибор, который
#    «не уверен». Это не наблюдение, а гадание по прибору.
#
# ═══ ЧТО СТАВИМ ═══
#
# Одну вставку сразу за тремя условиями: чем фрактал является и чем
# не является. Против её собственных формулировок, слово в слово —
# чтобы узнала свои и не повторяла.
#
# ЧЕГО НЕ ТРОГАЕМ. Стоп по фракталам при ведении остаётся как был:
# это не ориентир входа и не сигнал, а мерка, куда подтягивать стоп
# в уже открытой сделке. Слово Шефа про входы и сигналы, ведения оно
# не касается.
#
# Только A06. Правится текст задания, ни строчки кода.
#
# БЕЗОПАСНО. Рядом кладёт промпт.md.bak_fraktaly.
# Запускать можно сколько угодно раз.

import shutil
import sys
from pathlib import Path

KOREN = Path(__file__).resolve().parent
MARKER = "<!-- FRAKTALY_TOLKO_NAPRAVLENIE_V1 -->"
NUZHEN = "<!-- NAPRAVLENIE_PERED_DIVEROM_V1 -->"

PUT = (KOREN / "GRONDHEIM_CITY" / "Биржа" / "цеха" / "торговый_хаос"
       / "слоты" / "A06" / "промпт.md")

STAROE = "**ПРИСЕДАЮЩИЙ — объём.** Один на разворотном баре — уже достаточен.\n"

NOVOE = (
    "**ФРАКТАЛ — ЛИНЕЙКА, А НЕ СИГНАЛ.** Фракталы нужны тебе ровно для\n"
    "одного: прочитать, куда идёт цена. Хаи и лои растут — ход вверх,\n"
    "падают — вниз, вразнобой — хода нет. Всё. Прочитал направление —\n"
    "линейку отложил.\n"
    "\n"
    "Фрактал НЕ условие входа. НЕ ориентир, где входить. НЕ сигнал\n"
    "сам по себе. Вход окружает разворотный бар, а не фрактал.\n"
    "\n"
    "Вот как это ломается — узнай свои слова:\n"
    "\n"
    "- «разворотный бар с приседающим, **фракталы не растут**,\n"
    "  дивергенция AO» — ты поставил линейку ТРЕТЬИМ УСЛОВИЕМ вместо\n"
    "  хода. Условие — ход. Назови его: вверх, вниз или нет хода.\n"
    "- «фракталы показывают восходящий ход, **несмотря на** разворотный,\n"
    "  приседающий и AO» — линейка не спорит с условиями и не голосует.\n"
    "  Она только сообщает сторону.\n"
    "- «фракталы **обновляются уже не так уверенно**» — линейка не бывает\n"
    "  уверенной или неуверенной. Растут, падают или вразнобой — других\n"
    "  ответов у неё нет.\n"
    "\n"
    "**ПРИСЕДАЮЩИЙ — объём.** Один на разворотном баре — уже достаточен.\n"
)


def podozhdat():
    """Чтобы окно не захлопнулось при запуске двойным кликом."""
    try:
        input("\nГотово. Нажми Enter, чтобы закрыть окно.")
    except Exception:
        pass


def nayti():
    """Ищет задание Синди сам. Руками путь прописывать не надо."""
    if PUT.exists():
        return PUT
    musor = ("_ARCHIVE", "_OLD", "_АРХИВ", "_УБОРКА", ".bak")
    nashlos = [p for p in KOREN.rglob("промпт.md")
               if "A06" in str(p) and not any(m in str(p) for m in musor)]
    if len(nashlos) == 1:
        print(f"Нашёл: {nashlos[0]}")
        return nashlos[0]
    if len(nashlos) > 1:
        print("Нашёл несколько заданий A06:")
        for nomer, p in enumerate(nashlos, 1):
            print(f"  {nomer}. {p}")
        otvet = input("Какое правим? номер: ").strip()
        if otvet.isdigit() and 1 <= int(otvet) <= len(nashlos):
            return nashlos[int(otvet) - 1]
    return None


def main():
    put = nayti()
    if put is None:
        print("✗ не нашёл задание A06 — запускай из корня репозитория")
        return 1

    tekst = put.read_text(encoding="utf-8")

    if MARKER in tekst:
        print("· уже сделано")
        return 0

    if NUZHEN not in tekst:
        print("✗ сперва накати napravlenie_pered_diverom_A06.py.")
        print("  Ничего не тронул.")
        return 1

    if tekst.count(STAROE) != 1:
        print(f"✗ нашёл {tekst.count(STAROE)} мест вместо одного.")
        print("  Ничего не тронул. Скажи Брату, поправим по месту.")
        return 1

    novyy = tekst.replace(STAROE, NOVOE, 1)
    novyy = novyy.rstrip("\n") + "\n" + MARKER + "\n"

    kopiya = put.with_suffix(put.suffix + ".bak_fraktaly")
    if not kopiya.exists():
        shutil.copy2(put, kopiya)
        print(f"  (копия старого: {kopiya.name})")
    put.write_text(novyy, encoding="utf-8")

    print("✓ фрактал стал линейкой:")
    print("    · нужен ровно для одного — прочитать сторону хода")
    print("    · не условие, не ориентир входа, не сигнал")
    print("    · три её собственные ошибки названы дословно")
    print("    · стоп по фракталам при ведении не тронут")
    print()
    print("Перезапусти Кабинет (main.py) и запусти прогон.")
    print("Смотреть: перестанет ли «фракталы не растут» стоять вместо")
    print("хода. Должно быть «цена идёт вверх» или «хода нет».")
    return 0


if __name__ == "__main__":
    kod = main()
    podozhdat()
    sys.exit(kod)
