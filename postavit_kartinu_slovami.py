# -*- coding: utf-8 -*-
# KARTINA_SLOVAMI_V1 — рассказывает картину, числа только в приказе
"""
КАРТИНА СЛОВАМИ, ЧИСЛА — В ПРИКАЗ

Слово Шефа 10.09: «пусть картину описывает, что видит на графике,
без чисел даже, почему решает войти или не войти, а цену входа уже
пускай называет. То есть ясно, от какого хода он собрался и что
делает — покупает или продаёт».

И отдельно, про приседающий: «может и на бар назад быть, или вообще
ряд приседающих до некрона — рынок готовился. Сигналы не имеют
статус лучше или хуже. Но если цена давно долбит экстремумы, а AO
всё тухнет, и приседающий уже давно сигналит — явно дело к
развороту, и можно бар окружать».

ЧТО ДЕЛАЕТ ПАТЧ, две правки в бумаге каждого слота.

 1. ПРИСЕДАЮЩИЕ — ДОРОЖКОЙ, а не по одному. Абзац дописывается в
    раздел про кадр, сразу за красными точками. На кадре весь ряд
    виден сразу, а на столе лежит только последний бар — ещё одна
    причина смотреть, а не считать.

 2. КАК ОТВЕЧАТЬ. Вместо «сухих полей решения» — картина словами:
    от какого хода идёшь, что видишь, почему входишь или не входишь,
    и что делаешь — покупаешь или продаёшь. Числа в рассказ не
    тащить: цена и стоп называются в приказе, рукой.

ТРЕБУЕТ: CHTO_NA_KADRE_V1 (первая правка ставится в тот раздел) и
SLOVO_NE_PRIKAZ_V1 (вторая опирается на то, что решение уже
отдаётся рукой). Патч это проверяет.

БЕЗОПАСНОСТЬ: .bak_kartina, идемпотентен, `--suho` не трогает диск,
каждая правка ставится отдельно.

    python postavit_kartinu_slovami.py --suho
    python postavit_kartinu_slovami.py

`шесть·проверено·до·корня`
"""
import shutil
import sys
from pathlib import Path

MARKER = "KARTINA_SLOVAMI_V1"
SUHO = "--suho" in sys.argv

_REPO = Path(__file__).resolve().parent
SLOTY = _REPO / "GRONDHEIM_CITY" / "Биржа" / "цеха" / "торговый_хаос" / "слоты"

# ── правка 1: приседающие дорожкой ───────────────────────────
YAKOR_SQUAT = '''**Красные точки под ценой.** Приседающие бары. Точка есть — бар
приседающий, точки нет — нет. Величина точки ничего не значит.
'''

DOROZHKA = '''
Смотри их **дорожкой, а не по одному.** Точка под последним баром —
это только последний бар. Идут подряд несколько баров перед
разворотным — значит рынок готовился, дрались тут не раз. На кадре
весь ряд виден сразу; на столе лежит один последний бар — потому и
смотри, а не считай.
'''

# ── правка 2: как отвечать ───────────────────────────────────
STAROE_OTVET = '''Ответ — один объект JSON. Голос живёт ВНУТРИ него, в поле
`narrative`: одно-три предложения, как ты сам бы сказал, кратко и
по-своему. Остальное — сухие поля решения и строка в дневник.
'''

NOVOE_OTVET = '''Ответ — один объект JSON. Голос живёт ВНУТРИ него, в поле
`narrative`, и это главное, что ты говоришь.

**Рассказывай картину, а не показания.** Что видишь на графике —
своими словами, без чисел. Куда идёт цена, что с горбами, есть ли
приседающие и один это бар или дорожка. Из этого само выйдет, почему
ты входишь или не входишь.

Из ответа должно быть ясно **от какого хода** ты собрался и **что
делаешь** — покупаешь или продаёшь. Не «есть сигнал», а: этот ход
идёт оттуда, он выдохся вот на чём, поэтому продаю.

Числа в рассказ не тащи — они сбивают и тебя, и того, кто читает.
Цену входа и стоп ты называешь в ПРИКАЗЕ, рукой, там им и место.
Спросят число отдельно — тогда назовёшь.
'''


def _pravka(slot: str) -> int:
    p = SLOTY / slot / "промпт.md"
    if not p.exists():
        print(f"  {slot}: файла нет")
        return 0
    txt = p.read_text(encoding="utf-8")
    if MARKER in txt:
        print(f"  {slot}: уже стоит")
        return 0

    net = []
    if "CHTO_NA_KADRE_V1" not in txt:
        net.append("postavit_chto_na_kadre.py")
    if "SLOVO_NE_PRIKAZ_V1" not in txt:
        net.append("postavit_slovo_ne_prikaz.py")
    if net:
        print(f"  {slot}: ОТКАЗ — сперва {', '.join(net)}")
        return -1

    sdelano, novy = [], txt

    if novy.count(YAKOR_SQUAT) == 1:
        novy = novy.replace(YAKOR_SQUAT, YAKOR_SQUAT + DOROZHKA, 1)
        sdelano.append("приседающие дорожкой")
    else:
        print(f"  {slot}: ! абзац про красные точки не найден")

    if novy.count(STAROE_OTVET) == 1:
        novy = novy.replace(STAROE_OTVET, NOVOE_OTVET, 1)
        sdelano.append("картина словами")
    else:
        print(f"  {slot}: ! начало раздела про ответ не найдено")

    if not sdelano:
        return 0

    novy = novy.rstrip("\n") + f"\n\n<!-- {MARKER} -->\n"
    if not SUHO:
        shutil.copy2(p, p.with_suffix(".md.bak_kartina"))
        p.write_text(novy, encoding="utf-8")
    print(f"  {slot}: {'готово' if SUHO else 'поправлено'} — "
          + ", ".join(sdelano))
    return 1


def main():
    print()
    print("КАРТИНА СЛОВАМИ" + ("  · СУХОЙ ПРОГОН" if SUHO else ""))
    print("корень:", _REPO)
    print()
    if not SLOTY.exists():
        print("!! слотов нет — запускать из корня репы")
        return

    vsego = 0
    for s in ("A06", "A07", "A08"):
        r = _pravka(s)
        if r < 0:
            return
        vsego += r

    print()
    if SUHO:
        print("Сухой прогон: на диске ничего не изменилось.")
    else:
        print(f"Тронуто бумаг: {vsego}. Бэкапы — .bak_kartina")
    print("Теперь он рассказывает, что видит, а числа несёт в приказ.")
    print()


if __name__ == "__main__":
    main()
