#
# Кладётся в КОРЕНЬ репозитория, рядом с main.py.
# Запуск из PowerShell, из корня:
#     python ruka_poslednim_slovom_A06.py
#
# ВАЖНО: идёт после slovo_ne_prikaz_A06.py.
#
# ═══ ЧТО НАШЛОСЬ ═══
#
# Прогон 16.09 (45 мест): руку Илья позвал 12 раз, и ВСЕ ДВЕНАДЦАТЬ —
# только на переспросе. Ни разу с первого захода. 44 лишних обращения
# к модели и 44 лишних кадра за один прогон.
#
# Причина — самая последняя строка задания:
#
#     «diary_entry: input, action, result(=null). Ничего вне JSON.»
#
# «НИЧЕГО ВНЕ JSON». А рука — это как раз вне JSON. Город последним
# своим словом запрещал трейдеру ровно то, чего от него ждал.
#
# Про руку в задании сказано — но в середине. А в переспросе последние
# слова: «позови руку otdat_prikaz, третьего нет». И рука зовётся.
# Каждый раз. Двенадцать из двенадцати.
#
# Дело не в содержании, а в ПОРЯДКЕ. Что стоит последним, то и весит
# больше всего.
#
# ═══ ЧТО ДЕЛАЕМ ═══
#
# 1. Слово про руку уезжает из середины в САМЫЙ КОНЕЦ задания,
#    отдельным блоком, теми же словами, что работают в переспросе.
#
# 2. «Ничего вне JSON» переписано: текстом вне JSON ничего не пиши,
#    рука — не текст. Заодно поправлено давнее противоречие: чуть
#    выше задание САМО просит писать MEMORY_REQUEST отдельной строкой
#    до JSON, и старая формулировка это запрещала.
#
# Ни одного нового правила. Те же слова, в обратном порядке.
#
# Только A06. A07 и A08 — слово Шефа: пока не трогаем.
#
# КАК ПРОВЕРИТЬ. В логе следующего прогона не должно остаться ни
# одной строчки [ПЕРЕСПРОС]. Сейчас их 44.
#
# БЕЗОПАСНО. Собирает новый текст в памяти, проверяет ast.parse и
# только потом пишет. Рядом кладёт мозг.py.bak_ruka_poslednim.
# Запускать можно сколько угодно раз.

import ast
import shutil
import sys
from pathlib import Path

KOREN = Path(__file__).resolve().parent
MARKER = "RUKA_POSLEDNIM_SLOVOM_V1"
NUZHEN = "SLOVO_NE_PRIKAZ_V2"

PUT = (KOREN / "GRONDHEIM_CITY" / "Биржа" / "цеха" / "торговый_хаос"
       / "слоты" / "A06" / "мозг.py")

# ── 1. из середины слово про руку убираем ──
STAROE_1 = (
    '        "Решения в этом ответе НЕТ и быть не может. Войти, "\n'
    '        "передвинуть стоп, долить или закрыть — только рукой "\n'
    '        "otdat_prikaz. Не работаешь на этом баре — та же рука с "\n'
    '        "WAIT и причиной. Не позвал руку — ничего не произошло, "\n'
    '        "сколько ни рассказывай.\\n"\n'
)
NOVOE_1 = (
    '        # RUKA_POSLEDNIM_SLOVOM_V1: слово про руку уехало отсюда\n'
    '        # в САМЫЙ КОНЕЦ задания. Здесь, в середине, его перебивала\n'
    '        # последняя строка «Ничего вне JSON» — а рука и есть\n'
    '        # «вне JSON». Что стоит последним, то и весит больше.\n'
    '        "Решение в этот ответ не пишется — про него сказано в "\n'
    '        "самом конце.\\n"\n'
)

# ── 2. конец задания переписываем ──
STAROE_2 = (
    '        "diary_entry: input, action, result(=null). Ничего вне JSON."\n'
    '    )\n'
)
NOVOE_2 = (
    '        "diary_entry: input, action, result(=null).\\n"\n'
    '        # RUKA_POSLEDNIM_SLOVOM_V1: здесь стояло «Ничего вне JSON»,\n'
    '        # и это была САМАЯ ПОСЛЕДНЯЯ строка задания. Она прямо\n'
    '        # запрещала то, чего город ждёт: рука — это как раз «вне\n'
    '        # JSON». Трейдер слушался и заканчивал ход рассказом.\n'
    '        #\n'
    '        # Прогон 16.09: 45 мест, руку позвал 12 раз, и все 12 —\n'
    '        # только на переспросе, где последними словами были\n'
    '        # «позови руку». Значит последними словами будут они же.\n'
    '        #\n'
    '        # Заодно снято давнее противоречие: чуть выше задание САМО\n'
    '        # просит писать MEMORY_REQUEST отдельной строкой до JSON,\n'
    '        # а «ничего вне JSON» это запрещало.\n'
    '        "Кроме строки MEMORY_REQUEST, текстом вне JSON ничего не "\n'
    '        "пиши. Рука — не текст.\\n"\n'
    '        "\\n=== И ПОСЛЕДНЕЕ, САМОЕ ВАЖНОЕ ===\\n"\n'
    '        "Пока ты не позвал руку otdat_prikaz, ход НЕ ОКОНЧЕН. "\n'
    '        "Рассказ — это твой голос, и он нужен; но исполнитель "\n'
    '        "слышит только руку.\\n"\n'
    '        "Работаешь — otdat_prikaz с ENTER: сторона, цена заявки, "\n'
    '        "стоп.\\n"\n'
    '        "Не работаешь на этом баре — та же рука с WAIT и "\n'
    '        "причиной.\\n"\n'
    '        "Третьего нет. Не позвал руку — ничего не произошло, и в "\n'
    '        "истории это останется разговором."\n'
    '    )\n'
)


def podozhdat():
    """Чтобы окно не захлопнулось при запуске двойным кликом."""
    try:
        input("\nГотово. Нажми Enter, чтобы закрыть окно.")
    except Exception:
        pass


def nayti():
    """Ищет мозг Ильи сам. Руками путь прописывать не надо."""
    if PUT.exists():
        return PUT
    musor = ("_ARCHIVE", "_OLD", "_АРХИВ", "_УБОРКА", ".bak")
    nashlos = [p for p in KOREN.rglob("мозг.py")
               if "A06" in str(p) and not any(m in str(p) for m in musor)]
    if len(nashlos) == 1:
        print(f"Нашёл: {nashlos[0]}")
        return nashlos[0]
    if len(nashlos) > 1:
        print("Нашёл несколько мозгов A06:")
        for nomer, put in enumerate(nashlos, 1):
            print(f"  {nomer}. {put}")
        otvet = input("Какой правим? номер: ").strip()
        if otvet.isdigit() and 1 <= int(otvet) <= len(nashlos):
            return nashlos[int(otvet) - 1]
    return None


def main():
    put = nayti()
    if put is None:
        print("✗ не нашёл мозг A06 — запускай из корня репозитория")
        return 1

    tekst = put.read_text(encoding="utf-8")

    if MARKER in tekst:
        print("· уже сделано")
        return 0

    if NUZHEN not in tekst:
        print("✗ сперва накати slovo_ne_prikaz_A06.py — этот идёт следом.")
        print("  Ничего не тронул.")
        return 1

    pravki = [(STAROE_1, NOVOE_1), (STAROE_2, NOVOE_2)]
    for nomer, (staroe, _) in enumerate(pravki, 1):
        if tekst.count(staroe) != 1:
            print(f"✗ правка {nomer}: нашёл {tekst.count(staroe)} мест "
                  f"вместо одного. Ничего не тронул.")
            print("  Скажи Брату, поправим по месту.")
            return 1

    novyy = tekst
    for staroe, novoe in pravki:
        novyy = novyy.replace(staroe, novoe, 1)

    try:
        ast.parse(novyy)
    except SyntaxError as beda:
        print(f"✗ после правки файл поломался (строка {beda.lineno}): {beda.msg}")
        print("  Ничего не записал, оригинал цел.")
        return 1

    kopiya = put.with_suffix(put.suffix + ".bak_ruka_poslednim")
    if not kopiya.exists():
        shutil.copy2(put, kopiya)
        print(f"  (копия старого: {kopiya.name})")
    put.write_text(novyy, encoding="utf-8")

    print("✓ рука стала последним словом:")
    print("    · «Ничего вне JSON» больше не запрещает руку")
    print("    · блок про otdat_prikaz уехал в самый конец задания")
    print("    · MEMORY_REQUEST снова разрешён явно")
    print("    · A07 и A08 не тронуты — слово Шефа")
    print()
    print("Перезапусти Кабинет (main.py) и запусти прогон.")
    print("Проверка одна: строчек [ПЕРЕСПРОС] в логе быть не должно.")
    print("В прошлом прогоне их было 44.")
    return 0


if __name__ == "__main__":
    kod = main()
    podozhdat()
    sys.exit(kod)
