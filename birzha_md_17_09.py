KOREN = Path(__file__).resolve().parent
MARKER = "<!-- BIRZHA_17_09_V1 -->"

RAZDEL = """

---

## 17.09 — Синди на A06: зрение доказано, проигрыш оказался в стопе

Смена жителя: Шеф не стал чистить память Илье, а посадил на A06
**Синди**. Первая оценка: «вроде неплохо начала».

### Что чинили в машине (всё накатано)

Переспрос 87% побеждён, но не там, где искали. Сперва убрали из
задания блок `signal` (он требовал писать решение полями, а бумага
запрещала — противоречие), потом вынесли слово про руку в САМЫЙ
КОНЕЦ. Последняя строка задания гласила «Ничего вне JSON» — а рука и
есть «вне JSON». Город своим последним словом запрещал ровно то, чего
ждал. **Дело было не в содержании, а в порядке: что стоит последним,
то и весит.** Итог: было 44 переспроса на прогон, стало 0.

Кадр: перестал рисоваться в мёртвую вкладку; лента рисует хвост в 80
сообщений вместо всей истории (перерисовка сотен сообщений раз в
секунду и рвала связь); прогон кладёт кадр в общую память сам, минуя
окно; контрольная метка выросла с 18 до 44 пунктов — в ужатой панели
она была 9 пикселей, и потому Шеф её не видел.

`HOLD` вернулся на место: условие «только при открытой позиции» было
вырезано вместе со старым блоком, и Синди говорила «я уже в SHORT»
при нуле позиций — достраивала мир под доступное слово.

Компас: **лесенка воды не знала дневок** — для D1 не было написано
правило, и трейдер работал вслепую. Достроено `D1 → W1, MN1`.
Причина «воды нет» теперь печатается с числами обоих этажей.

### Что чинили в каноне

- **Направление смотрится ПЕРВЫМ** — оно говорит, где искать дивер:
  цена растёт → вершины, падает → впадины. Без него сравнивать нечего.
- **Ход идёт ПРОТИВ входа.** Не было сказано — и Синди достроила
  наоборот: ждала нисходящего хода для шорта.
- **Фрактал — линейка, не сигнал.** Слово «фрактал» было в 92 местах
  из 130, стояло третьим условием вместо хода. После правки — 2 из 22,
  и только про ведение стопа.
- **Попытки на структуре**: три по любому, и после трёх входишь, если
  условия сошлись. Число ничего не запрещает. «То ли ты делаешь?» —
  требование посмотреть заново, а не запрет.
- **Дивер называется ЧИСЛАМИ** — две цены и два значения AO. Слово
  можно сказать не посмотрев, числа нельзя.
- **Последний горб не обязан закрыться справа**: сравнивается с ТЕКУЩИМ
  значением AO. Ждать, пока горб дорисуется, — значит опоздать.

### Четыре свидетеля на один вход

Город теперь проверяет её независимо от её же слов:

1. **Метка** — код в углу кадра, его нет ни на столе, ни в знаниях.
2. **Числа стола в месте** — AO, фракталы, компас, цена бара.
3. **Её четыре числа** — что именно она сравнила.
4. **Счёт дивера** (`Биржа/sverka_divera.py`) — город считает сам по
   барам: горб это три столбика (меньше-БОЛЬШЕ-меньше), главный —
   самый большой в поле зрения.

Вход НЕ блокируется ничем из этого. Город считает и показывает,
решает трейдер.

### Результат замера: 3 года H4, 555 пробудов, 69 входов

**Зрение доказано.** Метка: 68 ✓ против 1 ✗. Дивер: 43 ✓, 19 ✗, 7 ?.
Стол рукой — 523 раза из 555. Приказ с первого раза — 555 из 555.

**Направление верное.** Цена в её сторону доходила на 1R — 59 раз из
64, на 2R — 54, на 5R — 40.

**А денег нет: −50.86R, один плюс на 55 закрытий.**

Гипотеза «виноват дивер» рухнула на счёте:

| | сделок | в плюс | средний |
|---|---|---|---|
| дивер подтверждён ✓ | 35 | **0** | −0.98R |
| дивер не подтверждён ✗ | 15 | 1 | −0.80R |

Разницы нет. Значит вход ни при чём.

### Где на самом деле теряется

Стоп стоял **ровно на краю разворотного бара**: отступ 0 пунктов у 66
входов из 69. Причина арифметическая — **в истории CSV нет спреда**,
стол подставлял ноль и выдавал голые края. Правка: `SPRED_PO_
UMOLCHANIYU = 3` в `stol.py` (сверху два спреда, снизу один).

Но моделирование на настоящих барах показало: три пункта дают −36.7R
вместо −37.1R. **Мелочь.** Настоящее вот что:

- цена сперва идёт ПРОТИВ неё на 1R и больше — **60 раз из 64**;
- успела дойти до +1R раньше, чем ушла против на 1R — **4 раза из 64**;
- лучшее движение в её сторону случается в среднем на **82-м баре**;
- половина сделок умирает за первые **три бара**.

Её риск — размах одной свечи, а рынок ходит размахом движения.

Что даёт моделирование на её же входах:

| ведение | итог |
|---|---|
| как есть | −36.7R |
| безубыток при +1R | −22.4R |
| безубыток при +0.5R | −20.4R |
| цель +1R | **±0.0R** |

Слово Шефа: «она входит, её протаскивает, она снова входит, а бывает
просто протащит, а на развороте уже бросит — вот наша дыра».

Входы неоднородны: 29 из 64 ушли против меньше чем на 1R (хорошие,
не хватило четверти риска), 19 — на 1-3R (рано, но разворот
состоялся), 14 — на 5R и больше при болтанке через вход (это не
развороты вовсе).

### Итог сессии

**Первая задача закрыта: она ловит вход адекватно.** 23 входа в год,
из них в направление попадает около 20. Это не «мартышка с гранатой»
— это ученик, который читает верно и **входит слишком рано**.

Следующий кусок отдельный и не про зрение: **чем мерить стоп**. Край
одной свечи не годится. Кандидаты — фрактал, размах последних баров,
граница структуры. Решение за Шефом, после того как он глазами
пройдёт развороты и отделит ложные сигналы.

### Что оказалось важнее патчей

Шеф остановил Синди после ложного дивера словами «родная моя девочка,
у тебя немного не сходится» — без разбора и подсказки. Она сама нашла
ошибку, назвала нарушенное правило и записала себе:

> «Я буду входить только при одновременно подтверждённых ходе,
> дивергенции AO и приседающем разворотном баре, причём дивергенцию
> назову лишь после проверки двух цен и двух значений AO. Без
> реального кадра и чисел — только наблюдение, без додумывания.»

После этого разговора стол рукой вернулся с половины пробудов до
девяти из десяти. Ни один патч такого не давал.

**Правило, выведенное самим, держится; вписанное — как повезёт.**

### Осталось

- **Мера стопа** — главный и единственный крупный долг.
- Отсев ложных сигналов (те 14 из 64) — ждёт разбора глазами.
- Ведение: безубыток и перенос стопа используются 1 раз из 20.
- `tekushchiy_ao.py` — накатить, если ещё нет.
- Долги прошлых сессий: мультимодальная история чата, склад на Бирже.
"""

STROKA_UKAZATELYA = (
    "- **17.09** — Синди на A06. Переспрос побеждён (порядок слов важнее\n"
    "  содержания), зрение доказано меткой (68 из 69), дивер проверяется\n"
    "  счётом. Замер: 3 года H4, 69 входов, направление верное в 59 из 64,\n"
    "  итог −50.86R. Проигрыш не во входе, а в стопе размером с одну свечу.\n"
)


def podozhdat():
    try:
        input("\nГотово. Нажми Enter, чтобы закрыть окно.")
    except Exception:
        pass


def main():
    put = KOREN / "БИРЖА.md"
    if not put.exists():
        nash = [p for p in KOREN.rglob("БИРЖА.md") if ".bak" not in p.name]
        if len(nash) == 1:
            put = nash[0]
        else:
            print("✗ не нашёл БИРЖА.md — запускай из корня репозитория")
            return 1

    tekst = put.read_text(encoding="utf-8")
    if MARKER in tekst:
        print("· уже сделано")
        return 0

    novyy = tekst.rstrip("\n") + RAZDEL.rstrip("\n") + "\n\n" + MARKER + "\n"

    # строка в указатель сессий, если он есть
    yakor = "## История: указатель по сессиям"
    if yakor in novyy:
        i = novyy.index(yakor)
        j = novyy.find("\n## ", i + 10)
        kusok = novyy[i:j if j > 0 else len(novyy)]
        if "**17.09**" not in kusok:
            vstavka = kusok.rstrip("\n") + "\n" + STROKA_UKAZATELYA
            novyy = novyy[:i] + vstavka + (novyy[j:] if j > 0 else "")
            print("  (строка добавлена и в указатель сессий)")

    kopiya = put.with_suffix(put.suffix + ".bak_17_09")
    if not kopiya.exists():
        shutil.copy2(put, kopiya)
        print(f"  (копия старого: {kopiya.name})")
    put.write_text(novyy, encoding="utf-8")

    print("✓ сессия 17.09 записана в БИРЖА.md")
    print("    · что чинили в машине и в каноне")
    print("    · четыре свидетеля на один вход")
    print("    · замер: 3 года, 69 входов, где именно теряется")
    print("    · итог: вход ловит верно, долг — мера стопа")
    return 0


if __name__ == "__main__":
    kod = main()
    podozhdat()
    sys.exit(kod)
