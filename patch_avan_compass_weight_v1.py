# -*- coding: utf-8 -*-
"""
patch_avan_compass_weight_v1.py
────────────────────────────────────────────────────────────────────
ЧИНИТ (разбор канона Котина, 2026-07-11): промт Авантюриста (A07)
дословно давал модели право ОТМЕНИТЬ компас — «что компас значит для
тебя сейчас, решаешь ты» — и отдельно учил часто идти против Паникёра.
По логам тестера (XAUUSD H1/H4) модель прочитала это не как «взвесь
своим суждением», а как «компас необязателен»: в разобранных сессиях
Авантюрист входил LONG почти независимо от знака компаса, включая
случаи, где Искра прямым текстом объявляла медвежий разворот. Итог —
систематические стопы, не редкая контрарианская удача.

Котин (первоисточник): медвежий разворотный бар → SELL-стоп ниже его
Low. Направление разворота — не мнение, а факт структуры. «Ранний,
автономный» характер Ильи (§6.2, конец волны C) — законная черта, но
она про ВРЕМЯ входа (раньше остальных), не про ОТМЕНУ направления.

ЛЕЧЕНИЕ — два прицельных места, голос и характер Ильи не тронуты:

  1) «Что компас значит для тебя, решаешь ты» → компас остаётся
     советом школы, но идти ПРОТИВ него — явно назван РЕДКИМ и ДОРОГИМ
     шагом (у'же стоп, меньше лот), не default-реакцией. Идти ЗА
     компасом — назван обычным хлебом (чаще).

  2) «Паникёр кричит — ты часто делаешь наоборот» → уточнено: наоборот
     толпе — про НАСТРОЕНИЕ (жадность/паника), не про НАПРАВЛЕНИЕ.
     Компас не в ведении Паникёра — фейдить толпу можно ВНУТРИ
     стороны компаса, не против него.

Идемпотентно. Маркер AVAN_COMPASS_WEIGHT_V1. Бэкап рядом (.bak).
Запуск из КОРНЯ репы (Windows/PowerShell):
    python patch_avan_compass_weight_v1.py
"""
from __future__ import annotations
import sys
from pathlib import Path

MARKER = "AVAN_COMPASS_WEIGHT_V1"
TARGET = (Path("GRONDHEIM_CITY") / "Биржа" / "цеха" / "торговый_хаос" /
          "слоты" / "A07" / "промпт.md")

OLD_1 = (
    "Глобальный тренд — старший таймфрейм — компас школы. Что компас значит для\n"
    "тебя сейчас, решаешь ты.\n"
)
NEW_1 = (
    "<!-- " + MARKER + " -->\n"
    "Глобальный тренд — старший таймфрейм — компас школы. Идти ЗА\n"
    "компасом — твой обычный хлеб, случается чаще всего. Идти ПРОТИВ\n"
    "него — не запрещено, но это отдельная, редкая ставка, не рефлекс:\n"
    "ты видишь, что компас говорит одно, а твоя раскладка — другое, и\n"
    "осознанно платишь за расхождение — стоп теснее, лот меньше. Компас\n"
    "не наряд, но и не мнение соседа, которое можно не услышать.\n"
)

OLD_2 = (
    "не команда. Паникёр кричит — ты слышишь его как фоновый шум толпы и часто\n"
    "делаешь наоборот.\n"
)
NEW_2 = (
    "не команда. Паникёр кричит — ты слышишь его как фоновый шум толпы и часто\n"
    "делаешь наоборот.\n"
    "\n"
    "<!-- " + MARKER + " -->\n"
    "Его крик про НАСТРОЕНИЕ толпы (жадность, паника) — не про\n"
    "НАПРАВЛЕНИЕ. Компас не в его ведении. Фейдишь толпу ВНУТРИ стороны\n"
    "компаса, не против неё — жадность на вершине при компасе BEAR это\n"
    "твой сигнал шортить раньше остальных, не повод покупать против\n"
    "компаса.\n"
)


def main() -> int:
    if not TARGET.exists():
        print(f"✗ не нашёл {TARGET}")
        print("  запусти из КОРНЯ репы (там, где папка GRONDHEIM_CITY).")
        return 1

    src = TARGET.read_text(encoding="utf-8")

    if MARKER in src:
        print(f"✓ уже пропатчено ({MARKER}) — ничего не делаю.")
        return 0

    missing = []
    if OLD_1 not in src:
        missing.append("блок про компас школы")
    if OLD_2 not in src:
        missing.append("блок про Паникёра")
    if missing:
        print(f"✗ не нашёл ожидаемые блоки: {', '.join(missing)}.")
        print("  Возможно, промт уже правился вручную. Проверь разделы "
              "«ВОТ СИСТЕМА» и «ВОТ СЕЙЧАС» в "
              "GRONDHEIM_CITY/.../A07/промпт.md.")
        return 2

    bak = TARGET.with_suffix(TARGET.suffix + ".bak")
    if not bak.exists():
        bak.write_text(src, encoding="utf-8")
        print(f"• бэкап: {bak}")
    else:
        print(f"• бэкап уже был: {bak} (не перезаписываю)")

    out = src.replace(OLD_1, NEW_1, 1).replace(OLD_2, NEW_2, 1)
    TARGET.write_text(out, encoding="utf-8")
    print(f"✓ {TARGET}: компас теперь взвешенный совет, не отменяемая опция.")
    print(f"  Маркер идемпотентности: {MARKER}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
