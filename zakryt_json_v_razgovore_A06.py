# -*- coding: utf-8 -*-
# zakryt_json_v_razgovore_A06.py — закрывает дыру, из-за которой Илья
# в чате мог ответить сырым JSON вместо разговора.
#
# Кладётся в КОРЕНЬ репозитория (рядом с папками Биржа/ и GRONDHEIM_CITY/).
# Запуск из PowerShell, из корня:   python zakryt_json_v_razgovore_A06.py
#
# Найдено 12.09 на живом логе: сразу после «прогона по истории» Шеф
# спросил Илью по-человечески — тот ответил {"narrative":...,
# "diary_entry":...}. Причина: явный запрет «никакого JSON» стоит в
# chat_with_brut только в ветке, когда есть last_run (память о
# последнем решении из кнопки РЫНОК). А `прогон_по_истории` last_run
# никогда не заполняет — своя, отдельная память. Значит сразу после
# теста чат падал в слабую ветку «РАБОЧИЙ РЕЖИМ», где запрет на JSON
# — одна проходная фраза, а не прямое опровержение схемы
# {narrative, diary_entry}, которая лежит открытым текстом в самом
# промпт.md, в блоке «КАК ТЫ ОТВЕЧАЕШЬ». Наглядная схема в промпте
# перебивала фразу вскользь.
#
# Что правит: в слабую ветку добавляется тот же прямой запрет, что
# уже стоит и работает в сильной ветке (когда last_run есть) — без
# него ссылка на «КАК ТЫ ОТВЕЧАЕШЬ» ничем не отменяется.
#
# Ничего не удаляет. Кладёт рядом копию мозг.py.bak_json_razgovor.
# Запускать можно сколько угодно раз.

import shutil
import sys
from pathlib import Path

KOREN = Path(__file__).resolve().parent
MOZG_A06 = (KOREN / "GRONDHEIM_CITY" / "Биржа" / "цеха" /
            "торговый_хаос" / "слоты" / "A06" / "мозг.py")

BYLO = (
    '            "\\n\\n=== РАБОЧИЙ РЕЖИМ ===\\n"\n'
    '            "Ты ещё не смотрел стол в этой сессии. Если Шеф спрашивает про "\n'
    '            "рынок — скажи, что нужно нажать РЫНОК. Живым голосом, без JSON."\n'
)

STALO = (
    '            "\\n\\n=== РАБОЧИЙ РЕЖИМ ===\\n"\n'
    '            "Ты ещё не смотрел стол в этой сессии. Если Шеф спрашивает про "\n'
    '            "рынок — скажи, что нужно нажать РЫНОК. Живым голосом, без JSON.\\n\\n"\n'
    '            # ZAKRYT_JSON_V_RAZGOVORE_V1: без этой явной отмены схема\n'
    '            # {narrative, diary_entry} из "КАК ТЫ ОТВЕЧАЕШЬ" ничем не\n'
    '            # перебивалась — фраза "без JSON" выше проигрывала наглядному\n'
    '            # фрагменту кода в самом промпте.\n'
    '            "=== СЕЙЧАС РАЗГОВОР, А НЕ РАБОТА ===\\n"\n'
    '            "Блок «КАК ТЫ ОТВЕЧАЕШЬ» со схемой полей — про РАБОТУ по "\n'
    '            "кнопке РЫНОК. Сейчас с тобой разговаривают. Никакого JSON, "\n'
    '            "никаких полей решения, никаких фигурных скобок — просто "\n'
    '            "ответь словами на то, что спросили."\n'
)


def main() -> int:
    if not MOZG_A06.exists():
        print(f"✗ нет файла: {MOZG_A06} — запускать из корня репозитория")
        return 1

    with open(MOZG_A06, "r", encoding="utf-8", newline="") as f:
        tekst = f.read()
    crlf = "\r\n" in tekst

    bylo = BYLO.replace("\n", "\r\n") if crlf else BYLO
    stalo = STALO.replace("\n", "\r\n") if crlf else STALO

    if bylo in tekst:
        tekst = tekst.replace(bylo, stalo, 1)
        kopiya = MOZG_A06.with_suffix(MOZG_A06.suffix + ".bak_json_razgovor")
        if not kopiya.exists():
            shutil.copy2(MOZG_A06, kopiya)
            print(f"  (копия старого: {kopiya.name})")
        with open(MOZG_A06, "w", encoding="utf-8", newline="") as f:
            f.write(tekst)
        print("✓ закрыт JSON-разговор A06 (ветка «ещё не смотрел стол»)")
        return 0
    elif stalo in tekst:
        print("· уже починено")
        return 0
    else:
        print("✗ не нашёл ожидаемое место в мозг.py — файл мог измениться,"
              " скажи Брату, поправим по месту")
        return 1


if __name__ == "__main__":
    sys.exit(main())
