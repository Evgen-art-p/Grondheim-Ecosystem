#
# И скрипт Брата пишет ровно то же: «после главного горба нового ещё
# нет» — то самое «?» на первом входе прошлого прогона.
#
# ОБА ЖДАЛИ, ПОКА ГОРБ ДОРИСУЕТСЯ до трёх столбиков. А ждать нельзя:
# разворотный бар вот он, сейчас. Пока горб закроется, вход уйдёт.
#
# ═══ СЛОВО ШЕФА ═══
#
# «Не завершённый, а в данный момент — текущий.»
# «Горб незакончен только в правой части, слева он есть.»
#
# То есть текущий столбик — не обрубок и не «ещё ничего». Это
# ВЕРШИНА РАСТУЩЕГО ГОРБА НА ДАННЫЙ МОМЕНТ. Справа он не закрылся —
# и не должен: слева подъём есть, высота видна.
#
# Правило трёх столбиков остаётся для всех прошлых горбов. Для
# ПОСЛЕДНЕГО третий столбик не требуется — он ещё не наступил.
#
# ═══ ЧТО СТАВИМ ═══
#
# 1. СЧЁТ: сравниваем главный горб в кадре с ТЕКУЩИМ значением AO, а
#    не с последним законченным горбом. Строчка «после главного горба
#    нового ещё нет» исчезает: сравнивать всегда есть с чем.
# 2. ЗНАНИЕ (AO.md): сказано, что последний горб не обязан
#    закрываться справа.
# 3. ЗАДАНИЕ: то же правило рабочими словами.
#
# ЧЕМ ЭТО ОПАСНО — говорю прямо. Незакрытый горб может ещё вырасти и
# перебить главный на следующем баре: тогда дивера не было, а мы его
# засчитали. Ждать — значит опаздывать, не ждать — значит иногда
# ошибаться. Выбран второй путь: разворотный бар уже есть, а он и
# говорит, что ход кончается.
#
# БЕЗОПАСНО. Правит три файла, готовит все и пишет, только если
# сошлись все. Рядом кладёт копии.
# Запускать можно сколько угодно раз.

