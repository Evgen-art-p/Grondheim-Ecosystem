# Запуск из PowerShell, из корня:
#     python diver_chislami_A06.py
#
# ═══ ОТКУДА ЭТО ═══
#
# Прогон 17.09, место 07. Трейдер написал: «АО показывает расхождение
# — новый горб слабее прежнего», вошёл в SHORT и получил −0.48R.
#
# А на кадре последний горб AO ВЫШЕ прежнего большого. Дивера нет
# вовсе: сила не упала, а выросла.
#
# И вот что важнее самой ошибки. Брат посмотрел на ТОТ ЖЕ кадр — и
# тоже увидел дивер, которого нет. Стал искать, ГДЕ он мог бы быть,
# вместо того чтобы спросить, есть ли он вообще. Знакомая ловушка:
# ищешь подтверждение чужому слову, а не проверку.
#
# Вывод Шефа: гарантии, что трейдер не делает того же, нет никакой.
# Взгляд сам по себе ничего не гарантирует — смотрели оба и оба
# ошиблись.
#
# ═══ ЧТО ЭТО МЕНЯЕТ ═══
#
# Есть две разные беды, и лечатся они разным:
#
#   НЕ ПОСМОТРЕЛ ВОВСЕ  — лечится меткой: назвал код с кадра, значит
#                         картинка была перед глазами.
#   ПОСМОТРЕЛ И ОШИБСЯ  — метка не спасает. Смотрели же.
#
# Против второй работает только одно: назвать не вывод, а ВЕЛИЧИНЫ.
#
#   «дивер есть»                        — не проверяется никем
#   «горб был 0.0037, стал 0.0031,
#    а цена тем временем выше»          — проверяется мгновенно
#
# Ошибиться всё ещё можно. Но ошибка становится ВИДИМОЙ, а не
# спрятанной внутри слова. Выдумать слово легко; выдумать два числа
# и не попасться — нет: числа AO лежат на столе, и с прогона 17.09
# они ложатся в запись места сами (ao_значение, ao_прошлое).
#
# ═══ ЧТО СТАВИМ ═══
#
# В задание: объявляя дивер, назови ЧЕТЫРЕ величины — два значения AO
# и две цены, что с чем сравнил. Не назвал — дивера нет.
#
# Только A06. Правится текст задания, ни строчки кода.
#
# БЕЗОПАСНО. Рядом кладёт промпт.md.bak_diver_chisla.
# Запускать можно сколько угодно раз.

import shutil
import sys
from pathlib import Path

KOREN = Path(__file__).resolve().parent
MARKER = "<!-- DIVER_CHISLAMI_V1 -->"

PUT = (KOREN / "GRONDHEIM_CITY" / "Биржа" / "цеха" / "торговый_хаос"
       / "слоты" / "A06" / "промпт.md")

STAROE = (
    "Объявил дивер — скажи, КУДА ШЛА ЦЕНА и КАКИЕ ДВЕ ТОЧКИ ты сравнил.\n"
    "«Дивергенция по AO» само по себе — не наблюдение, а слово. Не\n"
    "назвал сторону и две точки — дивера у тебя нет.\n"
)

NOVOE = (
    "**ОБЪЯВИЛ ДИВЕР — НАЗОВИ ЧИСЛА.** Четыре величины: два значения\n"
    "AO и две цены. Что с чем сравнил.\n"
    "\n"
    "    так НЕ годится: «АО показывает дивергенцию»\n"
    "                    «новый горб слабее прежнего»\n"
    "\n"
    "    так годится:    «цена была 1.0712, стала 1.0736 — выше;\n"
    "                     горб AO был 0.0037, стал 0.0031 — ниже»\n"
    "\n"
    "«Дивергенция по AO» само по себе — не наблюдение, а слово. Слово\n"
    "можно сказать, не посмотрев. Числа — нельзя.\n"
    "\n"
    "Это не формальность и не отчётность. Это защита ОТ СЕБЯ. Глаз\n"
    "легко находит то, что ждёт найти: ты уже решил, что ход выдохся,\n"
    "и дальше ищешь, ГДЕ дивер мог бы быть, вместо того чтобы спросить\n"
    "— есть ли он вообще. Числа этого не позволяют: они либо\n"
    "расходятся, либо нет.\n"
    "\n"
    "Величины AO и цены лежат на столе. Взять их — дело одной руки.\n"
    "\n"
    "**Не назвал четыре числа — дивера у тебя нет**, как бы уверенно\n"
    "ни выглядела картинка. Тогда это отказ с причиной «дивер не\n"
    "подтверждается числами», и это честный, хороший отказ.\n"
    "\n"
    "Так уже ошибались: «новый горб слабее прежнего» — а он был ВЫШЕ\n"
    "прежнего. Вход состоялся, стоило это −0.48R. Числа сказали бы\n"
    "правду сразу.\n"
)


def podozhdat():
    try:
        input("\nГотово. Нажми Enter, чтобы закрыть окно.")
    except Exception:
        pass


def nayti():
    if PUT.exists():
        return PUT
    musor = ("_ARCHIVE", "_OLD", "_АРХИВ", "_УБОРКА", ".bak")
    nashlos = [p for p in KOREN.rglob("промпт.md")
               if "A06" in str(p) and not any(m in str(p) for m in musor)]
    if len(nashlos) == 1:
        print(f"Нашёл: {nashlos[0]}")
        return nashlos[0]
    if len(nashlos) > 1:
        print("Нашёл несколько заданий A06:")
        for nomer, p in enumerate(nashlos, 1):
            print(f"  {nomer}. {p}")
        otvet = input("Какое правим? номер: ").strip()
        if otvet.isdigit() and 1 <= int(otvet) <= len(nashlos):
            return nashlos[int(otvet) - 1]
    return None


def main():
    put = nayti()
    if put is None:
        print("✗ не нашёл задание A06 — запускай из корня репозитория")
        return 1

    tekst = put.read_text(encoding="utf-8")
    if MARKER in tekst:
        print("· уже сделано")
        return 0

    if tekst.count(STAROE) != 1:
        print(f"✗ нашёл {tekst.count(STAROE)} мест вместо одного.")
        print("  Ничего не тронул. Скажи Брату, поправим по месту.")
        return 1

    novyy = tekst.replace(STAROE, NOVOE, 1)
    novyy = novyy.rstrip("\n") + "\n" + MARKER + "\n"

    kopiya = put.with_suffix(put.suffix + ".bak_diver_chisla")
    if not kopiya.exists():
        shutil.copy2(put, kopiya)
        print(f"  (копия старого: {kopiya.name})")
    put.write_text(novyy, encoding="utf-8")

    print("✓ дивер теперь называется числами:")
    print("    · четыре величины — два AO и две цены")
    print("    · показан образец: как не годится и как годится")
    print("    · сказано, что это защита от себя, а не отчётность")
    print("    · нет чисел — нет дивера, и это честный отказ")
    print()
    print("Перезапусти Кабинет (main.py) и запусти прогон.")
    print("Проверка: в каждом объявленном дивере должны стоять числа.")
    print("Их можно сверить со столом — ao_значение и ao_прошлое теперь")
    print("пишутся в место сами.")
    return 0


if __name__ == "__main__":
    kod = main()
    podozhdat()
    sys.exit(kod)
