def _naiti(rel_suffix: str) -> list[Path]:
    """Ищет файлы, чей путь оканчивается на rel_suffix, по всему дереву."""
    found = []
    for p in REPO_ROOT.rglob("*"):
        if p.is_file() and str(p).replace("\\", "/").endswith(rel_suffix):
            found.append(p)
    return found


def _backup(path: Path):
    bak = path.with_suffix(path.suffix + ".bak_vzglyad")
    if not bak.exists():
        bak.write_text(path.read_text(encoding="utf-8"), encoding="utf-8")


def patch_prompt(path: Path) -> bool:
    text = path.read_text(encoding="utf-8")
    changed = False

    if "## ВОТ КАК СМОТРЯТ" not in text:
        if STARIY_ANCHOR not in text:
            print(f"  ⚠️  {path}: не нашёл «## ВОТ СИСТЕМА» — раздел не вставлен")
        else:
            text = text.replace(STARIY_ANCHOR, VZGLYAD_BLOK + STARIY_ANCHOR, 1)
            changed = True
            print(f"  ✅ {path}: раздел «ВОТ КАК СМОТРЯТ» вставлен")
    else:
        print(f"  ⏭  {path}: раздел уже стоит, пропускаю")

    if STARAYA_STROKA in text:
        text = text.replace(STARAYA_STROKA, NOVAYA_STROKA, 1)
        changed = True
        print(f"  ✅ {path}: строка «выбрал — держись» заменена")
    elif "может быть разным — это твоё" not in text:
        print(f"  ⚠️  {path}: старую строку не нашёл (возможно, уже правлена вручную)")

    if STARIY_PASTI in text:
        text = text.replace(STARIY_PASTI, NOVYY_PASTI, 1)
        changed = True
        print(f"  ✅ {path}: абзац про пасть Аллигатора заменён (простое чтение фазы)")
    elif "уточнено 05.09" not in text:
        print(f"  ⚠️  {path}: старый абзац про пасть не нашёл (возможно, уже правлен вручную)")

    if changed:
        _backup(path)
        path.write_text(text, encoding="utf-8")
    return changed


def patch_a06_mozg(path: Path) -> bool:
    text = path.read_text(encoding="utf-8")
    changed = False

    if SEC61_A in text:
        text = text.replace(SEC61_A, SEC61_A_NEW, 1)
        changed = True
        print(f"  ✅ {path}: первое упоминание §6.1 заменено")
    if SEC61_B in text:
        text = text.replace(SEC61_B, SEC61_B_NEW, 1)
        changed = True
        print(f"  ✅ {path}: второе упоминание §6.1 заменено")

    if not changed:
        print(f"  ⏭  {path}: §6.1 не найдено — уже правлено или структура иная")
    else:
        _backup(path)
        path.write_text(text, encoding="utf-8")
    return changed


def main():
    print("=== UZAKONIT_VZGLYAD_V1 ===\n")

    print("1) промпт.md — A06/A07/A08:")
    prompts = _naiti("слоты/A06/промпт.md") + \
              _naiti("слоты/A07/промпт.md") + \
              _naiti("слоты/A08/промпт.md")
    if not prompts:
        print("  ❌ ни одного промпт.md не найдено — запускать из корня репо!")
    for p in prompts:
        patch_prompt(p)

    print("\n2) A06/мозг.py — §6.1:")
    mozgi = _naiti("слоты/A06/мозг.py")
    if not mozgi:
        print("  ❌ A06/мозг.py не найден")
    for p in mozgi:
        patch_a06_mozg(p)

    print("\nГотово. Резервные копии — рядом с файлами, суффикс .bak_vzglyad.")
    print("Повторный запуск ничего не сломает — правки идемпотентны.")


if __name__ == "__main__":
    main()
