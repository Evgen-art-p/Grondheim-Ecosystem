import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent

VZGLYAD_BLOK = '''## ВОТ КАК СМОТРЯТ

Справа от тебя нет ничего. Всё, что есть, — слева.

Сперва общий вид: виден тренд или нет. Растёт, падает, топчется — это
видно глазами. Не видно — поднимись на этаж-два выше и смотри там,
признаки те же.

Старший этаж говорит не только КУДА идёт цена, но и ГДЕ ты стоишь: в
его импульсе или в его откате. Это разные работы, и обе законные. По
тренду — берёшь конец наших мелких откатов. Против старшего — можно
взять его волну C. Что брать сегодня, решает не правило, а красота:
что тебе видно.

Точка ноль — самый крайний экстремум слева, взятый по направлению.
Работаешь на покупку — нижний, на продажу — верхний. От неё и
стартуешь.

Дальше смотришь от точки ноль до себя, слева направо: что успело
произойти. Импульс сформирован или только начался. Считаются изломы —
три их уже или нет. Чисел и порогов здесь нет, рынок нелинейный.

Слом точки — конец ноги, а не конец работы. Тренд после него идёт
дальше, и у следующей ноги будет своя точка.

Индикаторы — компас, а не сигнал. Аллигатор про тренд, AO про волну,
MFI про сам последний закрытый бар. Они подтверждают то, что уже видно
на цене, и никогда не говорят «входи». Прибор спорит с глазом — прав
глаз.

Входов на одной и той же структуре несколько, и они лежат рядом без
хозяина. Разница между ними — риск: чем раньше вход, тем дороже и тем
больше нужно смелости. Так же и доливка: можно строго по правилу, а
можно нырять вторыми входами в глубине. Вариантов работы много.

Город кладёт тебе на стол факты. Комбинацию из них собираешь ты — по
своей смелости, а не по бумаге. И собрать её в другой раз иначе —
твоё право, а не сбой.

Не предсказывай исход — это грубая ошибка. Думай, что рынок делает
СЕЙЧАС и куда идёт сейчас, иди с ценой взглядом. Не мониторь каждый
бар последовательно — только если некрон звякнул.

Если стопануло три раза подряд на одном месте — не ставь в четвёртый
раз по инерции. Спроси себя: там ли ты вообще стоишь.

---

'''

STARAYA_STROKA = (
    "Выбираешь ты. Выбрал — держись: смена входа от случая к случаю значит,\n"
    "что входа у тебя нет вовсе.\n\n"
)

NOVAYA_STROKA = (
    "Выбираешь ты, и выбор от раза к разу может быть разным — это твоё\n"
    "право, а не сбой.\n\n"
)

STARIY_ANCHOR = "## ВОТ СИСТЕМА\n\n"

SEC61_A = (
    "сам СЧИТАЕТ свой вход по §6.1 (фрактал за пастью): entry/stop"
)
SEC61_A_NEW = (
    "сам СЧИТАЕТ свой вход по канону, который сам выбрал (три места\n"
    "#     входа лежат в знаниях, без хозяина): entry/stop"
)

SEC61_B = (
    "выносит вердикт по §6.1 (фрактал за пастью) → кладёт"
)
SEC61_B_NEW = (
    "выносит вердикт по канону, который сам выбрал → кладёт"
)


def _naiti(rel_suffix: str) -> list[Path]:
    """Ищет файлы, чей путь оканчивается на rel_suffix, по всему дереву."""
    found = []
    for p in REPO_ROOT.rglob("*"):
        if p.is_file() and str(p).replace("\\", "/").endswith(rel_suffix):
            found.append(p)
    return found


def _backup(path: Path):
    bak = path.with_suffix(path.suffix + ".bak_vzglyad")
    if not bak.exists():
        bak.write_text(path.read_text(encoding="utf-8"), encoding="utf-8")


def patch_prompt(path: Path) -> bool:
    text = path.read_text(encoding="utf-8")
    changed = False

    if "## ВОТ КАК СМОТРЯТ" not in text:
        if STARIY_ANCHOR not in text:
            print(f"  ⚠️  {path}: не нашёл «## ВОТ СИСТЕМА» — раздел не вставлен")
        else:
            text = text.replace(STARIY_ANCHOR, VZGLYAD_BLOK + STARIY_ANCHOR, 1)
            changed = True
            print(f"  ✅ {path}: раздел «ВОТ КАК СМОТРЯТ» вставлен")
    else:
        print(f"  ⏭  {path}: раздел уже стоит, пропускаю")

    if STARAYA_STROKA in text:
        text = text.replace(STARAYA_STROKA, NOVAYA_STROKA, 1)
        changed = True
        print(f"  ✅ {path}: строка «выбрал — держись» заменена")
    elif "может быть разным — это твоё" not in text:
        print(f"  ⚠️  {path}: старую строку не нашёл (возможно, уже правлена вручную)")

    if changed:
        _backup(path)
        path.write_text(text, encoding="utf-8")
    return changed


def patch_a06_mozg(path: Path) -> bool:
    text = path.read_text(encoding="utf-8")
    changed = False

    if SEC61_A in text:
        text = text.replace(SEC61_A, SEC61_A_NEW, 1)
        changed = True
        print(f"  ✅ {path}: первое упоминание §6.1 заменено")
    if SEC61_B in text:
        text = text.replace(SEC61_B, SEC61_B_NEW, 1)
        changed = True
        print(f"  ✅ {path}: второе упоминание §6.1 заменено")

    if not changed:
        print(f"  ⏭  {path}: §6.1 не найдено — уже правлено или структура иная")
    else:
        _backup(path)
        path.write_text(text, encoding="utf-8")
    return changed


def main():
    print("=== UZAKONIT_VZGLYAD_V1 ===\n")

    print("1) промпт.md — A06/A07/A08:")
    prompts = _naiti("слоты/A06/промпт.md") + \
              _naiti("слоты/A07/промпт.md") + \
              _naiti("слоты/A08/промпт.md")
    if not prompts:
        print("  ❌ ни одного промпт.md не найдено — запускать из корня репо!")
    for p in prompts:
        patch_prompt(p)

    print("\n2) A06/мозг.py — §6.1:")
    mozgi = _naiti("слоты/A06/мозг.py")
    if not mozgi:
        print("  ❌ A06/мозг.py не найден")
    for p in mozgi:
        patch_a06_mozg(p)

    print("\nГотово. Резервные копии — рядом с файлами, суффикс .bak_vzglyad.")
    print("Повторный запуск ничего не сломает — правки идемпотентны.")


if __name__ == "__main__":
    main()
