# -*- coding: utf-8 -*-
# MARKER: PEREEZD_VERSHINY_TIKHIY_V1
"""
ПЕРЕЕЗД ВЕРШИНЫ ПЕРЕСТАЁТ БУДИТЬ ТРЕЙДЕРОВ.

ЧТО БЫЛО СЛОМАНО
────────────────
Вчерашняя починка (VERSHINA_NE_NIZHE_KRAYA_V1) правильно подтягивает
вершину волны 1, когда цена ушла дальше. Но каждый такой переезд
поднимался как СОБЫТИЕ и будил обоих трейдеров.

А в сильном импульсе вершина ползёт за ценой почти каждый бар. Из
прогона Шефа, живьём:

    вершина волны 1 сдвинулась → 45 бар. от точки
    вершина волны 1 сдвинулась → 48 бар.
    вершина волны 1 сдвинулась → 49 бар.
    вершина волны 1 сдвинулась → 50 бар.
    вершина волны 1 сдвинулась → 51 бар.
    вершина волны 1 сдвинулась → 57 бар.

Шесть побудок подряд там, где по сути НИЧЕГО НЕ ПРОИЗОШЛО: волна как
шла, так и идёт, просто её край переехал. Каждая побудка — запрос к
модели, и не один, а по трейдеру на каждого. Деньги Шефа сгорали на
шум: прогон встал на 25 сентября, не дойдя до конца года.

И сами трейдеры это видели. Их ответы на такие побудки — «откат
слишком мелкий», «нет разворотного бара», «жду коррекции». Их звали
смотреть на то, на что смотреть было незачем.

ЧТО ДЕЛАЕТ ПАТЧ
───────────────
Переезд вершины считается ТИХО: состояние обновляется как и раньше,
на столе всегда свежая вершина, глубина отката честная — но трейдера
не дёргают.

Событием остаётся ровно то, что событие и есть:
    · волна 1 кончилась ПЕРВЫЙ раз — будим (есть от чего ждать откат)
    · откат кончился — будим (это третье место, ради него всё)
    · точка родилась, сделка закрылась, заявка висит — как было

Это ровно слово Шефа, записанное в самом файле: «побарный мониторинг —
ошибка большинства трейдеров; трейдер ждёт событие, а не пялится в
каждую свечу». Переезд края событием не был — им его сделал вчерашний
патч, по недосмотру.

ЧТО НЕ МЕНЯЕТСЯ
───────────────
Сама починка вершины остаётся: вершина по-прежнему не может быть ниже
того, куда цена дошла. Меняется ТОЛЬКО одно — будить на этом или нет.

Идемпотентен. .bak рядом. Путь ищет сам.
"""
import ast
import shutil
import sys
from pathlib import Path

MARKER = "PEREEZD_VERSHINY_TIKHIY_V1"


def _nayti_birzhu() -> Path:
    primety = ("council.py",)
    nashli = []
    korni = []
    for k in (Path(__file__).resolve().parent, Path.cwd().resolve()):
        if k not in korni:
            korni.append(k)
    for koren in korni:
        mesta = [koren]
        try:
            mesta += [x for x in koren.iterdir() if x.is_dir()]
        except OSError:
            pass
        for p in mesta:
            if all((p / f).exists() for f in primety) and p not in nashli:
                nashli.append(p)
    if len(nashli) == 1:
        return nashli[0]
    if not nashli:
        print("Не нашёл папку Биржа рядом со скриптом.")
        s = input("Перетащи сюда папку Биржа и нажми Enter:\n> ")
        p = Path(s.strip().strip('"').strip("'"))
        if (p / "council.py").exists():
            return p
        raise SystemExit("не та папка — там нет council.py")
    print("Нашёл несколько:")
    for i, p in enumerate(nashli, 1):
        print(f"  {i}. {p}")
    return nashli[int((input("которая? ").strip() or "1")) - 1]


YAKOR = '            if kv.get("сдвинулась"):\n                return {"будим": True,\n                        "почему": f"{_kray} волны 1 сдвину{_ok} → "\n                                  f"{kv.get(\'цена\')} "\n                                  f"({kv.get(\'баров_от_точки\')} бар. "\n                                  f"от точки)"}\n'
NOVOE = '            # PEREEZD_VERSHINY_TIKHIY_V1: переезд края — НЕ СОБЫТИЕ.\n            #\n            # Вершина подтягивается за ценой (VERSHINA_NE_NIZHE_KRAYA_V1)\n            # и в сильном импульсе едет чуть не каждый бар. Раньше на\n            # каждый такой переезд будили обоих трейдеров — шесть побудок\n            # подряд там, где волна просто продолжается. Каждая побудка —\n            # запрос к модели за деньги Шефа, а трейдеру показать нечего:\n            # он отвечал «откат слишком мелкий, жду».\n            #\n            # Слово Шефа, записанное строкой выше: трейдер ждёт СОБЫТИЕ,\n            # а не пялится в каждую свечу. Край, который ползёт за ценой,\n            # событием не является — состояние обновляется молча, на\n            # столе всегда свежая вершина, глубина отката честная.\n            #\n            # Событие впереди своё: откат кончился (KONEC_VOLNY_2_V1).\n            # Вот тогда и позовём.\n            if kv.get("сдвинулась"):\n                return {"будим": False,\n                        "почему": f"{_kray} волны 1 переехал{\'а\' if _st == \'BULL\' else \'о\'} "\n                                  f"на {kv.get(\'цена\')} — волна идёт, "\n                                  f"событие впереди"}\n'



def main():
    b = _nayti_birzhu()
    print(f"\nБиржа: {b}\n")
    p = b / "council.py"
    text = p.read_text(encoding="utf-8")

    if MARKER in text:
        print("  . council.py: уже накачен, пропускаю")
    else:
        if text.count(YAKOR) != 1:
            raise SystemExit(
                f"  X council.py: якорь не найден или не один "
                f"({text.count(YAKOR)}). Файл НЕ ТРОНУТ.")
        novyy = text.replace(YAKOR, NOVOE)
        novyy = novyy.rstrip() + "\n\n# " + MARKER + " - marker\n"
        ast.parse(novyy)
        shutil.copy2(p, p.with_suffix(".py.bak_tikho"))
        p.write_text(novyy, encoding="utf-8")
        print("  + council.py: переезд вершины теперь тихий (.bak_tikho рядом)")

    print("\nГотово. Перезапусти город.")
    print("В прогоне больше НЕ должно быть строк «вершина волны 1")
    print("сдвинулась» с вопросом трейдеру — вершина едет молча.")
    print("Событий останется: точка родилась · волна 1 кончилась ·")
    print("откат кончился · сделка закрылась.")


if __name__ == "__main__":
    try:
        main()
    except SystemExit as e:
        print(e)
    except Exception:
        import traceback
        traceback.print_exc()
    if sys.platform.startswith("win"):
        input("\nEnter — закрыть окно ")
