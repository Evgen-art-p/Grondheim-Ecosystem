def _teper() -> str:
    return datetime.now().strftime("%Y%m%d_%H%M%S")


def naiti_koren() -> Path:
    starty = [Path(__file__).resolve().parent, Path.cwd().resolve()]
    for start in starty:
        for kand in [start, *start.parents]:
            if (kand / "GRONDHEIM_CITY" / "локации").is_dir() \
                    and (kand / "ГОРОД" / "rabota.py").is_file():
                return kand
    raise SystemExit("Не нашёл корень репо. Запусти из корня "
                     "Grondheim-Ecosystem.")


def razlozhit_sklad(kuda: Path) -> tuple:
    """Разложить вложенный склад. Что лежит — не трогаем."""
    buf = io.BytesIO(base64.b64decode(SKLAD_B64))
    vzyato, bylo = 0, 0
    kuda.mkdir(parents=True, exist_ok=True)
    with tarfile.open(fileobj=buf, mode="r:gz") as t:
        for chlen in t.getmembers():
            if not chlen.isfile():
                continue
            dannye = t.extractfile(chlen)
            if dannye is None:
                continue
            cel = kuda / chlen.name
            if cel.exists():
                bylo += 1
                continue
            cel.write_bytes(dannye.read())
            vzyato += 1
    return vzyato, bylo


def imena_na_sklade() -> set:
    """Что вообще лежит в патче — до всякой записи на диск."""
    buf = io.BytesIO(base64.b64decode(SKLAD_B64))
    with tarfile.open(fileobj=buf, mode="r:gz") as t:
        return {c.name for c in t.getmembers() if c.isfile()}


def proverit_formulyary() -> list:
    """Сторож: каждое название формуляра обязано лежать на складе."""
    est = imena_na_sklade()
    bedy = []
    for slot, spisok in FORMULYARY.items():
        for f in spisok:
            if f not in est:
                bedy.append(f"{slot} просит «{f}», а на складе такого нет")
    lishnie = est - {f for v in FORMULYARY.values() for f in v}
    for f in sorted(lishnie):
        bedy.append(f"«{f}» лежит на складе, а не нужен никому")
    return bedy


def main() -> None:
    try:
        sys.stdout.reconfigure(encoding="utf-8")  # type: ignore[union-attr]
    except Exception:
        pass

    koren = naiti_koren()
    print(f"Корень: {koren}\n")

    bedy = proverit_formulyary()
    if bedy:
        print("ФОРМУЛЯРЫ НЕ СХОДЯТСЯ СО СКЛАДОМ, на диск не кладу:")
        for b in bedy:
            print(f"  · {b}")
        return
    print(f"Сторож: {len(imena_na_sklade())} файлов на складе, "
          f"все формуляры сходятся.")

    ceh = koren / "GRONDHEIM_CITY" / "Студия" / "цеха" / "турбо"
    if not (ceh / "manifest.json").exists():
        raise SystemExit("Цеха турбо нет — сперва накати ceh_turbo.py")

    # ── склад ─────────────────────────────────────────────────
    vzyato, bylo = razlozhit_sklad(ceh / "знания")
    print(f"Склад: разложено {vzyato}   (уже лежало: {bylo})")

    # ── формуляры в манифест ──────────────────────────────────
    mf = ceh / "manifest.json"
    m = json.loads(mf.read_text(encoding="utf-8"))
    for s in m["слоты"]:
        s["знания"] = FORMULYARY.get(s["слот"], [])
    m["_маркер_знаний"] = MARKER
    m["_note_знания"] = (
        "склад цеха — знания/, один файл одна копия. У места свой "
        "формуляр: в голову идёт не весь склад, а только список. "
        "Правишь файл один раз — видят все, кто его просит."
    )
    novyy = json.dumps(m, ensure_ascii=False, indent=2) + "\n"
    if mf.read_text(encoding="utf-8") == novyy:
        print("Манифест: формуляры уже стоят")
    else:
        bak = mf.with_suffix(f".json.bak_{_teper()}")
        shutil.copyfile(mf, bak)
        mf.write_text(novyy, encoding="utf-8")
        print(f"Манифест: формуляры вписаны, старый в {bak.name}")

    # ── уборка ────────────────────────────────────────────────
    staroe = ceh / "слоты" / "A03" / "знания"
    if staroe.is_dir():
        shutil.rmtree(staroe)
        print("Уборка: слоты/A03/знания убраны — всё на складе")

    ubrano = 0
    for p in (koren / "_АРХИВ_ЧИСТКИ").glob("veo_ustarel_*"):
        shutil.rmtree(p)
        ubrano += 1
    if ubrano:
        print(f"Уборка: Veo3 выброшен ({ubrano} папка из _АРХИВ_ЧИСТКИ)")

    # ── что вышло ─────────────────────────────────────────────
    print("\nФормуляры мест:")
    for s in m["слоты"]:
        print(f"  {s['слот']} · {s['роль']:<14} {len(s['знания'])} названий")

    print("\nГотово. Знания цеха на одном складе, у каждого свой список.\n"
          "шесть·проверено·до·корня")


if __name__ == "__main__":
    main()
