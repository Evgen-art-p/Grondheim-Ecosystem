"""
НАЙДЕНО (06.09, живой разговор с Ильёй): за весь обмен он ни разу не
позвал руку (stol_na_etazhe / pokazat_etazh) — рассказал про старший
этаж и AO из общего впечатления с одной картинки, не проверив ни
цифры, ни другой этаж. Та же болезнь, что была на годовом прогоне в
августе: говорит заученно, не сверяясь со столом.

Причина, скорее всего, здесь: в _GLAZ_RAZGOVOR стоит фраза «смотри на
него и отвечай по нему, а не проси прислать данные». Она писалась
ДО того, как руки появились в разговоре (RUKI_V_RAZGOVORE_V1) — тогда
смысл был один: не проси Шефа прислать график, как человека. Теперь
руки — это его собственный инструмент, а не просьба к Шефу, но фраза
этого не разводит, и модель, похоже, читает «не проси данных» шире,
чем задумано, — и просто не пользуется рукой, которая у неё есть.

Патч добавляет одну уточняющую фразу сразу после существующей, во
всех трёх мозгах (A06/A07/A08 — текст в них одинаковый).

Запускать из корня репозитория:
    python postavit_ruki_v_razgovore_razlichit.py
Идемпотентен — если уточнение уже стоит, файл не трогает.
"""
from __future__ import annotations
from pathlib import Path

SLOTS = ["A06", "A07", "A08"]
REL_PATH = ("GRONDHEIM_CITY/Биржа/цеха/торговый_хаос/слоты/{slot}/мозг.py")

ANCHOR = (
    '    "Перед тобой кадр того рынка, на который ты сейчас смотришь — "\n'
    '    "тот же самый, что видит Шеф.\\n"\n'
    '    "Спрашивают про рынок — смотри на него и отвечай по нему, а не проси "\n'
    '    \'прислать данные.\\n\'\n'
)

# на случай другого стиля кавычек в конкретном файле — второй вариант якоря
ANCHOR_ALT = (
    '    "Перед тобой кадр того рынка, на который ты сейчас смотришь — "\n'
    '    "тот же самый, что видит Шеф.\\n"\n'
    '    "Спрашивают про рынок — смотри на него и отвечай по нему, а не проси "\n'
    '    "прислать данные.\\n"\n'
)

DOBAVKA = (
    '    "Это про ШЕФА — ему присылать не нужно, у тебя перед глазами то же, "\n'
    '    "что и у него. А вот руки (stol_na_etazhe, pokazat_etazh и другие) — "\n'
    '    "это не просьба к Шефу, это твой собственный инструмент. Хочешь "\n'
    '    "сказать что-то про другой этаж, точное число или компас — сначала "\n'
    '    "посмотри рукой, а не рассказывай по памяти: один кадр показывает "\n'
    '    "только твой рабочий этаж, всё остальное — через руки.\\n"\n'
)


def patch_one(path: Path) -> str:
    if not path.exists():
        return f"НЕТ ФАЙЛА: {path}"
    text = path.read_text(encoding="utf-8")
    if "это твой собственный инструмент" in text:
        return f"уже стоит: {path}"

    for anchor in (ANCHOR, ANCHOR_ALT):
        if text.count(anchor) == 1:
            bak = path.with_suffix(path.suffix + ".bak_ruki_razlichit")
            if not bak.exists():
                bak.write_text(text, encoding="utf-8")
            new_text = text.replace(anchor, anchor + DOBAVKA, 1)
            path.write_text(new_text, encoding="utf-8")
            return f"ПРИМЕНЁН: {path}"

    return f"ЯКОРЬ НЕ НАЙДЕН (не тронуто, пришли файл Брату): {path}"


def main() -> None:
    root = Path(__file__).resolve().parent
    for slot in SLOTS:
        p = root / REL_PATH.format(slot=slot)
        print(patch_one(p))


if __name__ == "__main__":
    main()

