from __future__ import annotations
import io
import sys
from pathlib import Path

MARKER = "AVAN_OPORA_NA_OPYT_V1"
NEED = "ROD_PERVYM_V1"

BRAIN = (Path("GRONDHEIM_CITY") / "Биржа" / "цеха" / "торговый_хаос" /
         "слоты" / "A07" / "мозг.py")

# ── 1. ложный указатель «ДНК — ниже» ────────────────────────────
OLD_PTR = '''        "Перед тобой стол и ты сам. Канон у тебя на полке (книга Котина), "
        "твоя ДНК — ниже. Решаешь только ты. По системе сигнал ранней добычи "'''
NEW_PTR = '''        "Перед тобой стол и ты сам. Канон у тебя на полке (книга Котина), "
        # ''' + MARKER + ''': было «твоя ДНК — ниже» — ложь после ROD_PERVYM_V1:
        # род, натура и ЯКОРЯ лежат ВЫШЕ, в блоке «КТО ТЫ». Указатель вёл вниз,
        # в канон — и он думал канонными категориями, а не своей головой.
        "кто ты, твоя натура и твой ОПЫТ — ВЫШЕ, в блоке «КТО ТЫ». "
        "Решаешь только ты. По системе сигнал ранней добычи "'''

# ── 2. сверка с собой перед решением ────────────────────────────
OLD_TAIL = '''        "REJECTED. Никто не подложит тебе готовую цену и не скажет, как "
        "поступить. Выдай строго JSON {narrative, signal, "'''
NEW_TAIL = '''        "REJECTED. Никто не подложит тебе готовую цену и не скажет, как "
        "поступить.\\n\\n"
        # ''' + MARKER + ''': опыт лежал на столе украшением — никто не просил
        # на него опереться. Не рука на его руке: не говорим ЧТО решить,
        # требуем думать СВОЕЙ головой, а не только канонной.
        "СВЕРЬСЯ С СОБОЙ. Прежде чем решить — глянь на свои якоря (блок "
        "«КТО ТЫ»): что ты УЖЕ вынес из похожих входов? Твой опыт оплачен "
        "твоими деньгами. Он не приказ — но и не украшение. Если идёшь "
        "против собственного вывода, скажи об этом в narrative прямо и "
        "своими словами: «иду против своего же — потому что...». Если "
        "опираешься на него — тоже скажи. Молчать о себе не надо.\\n\\n"
        "Выдай строго JSON {narrative, signal, "'''


def main() -> int:
    if isinstance(sys.stdout, io.TextIOWrapper):
        try:
            sys.stdout.reconfigure(encoding="utf-8")
        except Exception:
            pass

    print("═══ ОПОРА НА ОПЫТ — Илья думает своей головой ═══")

    if not BRAIN.exists():
        print(f"✗ не нашёл {BRAIN} — ты в КОРНЕ репы?")
        return 1

    b = BRAIN.read_text(encoding="utf-8")

    if NEED not in b:
        print("✗ сначала patch_avan_rod_pervym_v1.py — без него род лежит")
        print("  СНОСКОЙ В ХВОСТЕ, и указатель «опыт выше» снова соврёт.")
        print("  (В мозге нет маркера ROD_PERVYM_V1 — патч не прогонялся.)")
        return 2

    if MARKER in b:
        print(f"✓ уже пропатчено ({MARKER}) — ничего не делаю.")
        return 0

    for old, what in ((OLD_PTR, "указатель «твоя ДНК — ниже» в задаче"),
                      (OLD_TAIL, "хвост задачи перед требованием JSON")):
        if old not in b:
            print(f"✗ не нашёл блок: {what}. Файл правился вручную? Сверь глазами.")
            return 3

    bak = BRAIN.with_suffix(".py.bak4")
    if not bak.exists():
        bak.write_text(b, encoding="utf-8")
        print(f"• бэкап: {bak}")

    b = b.replace(OLD_PTR, NEW_PTR, 1).replace(OLD_TAIL, NEW_TAIL, 1)
    BRAIN.write_text(b, encoding="utf-8")

    print("✓ мозг A07:")
    print("   • указатель ведёт ВВЕРХ, в живой блок «КТО ТЫ» (было — ложь);")
    print("   • перед решением — СВЕРКА С СОБОЙ: что ты уже вынес из похожих")
    print("     входов? Идёшь против своего вывода — скажи вслух.")
    print(f"   Маркер: {MARKER}")
    print("\nПрогони тестер. Смотри в narrative Авантюриста: появятся ли ЕГО")
    print("слова — «вхожу на open, ретеста не жду», «мой PF 1.071», «я уже")
    print("так платил». Если появятся — Илья сел за стол по-настоящему.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
