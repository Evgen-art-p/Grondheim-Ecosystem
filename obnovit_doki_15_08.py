def _eto_koren(p: Path) -> bool:
    return (p / "БИРЖА.md").exists() and (p / "ЛЕТОПИСЬ_ГРОНДХЕЙМА.md").exists()


def nayti_koren() -> Path:
    zdes = Path(__file__).resolve().parent
    for kand in (zdes, Path.cwd(), *zdes.parents):
        if _eto_koren(kand):
            return kand
    kandidaty = []
    for baza in (zdes.parent, Path.cwd().parent):
        if not baza.is_dir():
            continue
        for d in baza.iterdir():
            if d.is_dir() and _eto_koren(d) and d not in kandidaty:
                kandidaty.append(d)
    if len(kandidaty) == 1:
        if input(f"Нашёл город здесь:\n  {kandidaty[0]}\nЭтот? [Enter=да] "
                 ).strip().lower() in ("", "y", "д", "да"):
            return kandidaty[0]
    elif len(kandidaty) > 1:
        print("Нашёл несколько городов:")
        for i, d in enumerate(kandidaty, 1):
            print(f"  {i}. {d}")
        nom = input("Какой? номер: ").strip()
        if nom.isdigit() and 1 <= int(nom) <= len(kandidaty):
            return kandidaty[int(nom) - 1]
    put = input("Не нашёл сам. Перетащи сюда папку репо и нажми Enter:\n> ")
    p = Path(put.strip().strip('"').strip("'"))
    if _eto_koren(p):
        return p
    print("✗ Это не корень репо")
    sys.exit(1)


def est_marker(koren: Path, marker: str) -> bool:
    """Есть ли маркер в коде города (патч-скрипты не считаем)."""
    for f in koren.rglob("*.py"):
        s = str(f)
        if "_УБОРКА" in s or "_АРХИВ" in s:
            continue
        if f.parent == koren and f.name[:1].islower() and (
                f.name.startswith(("postavit", "ubrat", "obnovit",
                                   "pochinit", "peredvinut", "proverka"))):
            continue
        try:
            if marker in f.read_text(encoding="utf-8", errors="ignore"):
                return True
        except Exception:
            continue
    return False


