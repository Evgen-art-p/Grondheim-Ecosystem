# ─────────────────────────────────────────────────────────────
# DVER_V_METKI_V1 — ТРИ ГОЛОСА В ПРОМПТЕ. Дверь во второй этаж.
#
# TRI_ETAZHA_V1 построил второй этаж: метки лежат в 2_метки/metki.json.
# Но _sobrat_dushu их НЕ ЗНАЕТ — метка запишется, а житель её не
# прочтёт. Этаж есть, двери в него из промпта нет.
#
# ⚠ И ВТОРОЕ, КРУПНЕЕ ДВЕРИ — ПРОМПТ ВРАЛ ЖИТЕЛЮ.
#   Сейчас там дословно:
#     «ТВОЙ ОПЫТ — что ты вынес сам (якоря). Это не правила сверху,
#      это твои же выводы, ОПЛАЧЕННЫЕ ТВОИМИ ДЕНЬГАМИ»
#   А в Anchor_Points лежит РОД — вписанный при рождении рукой Джема
#   (-2/studio/.../A07/core/anchor_points.md: «ВЕЧНЫЕ КОНСТАНТЫ»).
#   Илья ничего не выносил и ничего не оплачивал. Он таким РОДИЛСЯ.
#   Промпт врал ему о его же происхождении — мнение под маской факта.
#   Это IV заповедь. Режем.
#
# ТРИ ГОЛОСА (закон ядра, Брат/README.md):
#   РОД   — «кто ты ЕСТЬ» (не менялось и не меняется)
#   МЕТКИ — «что ты нажил» (с полем ОТКУДА: рынок / учёба / профессия)
#   МАЯКИ — «что замечаешь за собой» (не подтвердилось повтором)
#
# Голоса РАЗНЫЕ — значит модель может их СТОЛКНУТЬ. Медийщик на Бирже
# увидит «что я вынес в монтажной» рядом с «что мне сказал рынок» —
# и это будет спор внутри головы, а не однородная каша.
#
# ЧТО ДЕЛАЕТ:
#   1. Биржа/nositel.py :: _sobrat_dushu — три голоса вместо одного.
#   2. Биржа/nositel.py :: zapisat_vyvod / zapisat_vyvod_pare —
#      передают otkuda="рынок" (голос вывода назван).
#   3. Защита от повтора: сверялась с Anchor_Points + Draft_Anchors.
#      Draft_Anchors больше нет в паспорте (уехали в 3_маяки).
#      Сверка чинится: род + метки + маяки.
#
# ИДЕМПОТЕНТЕН. BACKUP: Биржа/nositel.py.bak_dver
#
# Запуск из корня репо:  python patch_dver_v_metki.py
#
# `шесть·проверено·до·корня`
# ─────────────────────────────────────────────────────────────
