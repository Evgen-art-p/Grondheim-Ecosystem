ROOT = Path(__file__).resolve().parent
NOSITEL = ROOT / "Биржа" / "nositel.py"
MARK = "DVER_V_METKI_V1"


# ═══════════════════════════════════════════════════════════
# НОВЫЙ БЛОК ГОЛОСОВ (заменяет «ногу опыта» + черновики)
# ═══════════════════════════════════════════════════════════

NOVYE_GOLOSA = '''    # ── ТРИ ГОЛОСА (DVER_V_METKI_V1) ────────────────────────────
    # Закон ядра (Брат/README.md): род / метки / маяки — три этажа,
    # три РАЗНЫХ голоса. Раньше здесь был один, и он ВРАЛ: называл
    # род «твоими выводами, оплаченными твоими деньгами». А род вписан
    # при рождении — житель его не выносил и не оплачивал.
    # Голоса разные — значит житель может их СТОЛКНУТЬ.

    # ГОЛОС 1 — РОД. Кто он ЕСТЬ. Не менялось и не меняется.
    yak = stol.get("якоря") or ""
    parts = [x.strip() for x in yak.replace("\\\\n", "\\n").split("\\n") if x.strip()]
    if parts:
        L.append("\\nКТО ТЫ ЕСТЬ — твой род. Не выводы, не уроки: так ты "
                 "устроен(а) с самого начала. Это дно, оно не спорит:")
        for p in parts:
            L.append(f"  • {p}")

    # ГОЛОС 2 — МЕТКИ. Нажитое. ВОТ ЭТО оплачено, и вот здесь голос
    # «твои же выводы» — правда. Поле ОТКУДА даёт разный тон: то, что
    # сказал рынок, звучит иначе, чем то, чему учили.
    metki = stol.get("метки") or []
    if metki:
        L.append("\\nЧТО ТЫ НАЖИЛ САМ — выводы, которых при рождении не "
                 "было. Ты их заработал:")
        for m in metki:
            otk = (m.get("откуда") or "").strip()
            golos = {
                "рынок":  "рынок сказал",
                "учёба":  "чему тебя учили",
            }.get(otk, f"вынес(ла) как {otk}" if otk else "вынес(ла)")
            L.append(f"  • [{golos}] {m.get('текст','')}")
        L.append("Это твоё, оплаченное. Хочешь идти против — иди, "
                 "но знай, что идёшь против себя же.")

    # ГОЛОС 3 — МАЯКИ. Момент. Ещё не вывод (Гл.4.4: один вывод — не опыт).
    chernoviki = stol.get("черновики") or []
    if chernoviki:
        L.append("\\nЗАМЕЧАЮ ЗА СОБОЙ (не подтвердилось повтором — "
                 "наблюдение, не готовый вывод):")
        for d in chernoviki:
            raz = d.get("раз", 1)
            hvost = "" if raz < 2 else f" (уже {raz} раз(а) — похоже на закономерность)"
            L.append(f"  • {d.get('текст','')}{hvost}")

'''


def _zamenit_golosa(src: str) -> tuple:
    """Вырезает старый блок «нога опыта + черновики» и ставит три голоса."""
    nach = src.find("    # ── НОГА ОПЫТА")
    if nach < 0:
        return src, False
    # конец блока — строка про домашний промпт (следующая после черновиков)
    konec = src.find("    if s_domom and stol.get(\"дом\"):", nach)
    if konec < 0:
        return src, False
    return src[:nach] + NOVYE_GOLOSA + src[konec:], True


def _nazvat_golos(src: str) -> tuple:
    """zapisat_vyvod / zapisat_vyvod_pare зовут dopisat_vyvod без otkuda —
    вывод ляжет с умолчанием. Называем голос явно: это РЫНОК судил.

    Ловим ДВА конкретных вызова (проверено на живом файле 13.07):
      pattern=_klyuch_trader(vyvod))   # YAKORYA_DVA_YARUSA_V1
      pattern=_klyuch_sensora(vyvod))  # YAKORYA_DVA_YARUSA_V1
    Строка кончается КОММЕНТАРИЕМ, не скобкой — первый матчер на это
    и попался, отчитавшись «0 вызовов». Правим по факту, не по догадке."""
    n = 0
    for klyuch in ("_klyuch_trader", "_klyuch_sensora"):
        staroe = f"                              pattern={klyuch}(vyvod))"
        novoe = (f"                              pattern={klyuch}(vyvod),\n"
                 f"                              otkuda=\"рынок\")"
                 f"   # DVER_V_METKI_V1: голос вывода назван")
        if staroe in src and "otkuda=" not in src[src.find(staroe):
                                                  src.find(staroe) + 200]:
            src = src.replace(staroe, novoe, 1)
            n += 1
    return src, n


def _pochinit_sverku(src: str) -> int:
    """Защита от повтора сверялась с Anchor_Points + Draft_Anchors.
    Draft_Anchors УЕХАЛИ в 3_маяки (TRI_ETAZHA_V1) — сверка ослепла
    на половину. Чиним: род + метки + маяки."""
    staroe = ('        _est += [dd.get("текст", "") for dd in '
              '(d.p.get("Draft_Anchors") or [])]')
    novoe = ('        # DVER_V_METKI_V1: черновики уехали из паспорта в 3_маяки.\n'
             '        # Сверяем ВСЕ ТРИ этажа — иначе повтор проскочит.\n'
             '        try:\n'
             '            _est += [dd.get("текст", "") for dd in d.mayaki()]\n'
             '            _est += [dd.get("текст", "") for dd in d.metki()]\n'
             '        except AttributeError:\n'
             '            _est += [dd.get("текст", "") for dd in '
             '(d.p.get("Draft_Anchors") or [])]')
    n = src.count(staroe)
    return src.replace(staroe, novoe), n


