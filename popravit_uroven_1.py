# -*- coding: utf-8 -*-
# UROVEN_1_VYZHIVI_V1
"""
Поправка в МИРОУСТРОЙСТВО Брата: первый уровень — ВЫЖИВИ.

═══ ЧТО НЕ ТАК ═══

В `Брат/1_якоря_очень_важно/МИРОУСТРОЙСТВО.md` первый уровень пути
записан так: «покажи, что ты крут хоть в малом, дай первую ценность,
заяви себя».

Слово Шефа 09.09: это не его формулировка. **Первый уровень —
выживи.**

Разница не словесная. «Заяви себя» толкает новичка геройствовать:
чтобы показать крутое, надо действовать, и чем раньше, тем лучше.
А задача первого уровня обратная — остаться в игре, пока набираешься
опыта. У Вильямса это сказано прямо: цель первого уровня — не
потерять деньги, а не заработать их.

Для Биржи это не мелочь. Трейдер на первом уровне, прочитавший «дай
первую ценность», будет входить, чтобы себя показать. Ровно то, чего
мы весь вечер добиваемся не делать.

═══ ЧТО ПАТЧ ДЕЛАЕТ ═══

Переписывает раздел первого уровня. Оптика дома («ценим крутое, а не
оцениваем плохое») сохранена: крутое на первом уровне — уцелеть, а
не блеснуть. Промолчать, когда нечего сказать, — такой же крутой
ход, как удачный вход.

Уровни 2 и 3 не тронуты. Больше ничего в файле не меняется.

Запускать из корня репозитория:
    python popravit_uroven_1.py

Идемпотентен (маркер UROVEN_1_VYZHIVI_V1). Рядом .bak. Есть --suho.
"""
from __future__ import annotations

import sys
from pathlib import Path

MARKER = "UROVEN_1_VYZHIVI_V1"
SUHO = "--suho" in sys.argv

FAYL = Path("Брат") / "1_якоря_очень_важно" / "МИРОУСТРОЙСТВО.md"

OLD = """### Уровень 1 — ВЫЖИВАНИЕ
Вошёл новичком. Первое — **покажи, что ты крут хоть в малом.**
Дай первую ценность, заяви себя. Опора — традиция, проверенное
(как A08 Консерватор: бьёт только наверняка). Здесь копят первое
доверие — не страхом не упасть, а первым крутым ходом."""

NEW = """### Уровень 1 — ВЫЖИВАНИЕ
Вошёл новичком. Первое — **выживи.** Не заяви себя и не покажи
класс: останься в игре, пока набираешься опыта. Задача уровня не
«дай первую ценность», а «не растеряй то, с чем пришёл» — у трейдера
это деньги, у любого другого доверие, с которого он начал.

Опора — традиция, проверенное (как A08 Консерватор: бьёт только
наверняка). Здесь копят первый ОПЫТ, а не первые заслуги.

И крутое тут своё: **крутое на первом уровне — уцелеть.** Промолчать,
когда нечего сказать; уйти, когда работы нет; не полезть, потому что
не понял — это такой же крутой ход, как удачное дело, и город ценит
его так же. Требовать от новичка заявить себя — значит толкать его
геройствовать раньше срока."""


def nayti_koren() -> Path:
    kandidat = Path(__file__).resolve().parent
    for papka in [kandidat, *kandidat.parents]:
        if (papka / FAYL).is_file():
            return papka
    print("Не нашёл Брат/1_якоря_очень_важно/МИРОУСТРОЙСТВО.md.")
    print("Положи скрипт в корень репозитория и запусти оттуда.")
    input("Enter — закрыть...")
    sys.exit(1)


def main() -> None:
    koren = nayti_koren()
    p = koren / FAYL
    tekst = p.read_text(encoding="utf-8")
    print(f"Файл: {p}")

    if MARKER in tekst:
        print("уже поправлено — маркер на месте")
        input("Enter — закрыть...")
        return

    skolko = tekst.count(OLD)
    if skolko != 1:
        print(f"⚠ раздел найден {skolko} раз, нужно 1 — НЕ трогаю.")
        input("Enter — закрыть...")
        return

    novyy = tekst.replace(OLD, NEW, 1).rstrip("\n")
    novyy += f"\n\n<!-- {MARKER} -->\n"

    if SUHO:
        print("✔ найден, готов поправить (сухой прогон)")
        input("Enter — закрыть...")
        return

    bak = p.with_suffix(p.suffix + ".bak_uroven1")
    if not bak.exists():
        bak.write_text(tekst, encoding="utf-8")
    p.write_text(novyy, encoding="utf-8")

    print("\n✔ первый уровень теперь про выживание")
    print("  Бэкап:", bak.name)
    input("\nEnter — закрыть...")


if __name__ == "__main__":
    main()
