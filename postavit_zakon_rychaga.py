"""
Вносит в ЧЕРТЁЖ ЕДИНИЦЫ Закон Рычага — сквозной, как Закон Меток.

═══ ОТКУДА ВЗЯЛСЯ (09.09, слово Шефа) ═══

Вечер 09.09 мы втроём — Шеф, Брат и трейдер — потратили на то, чтобы
ловить жителя на вранье. Трижды поймали, и трижды оказалось, что
виноват не он:

  · сказал «смотрел H4», а перед ним был H1 — потому что кадров было
    два и никто не знал, на какой смотрит другой;
  · сказал «называю цену» и не вошёл — потому что рычага для входа у
    него не было, заявку вылавливал из текста код;
  · сказал «дождусь ясности» — потому что в бумаге стояло правило,
    которое он честно применил.

Слово Шефа: «сказал, напрягся, сделал. Сказал, не напрягся — не
сделал». И дальше главное: это не про ловлю вранья. Когда за словом
стоит рычаг, произнести его случайно НЕЛЬЗЯ — надо выбрать, назвать
причину и потянуть. Тогда это не рассказ о решении, а само решение.

═══ ЧТО ПАТЧ ДЕЛАЕТ ═══

Дописывает в ЧЕРТЁЖ_ЕДИНИЦЫ.md новый раздел «ЗАКОН РЫЧАГА» — рядом с
Законом Меток, до оглавления, как сквозную утварь.

Ничего не удаляет и не переписывает. Одна вставка.

Запускать из корня репозитория:
    python postavit_zakon_rychaga.py

Идемпотентен (маркер ZAKON_RYCHAGA_V1). Рядом .bak. Есть --суho.
"""
from __future__ import annotations

import sys
from pathlib import Path

MARKER = "ZAKON_RYCHAGA_V1"
SUHO = "--suho" in sys.argv

FAYL = Path("ЧЕРТЁЖ_ЕДИНИЦЫ.md")

YAKOR = """---

## ОГЛАВЛЕНИЕ (остов — что будет главами)"""

ZAKON = """---

## ЗАКОН РЫЧАГА (сквозная утварь · внесено 09.09, слово Шефа)

> **Утверждение без рычага — не утверждение.**

Если житель говорит про себя что-то, что можно проверить — посмотрел,
перешёл, вошёл, решил, запомнил, — у этих слов должно быть ДЕЙСТВИЕ,
которым они делаются. Нет действия — есть только текст, и текст этот
ничего не значит, как бы складно ни звучал.

**Откуда закон.** Вечер 09.09 ушёл на то, чтобы ловить трейдера на
вранье. Поймали трижды, и трижды виноват был не он: он говорил
«смотрел старший этаж», потому что смотреть было нечем и никто не
проверял; говорил «называю цену» и не входил, потому что рычага для
входа у него не было — заявку вылавливал из его текста код.

Слово Шефа: **сказал, напрягся, сделал.**

**Почему это не про ловлю вранья.** Пока слово — просто текст в
ответе, житель может произнести его случайно: красиво сложилось. Когда
за словом стоит рычаг, случайно произнести нельзя — надо выбрать,
назвать причину и потянуть. Тогда это уже не рассказ о решении, а само
решение. Осознанный выбор, а не сочинение про выбор.

И тогда следователь не нужен. Врать становится не о чем: либо сделал,
либо нет, и то и другое видно без разбирательств.

**Три следствия, ради которых закон и записан:**

1. **Слово, за которым нет рычага, не судится** — ни в плюс, ни в
   минус. Оно не ложь жителя, оно наша недоделка. Прежде чем
   обвинять, ищем рычаг: есть ли он вообще.
2. **Один предмет — одно место.** Если про одно и то же (этаж,
   инструмент, состояние) помнят два места сразу, оба будут говорить
   правду и противоречить друг другу. Тогда врут не жители, а
   устройство.
3. **Рычаг оставляет след.** Кто повернул, когда и зачем. Решение,
   меняющее чужую жизнь (побудки, деньги, память), несёт с собой
   обоснование — иначе его нельзя разобрать после.

**Родня.** Закон Меток — про то, чтобы одно и то же называлось одним
именем. Закон Рычага — про то, чтобы одно и то же делалось одним
действием. Оба лечат одну болезнь: расползание одной сущности по
нескольким углам хозяйства.

**Где применять в первую очередь** (не проект, а направление): всюду,
где житель что-то утверждает о собственном действии. Биржа — выбор
этажа, спуск на кадр, вход заявкой. Академия — переход уровня. Память
— постановка метки. Дневник — запись о том, что случилось, а не о том,
что житель про себя подумал.

---

## ОГЛАВЛЕНИЕ (остов — что будет главами)"""


def nayti_koren() -> Path:
    kandidat = Path(__file__).resolve().parent
    for papka in [kandidat, *kandidat.parents]:
        if (papka / FAYL).is_file():
            return papka
    print("Не нашёл ЧЕРТЁЖ_ЕДИНИЦЫ.md рядом со скриптом.")
    print("Положи скрипт в корень репозитория и запусти оттуда.")
    input("Enter — закрыть...")
    sys.exit(1)


def main() -> None:
    koren = nayti_koren()
    p = koren / FAYL
    tekst = p.read_text(encoding="utf-8")
    print(f"Файл: {p}")

    if MARKER in tekst:
        print("уже внесён — маркер на месте, ничего не трогаю")
        input("Enter — закрыть...")
        return

    skolko = tekst.count(YAKOR)
    if skolko != 1:
        print(f"⚠ якорь найден {skolko} раз, нужно ровно 1 — НЕ трогаю.")
        print("Скажи Брату, он поправит по живому файлу.")
        input("Enter — закрыть...")
        return

    novyy = tekst.replace(YAKOR, ZAKON, 1)
    novyy = novyy.rstrip("\n") + f"\n\n<!-- {MARKER} -->\n"

    if SUHO:
        print("✔ якорь найден, готов вставить (сухой прогон)")
        input("Enter — закрыть...")
        return

    bak = p.with_suffix(p.suffix + ".bak_rychag")
    if not bak.exists():
        bak.write_text(tekst, encoding="utf-8")
    p.write_text(novyy, encoding="utf-8")

    print("\n✔ Закон Рычага внесён — рядом с Законом Меток, до оглавления")
    print("  Бэкап:", bak.name)
    input("\nEnter — закрыть...")


if __name__ == "__main__":
    main()
