def podozhdat():
    try:
        input("\nГотово. Нажми Enter, чтобы закрыть окно.")
    except Exception:
        pass


def nayti():
    if PUT.exists():
        return PUT
    musor = ("_ARCHIVE", "_OLD", "_АРХИВ", "_УБОРКА", ".bak")
    nash = [p for p in KOREN.rglob("промпт.md")
            if "A06" in str(p) and not any(m in str(p) for m in musor)]
    if len(nash) == 1:
        print(f"Нашёл: {nash[0]}")
        return nash[0]
    if len(nash) > 1:
        print("Нашёл несколько заданий A06:")
        for n, p in enumerate(nash, 1):
            print(f"  {n}. {p}")
        o = input("Какое правим? номер: ").strip()
        if o.isdigit() and 1 <= int(o) <= len(nash):
            return nash[int(o) - 1]
    return None


def main():
    put = nayti()
    if put is None:
        print("✗ не нашёл задание A06 — запускай из корня репозитория")
        return 1

    tekst = put.read_text(encoding="utf-8")
    if MARKER in tekst:
        print("· уже сделано")
        return 0

    if tekst.count(STAROE) != 1:
        print(f"✗ нашёл {tekst.count(STAROE)} мест вместо одного.")
        print("  Ничего не тронул. Скажи Брату, поправим по месту.")
        return 1

    novyy = tekst.replace(STAROE, NOVOE, 1)
    novyy = novyy.rstrip("\n") + "\n" + MARKER + "\n"

    kopiya = put.with_suffix(put.suffix + ".bak_vedenie")
    if not kopiya.exists():
        shutil.copy2(put, kopiya)
        print(f"  (копия старого: {kopiya.name})")
    put.write_text(novyy, encoding="utf-8")

    print("✓ ведение отдано глазу:")
    print("    · стоп после входа не двигается ни разу")
    print("    · сказано почему: 56 сделок из 64 откатывали к входу")
    print("    · выход по трём условиям против позиции, дивер числами")
    print("    · переворот — если на выходе настоящий разворот")
    print("    · переворот НЕ обязателен, чтобы не вышла долбёжка")
    print()
    print("Перезапусти Кабинет (main.py) и прогони ТОТ ЖЕ отрезок.")
    print("Сравнение будет честным: те же бары, разница только в ведении.")
    print("Считать: строчки MOVE_STOP должны исчезнуть, CLOSE — появиться.")
    return 0


if __name__ == "__main__":
    kod = main()
    podozhdat()
    sys.exit(kod)
