#
# ═══ ЧТО ПОСЧИТАНО НА ВСЕХ 64 СДЕЛКАХ ═══
#
# Перенос стопа по фракталу пробовали крутить — не помогает:
#   с 1-го фрактала −23.1R · со 2-го −25.4R · с 3-го −17.2R
# Номер фрактала не та ручка, результат стоит на месте.
#
# Безубыток ХУЖЕ, чем стоп на месте:
#   стоп стоит −3.5R · безубыток при +1R −4.2R · при +2R −4.8R
#
# Почему — слово Шефа: «поймает первую волну, а она часто длинная и
# глубокая, откатит на лоу и потом выстреливает, и не факт, что
# разворотник нарисует». Счёт подтвердил: **56 сделок из 64** прошли
# +1R, вернулись к самой цене входа и ПОТОМ дали ещё полтора риска и
# больше. Откат к входу на H4 — норма, а не исключение.
#
# А выход ГЛАЗОМ вместо механики — работает:
#   стоп по фракталу −15.3R · выход по развороту −3.5R
#   выход по развороту + ПЕРЕВОРОТ  **+1.6R**, плюсовых 36 из 84
#
# Первый плюс за всю работу. Причём на грубой подделке под её зрение
# (бар вынес край и закрылся в другой половине, без дивера и
# приседающего) — у настоящей Синди должно выйти лучше.
#
# Слово Шефа про переворот: «по сути перевороты делать, но не тупые:
# где-то просто выход, а где-то перевернуть. Её будят, ей проще, чем
# мне ловить каждый некрон».
#
# ═══ ЧТО СТАВИМ ═══
#
# 1. СТОП ПОСЛЕ ВХОДА НЕ ДВИГАЕТСЯ. Ни по фракталу, ни в безубыток.
# 2. ВЫХОД ГЛАЗОМ: те же три условия, но против позиции.
# 3. ПЕРЕВОРОТ: вышла и видит настоящий разворот — входит в другую
#    сторону тут же. Не видит — ждёт некрона, он разбудит.
#
# Переворот НЕ обязателен — нарочно сказано, иначе она станет
# переворачиваться из каждого выхода, и выйдет та же долбёжка с
# другого конца.
