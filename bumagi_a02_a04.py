BUMAGI = {"A02": A02, "A04": A04}


def _teper() -> str:
    return datetime.now().strftime("%Y%m%d_%H%M%S")


def naiti_koren() -> Path:
    starty = [Path(__file__).resolve().parent, Path.cwd().resolve()]
    for start in starty:
        for kand in [start, *start.parents]:
            if (kand / "GRONDHEIM_CITY" / "локации").is_dir() \
                    and (kand / "ГОРОД" / "rabota.py").is_file():
                return kand
    raise SystemExit("Не нашёл корень репо. Запусти из корня "
                     "Grondheim-Ecosystem.")


def main() -> None:
    try:
        sys.stdout.reconfigure(encoding="utf-8")  # type: ignore[union-attr]
    except Exception:
        pass

    koren = naiti_koren()
    print(f"Корень: {koren}\n")

    ceh = koren / "GRONDHEIM_CITY" / "Студия" / "цеха" / "турбо"
    if not (ceh / "manifest.json").exists():
        raise SystemExit("Цеха турбо нет — сперва накати ceh_turbo.py")

    for imya, tekst in BUMAGI.items():
        slot = ceh / "слоты" / imya
        slot.mkdir(parents=True, exist_ok=True)
        put = slot / "промпт.md"
        if put.exists():
            if put.read_text(encoding="utf-8") == tekst:
                print(f"{imya}: уже стоит, не трогал")
                continue
            bak = put.with_suffix(f".md.bak_{_teper()}")
            shutil.copyfile(put, bak)
            put.write_text(tekst, encoding="utf-8")
            print(f"{imya}: обновлена, старая в {bak.name}")
        else:
            put.write_text(tekst, encoding="utf-8")
            print(f"{imya}: написана ({len(tekst.splitlines())} строк)")

    # ── общая сверка всего цеха ───────────────────────────────
    m = json.loads((ceh / "manifest.json").read_text(encoding="utf-8"))
    print("\nСверка цеха целиком:")
    bedy = []
    for s in m["слоты"]:
        put = ceh / "слоты" / s["слот"] / "промпт.md"
        if not put.exists():
            print(f"  {s['слот']} · бумаги нет")
            bedy.append(s["слот"])
            continue
        t = put.read_text(encoding="utf-8")
        klyuchi = list(s.get("берёт", [])) + list(s.get("даёт", []))
        net = [k for k in klyuchi if k not in t]
        netz = [f for f in s.get("знания", [])
                if not (ceh / "знания" / f).exists()]
        znak = "ok" if not net and not netz else "!!"
        print(f"  {s['слот']} · {s['роль']:<14} {znak}  "
              f"ключей {len(klyuchi)}, знаний {len(s.get('знания', []))}"
              + (f"  НЕТ В БУМАГЕ: {net}" if net else "")
              + (f"  НЕТ НА СКЛАДЕ: {netz}" if netz else ""))
        if net or netz:
            bedy.append(s["слот"])

    print()
    if bedy:
        print(f"Не сходится: {', '.join(bedy)}")
    else:
        print("ЦЕХ ОДЕТ. Пять мест, бумаги на месте, ключи и знания сходятся.")
        print("Дальше — движок цеха.")
    print("шесть·проверено·до·корня")


if __name__ == "__main__":
    main()
