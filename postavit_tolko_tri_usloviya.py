"""
УСЛОВИЙ РОВНО ТРИ · остальное — выдумка, и она не считается

ТРИ ПРОГОНА, ТРИ РАЗНЫЕ ВЫДУМКИ. Каждый раз трейдер собирал три
части верно — и приделывал сверху условие, которого нет ни в одной
бумаге:

  · «жду, пока цена пробьёт хай разворотника»
  · «разворотник внутри Аллигатора — сомнительный»
  · «цена не должна возвращаться к линиям Аллигатора»

Разные модели, одна повадка: как только сошлось и надо действовать,
находится ещё одно условие, чтобы не входить.

И это НЕ про модели. Вся его бумага — про то, когда НЕ работать:
передышка, шум, не то место. «Сошлись — окружай» стоит одной
строкой, а сомневаться учит весь остальной текст. Он и сомневается,
старательно и каждый раз по-новому.

ЧТО ДЕЛАЕТ ПАТЧ, две правки:

 1. ЗАКРЫТЫЙ СПИСОК. Прямо сказано: условий ровно три, и других нет.
    Всё, чего нет в трёх частях, — выдумка, и она не считается. С
    перечнем того, что уже придумывалось, поимённо — чтобы узнавал
    свои же слова.

 2. ОТКАЗ ИМЕНУЕТСЯ. Не работаешь — назови, КАКОЙ из трёх частей не
    хватило: направления, импульса или напряжения. «Нет чёткого
    сигнала», «нужно подтверждение», «ситуация неясная» — это не
    причины, это отговорки. Тогда выдумке негде поместиться: либо
    называешь свою часть, либо у тебя всё сошлось и надо окружать.

ТРЕБУЕТ: TRI_SOSHLIS_VHODI_V1.

БЕЗОПАСНОСТЬ: .bak_tolko3, идемпотентен, `--suho` не трогает диск.

    python postavit_tolko_tri_usloviya.py --suho
    python postavit_tolko_tri_usloviya.py

`шесть·проверено·до·корня`
"""
import shutil
import sys
from pathlib import Path

MARKER = "TOLKO_TRI_USLOVIYA_V1"
SUHO = "--suho" in sys.argv

_REPO = Path(__file__).resolve().parent
SLOTY = _REPO / "GRONDHEIM_CITY" / "Биржа" / "цеха" / "торговый_хаос" / "слоты"

YAKOR = """Такого правила — «дождись пробоя» — у тебя нет. Если ловишь себя на
том, что ждёшь ещё чего-то сверх трёх частей, ты выдумал это сам.
"""

DOPISKA = """
**УСЛОВИЙ РОВНО ТРИ. ДРУГИХ НЕТ.** Направление, импульс, напряжение.
Всё, чего нет в этих трёх, — не условие, а твоя выдумка, и она НЕ
СЧИТАЕТСЯ.

Вот что уже придумывалось на этом месте — узнай свои слова:

- «жду, пока цена пробьёт хай разворотника»
- «цена не должна возвращаться к линиям Аллигатора»
- «разворотник внутри Аллигатора — сомнительный»
- «нужно подтверждение», «жду ясности», «нет чёткого сигнала»

Ни одного из этих правил тебе никто не давал. Они появляются, когда
три части сошлись и пора действовать, — это не осторожность, это
способ не решать.

**Отказываешься — НАЗОВИ, ЧЕГО НЕ ХВАТИЛО.** Одной из трёх:
направления, импульса или напряжения. «Дивера нет» — причина.
«Приседающих нет» — причина. «Цена топчется, направления не вижу» —
причина. А «нет чёткого сигнала» и «нужно подтверждение» — не
причины, и такой отказ не принимается.

Если все три на месте, а отказаться всё равно хочется — значит
причины нет. Окружай бар.
"""


def _pravka(slot: str) -> int:
    p = SLOTY / slot / "промпт.md"
    if not p.exists():
        print(f"  {slot}: файла нет")
        return 0
    txt = p.read_text(encoding="utf-8")
    if MARKER in txt:
        print(f"  {slot}: уже стоит")
        return 0
    if "TRI_SOSHLIS_VHODI_V1" not in txt:
        print(f"  {slot}: ОТКАЗ — сперва postavit_tri_soshlis_vhodi.py")
        return -1
    if txt.count(YAKOR) != 1:
        print(f"  {slot}: ОТКАЗ — якорь встречается {txt.count(YAKOR)} раз(а)")
        return 0
    novy = txt.replace(YAKOR, YAKOR + DOPISKA, 1)
    novy = novy.rstrip("\n") + f"\n\n<!-- {MARKER} -->\n"
    if not SUHO:
        shutil.copy2(p, p.with_suffix(".md.bak_tolko3"))
        p.write_text(novy, encoding="utf-8")
    print(f"  {slot}: {'готово' if SUHO else 'поправлено'}")
    return 1


def main():
    print()
    print("УСЛОВИЙ РОВНО ТРИ" + ("  · СУХОЙ ПРОГОН" if SUHO else ""))
    print("корень:", _REPO)
    print()
    if not SLOTY.exists():
        print("!! слотов нет — запускать из корня репы")
        return
    vsego = 0
    for s in ("A06", "A07", "A08"):
        r = _pravka(s)
        if r < 0:
            return
        vsego += r
    print()
    if SUHO:
        print("Сухой прогон: на диске ничего не изменилось.")
    else:
        print(f"Тронуто бумаг: {vsego}. Бэкапы — .bak_tolko3")
    print("Отказ теперь надо назвать по имени.")
    print()


if __name__ == "__main__":
    main()
