# ОДНА ДВЕРЬ (Закон Пары): весь механизм — в nositel.py, рядом с
#   dusha_slota. НЕ вписываю в девять мозгов: через месяц было бы
#   девять разъехавшихся копий. Ровно болезнь пяти магиков (§5г БИРЖА).
