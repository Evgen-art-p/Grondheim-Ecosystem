#   3. Промпт: житель УЗНАЁТ, что может просить. Молчком воли нет.
#   4. Ложь про «оплаченный род» — вырезана.
#
# ИДЕМПОТЕНТЕН. BACKUP: *.bak_memreq
# Запуск из корня репо:  python patch_memory_request_birzha.py
