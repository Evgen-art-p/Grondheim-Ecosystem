# 2а. Инструкция в user_msg — житель узнаёт, что может просить
INSTRUKTSIYA = '''        # MEMORY_REQUEST_BIRZHA_V1: житель УЗНАЁТ, что может вспомнить.
        # Молчком воли нет: если ему не сказать — он не попросит.
        "МОЖЕШЬ ВСПОМНИТЬ. Если этот момент тебе что-то напоминает — "
        "напиши ОТДЕЛЬНОЙ СТРОКОЙ, до JSON:\\n"
        "MEMORY_REQUEST: <что именно хочешь поднять из своей памяти>\\n"
        "Например: «похожий разворот на дне без приседающего». Один "
        "запрос — больше не дадут. Поднимут твой архив, и ты решишь "
        "СНОВА, уже зная. Не напоминает — не проси, не трать.\\n\\n"
'''


def _pochinit_lozh(src: str) -> tuple:
    """Промпт трейдера говорит «глянь на свои ЯКОРЯ... опыт ОПЛАЧЕН
    ТВОИМИ ДЕНЬГАМИ». Якоря = РОД, вписанный при рождении. Он ничего
    не оплачивал. Та же ложь, что вчера в _sobrat_dushu — тот же класс,
    что пять копий магика: вырезал в одном месте, сидит в девяти."""
    staroe = ('"«КТО ТЫ»): что ты УЖЕ вынес из похожих входов? Твой опыт оплачен "\n'
              '        "твоими деньгами. Он не приказ — но и не украшение. Если идёшь "')
    novoe = ('"«КТО ТЫ»): там ТРИ разных голоса — твой РОД (кто ты есть от "\n'
             '        "рождения), твои МЕТКИ (что ты нажил сам — вот ЭТО оплачено "\n'
             '        "твоими деньгами) и МАЯКИ (что только замечаешь за собой). "\n'
             '        "Они могут спорить между собой — и это нормально. Если идёшь "')
    if staroe in src:
        return src.replace(staroe, novoe, 1), True
    return src, False


def _patch_mozg(path: Path, fn_name: str) -> dict:
    src = path.read_text(encoding="utf-8")
    itog = {"файл": path.parent.name, "ложь": False, "запрос": False,
            "второй_вызов": False}

    if MARK in src:
        return {"уже": True, **itog}

    bak = path.with_suffix(".py.bak_memreq")
    if not bak.exists():
        shutil.copy2(path, bak)

    # ── 1. Ложь про оплаченный род ──────────────────────────────
    src, ok = _pochinit_lozh(src)
    itog["ложь"] = ok

    # ── 2. Инструкция — перед строкой «Выдай строго JSON» ───────
    # У всех троих эта строка РАЗНАЯ (проверено на диске 13.07):
    #   A06: '        "Выдай строго JSON {narrative, signal, diary_entry}. signal: "'
    #   A07: '        "Выдай строго JSON {narrative, signal, "'
    #   A08: '        "как поступить. Выдай строго JSON {narrative, signal, "'
    # Первый матчер искал точную строку A07 — и молча промахнулся на двух
    # других. Цепляемся за ОБЩЕЕ: начало строки, где стоит «Выдай строго
    # JSON». Ищем НАЧАЛО СТРОКИ, а не подстроку — иначе разрежем текст.
    for stroka in src.splitlines():
        if "Выдай строго JSON" in stroka and stroka.strip().startswith('"'):
            src = src.replace(stroka, INSTRUKTSIYA + stroka, 1)
            itog["запрос"] = True
            break

    # ── 3. ВТОРОЙ ВЫЗОВ — после первого ответа модели ───────────
    # цепляем сразу после chat(), до _parse_*
    ank2 = "    narrative, signal, diary_entry = _parse_"
    i = src.find(ank2)
    if i > 0:
        vtoroy = f'''    # ═══ MEMORY_REQUEST_BIRZHA_V1 — ВОЛЯ ВСПОМНИТЬ ═══
    # Житель попросил? Копаем ЕГО память и спрашиваем СНОВА — уже зная.
    # Не просил — ничего не тратим (второго вызова просто нет).
    # ОДИН ЗАПРОС ЗА РАН: подняли раз, дальше решай сам (канон -2).
    try:
        from nositel import podnyat_iz_arhiva, blok_pamyati, ubrat_zapros
        _zapros, _naydeno = podnyat_iz_arhiva(_CEH, _SLOT, response)
        if _zapros:
            response = chat(
                system=system_full,
                user=user_msg + blok_pamyati(_zapros, _naydeno),
                knowledge=knowledge,
                agent_id="{path.parent.name}", slot_id=_SLOT,
                temperature=_temp)
            response = ubrat_zapros(response) or response
    except Exception as _e:
        print(f"[МОСТ] ⚠️  память не поднялась: {{_e}}")

'''
        src = src[:i] + vtoroy + src[i:]
        itog["второй_вызов"] = True

    # клеймо
    src = src.replace("# `шесть·проверено·до·корня`",
                      f"# {MARK}: житель может ПОПРОСИТЬ вспомнить (воля выше шлюза).\n"
                      "# `шесть·проверено·до·корня`", 1)
    if MARK not in src:
        src = f"# {MARK}\n" + src

    try:
        ast.parse(src)
    except SyntaxError as ex:
        return {"ошибка": f"синтаксис сломан: {ex}", **itog}

    path.write_text(src, encoding="utf-8")
    return itog


