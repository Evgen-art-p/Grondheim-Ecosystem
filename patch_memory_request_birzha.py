# ⚠ ЗАОДНО РЕЖЕТСЯ ТА ЖЕ ЛОЖЬ, ЧТО ВЧЕРА В _sobrat_dushu:
#   промпт трейдера говорит «глянь на свои ЯКОРЯ... твой опыт ОПЛАЧЕН
