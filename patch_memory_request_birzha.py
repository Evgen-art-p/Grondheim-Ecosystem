#   («по канону таких 3-4 в год» — комментарий в коде Шефа).
#   Значит житель просыпается РЕДКО И ПО ДЕЛУ. А заряд у него при этом
#   около нуля (после Тика) → шлюз откроет только `core`, самый мелкий
#   слой. Проснулся на важнейшем событии — а память на минимуме.
