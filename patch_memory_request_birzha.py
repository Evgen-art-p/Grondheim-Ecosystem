#   не оплачивал. Вырезал в одном месте — а она сидела в промпте
#   КАЖДОГО трейдера. Тот же класс, что пять копий магика.
#
# ЧТО ДЕЛАЕТ:
#   1. Биржа/nositel.py: vspomnit_slotom(ceh, slot, zapros) — одна дверь.
#      + izvlech_zapros(text) / ubrat_zapros(text) — как в ui_zhitel.
#   2. Мозги трейдеров (A06/A07/A08): после ответа модели —
