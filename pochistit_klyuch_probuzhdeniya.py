"""
КЛЮЧ БУДИТ ТОЛЬКО НЕКРОНОМ

Слово Шефа 12.09: «из ключа желательно убрать названия волн, откаты,
макушки — просто бар-некрон и направление».

ЗАЧЕМ. Ключ будил трейдера словами второго уровня: «волна 1
кончилась, дно @ 1.03136», «излом верх @ 1.04343 (18 бар назад) стал
виден», «откат кончился, нога 1». Он этих слов не знает — и каждый
раз пересказывал их как умел. Отсюда разбор «не про эту картинку»:
его будили изломом восемнадцать баров назад, а он честно искал
разворотный бар на правом краю и рассказывал про него.

На первом уровне у него три вещи: некрон, AO, приседающий. Волны,
откаты и изломы — второй уровень, они дождутся своего.

ЧТО ДЕЛАЕТ ПАТЧ. В `Биржа/council.py`:

 · ПОВОД ВЗГЛЯДА — только разворотный бар. Излом из повода уходит:
   он «дозревает позже» и говорит ГДЕ, а не КОГДА, — это не первый
   уровень.
 · ВОЛНОВЫЕ ПОВОДЫ — «волна 1 кончилась», «откат кончился» — больше
   не будят. Считаться они продолжают (разметка нужна старшим
   уровням), просто из побудки уходят.
 · ТОЧКА НОЛЬ — тоже не будит: это третий уровень у Вильямса.

ОСТАЮТСЯ БУДИТЬ: некрон и своё — заявка висит, вошёл, сделка
закрылась. Про своё он должен знать всегда.

БУДЕТ МЕНЬШЕ ПОБУДОК — и это правильно: за прошлый прогон из
восемнадцати мест четырнадцать кончились молчанием. Будили по
поводам, которых он не понимает.

КУДА КЛАСТЬ ЭТОТ ФАЙЛ: в корень репы, рядом с main.py.

БЕЗОПАСНОСТЬ: .bak_klyuch3, идемпотентен, синтаксис до записи,
`--suho` не трогает диск.

    python pochistit_klyuch_probuzhdeniya.py --suho
    python pochistit_klyuch_probuzhdeniya.py

`шесть·проверено·до·корня`
"""
import ast
import shutil
import sys
from pathlib import Path

MARKER = "KLYUCH_TOLKO_NEKRON_V1"
SUHO = "--suho" in sys.argv

_REPO = Path(__file__).resolve().parent
FAJL = _REPO / "Биржа" / "council.py"

# ── 1. излом уходит из повода ────────────────────────────────
STAROE_IZLOM = '''        iz = _izl.dozrel(bs)
        if iz:
            povody.append(f"излом {iz['тип']} @ {iz['цена']} "
                          f"({iz['баров_назад']} бар назад) стал виден")'''
NOVOE_IZLOM = '''        # KLYUCH_TOLKO_NEKRON_V1: излом больше не будит. Он говорит
        # ГДЕ и дозревает позже — это второй уровень. Трейдера будили
        # изломом «18 баров назад», а он искал разворотный бар на
        # правом краю и рассказывал про него: разбор выходил не про
        # ту картинку. Считаться излом продолжает, будить — нет.
        _ = _izl'''

# ── 2. волновые поводы не будят ──────────────────────────────
STAROE_VOLNA = '''            return {"будим": True,
                    "почему": f"волна 1 кончилась, {_kray} @ "'''
NOVOE_VOLNA = '''            return {"будим": False,      # KLYUCH_TOLKO_NEKRON_V1
                    "почему": f"волна 1 кончилась, {_kray} @ "'''

STAROE_OTKAT = '''            return {"будим": True,
                    "почему": f"откат кончился @ {kv2.get('цена')} "'''
NOVOE_OTKAT = '''            return {"будим": False,      # KLYUCH_TOLKO_NEKRON_V1
                    "почему": f"откат кончился @ {kv2.get('цена')} "'''

# ── 3. точка ноль не будит ───────────────────────────────────
STAROE_TOCHKA = '''            return {"будим": True,
                    "почему": f"точка родилась: {tch.get('trend_direction')} @ "'''
NOVOE_TOCHKA = '''            return {"будим": False,      # KLYUCH_TOLKO_NEKRON_V1
                    "почему": f"точка родилась: {tch.get('trend_direction')} @ "'''


def main():
    print()
    print("КЛЮЧ — ТОЛЬКО НЕКРОН" + ("  · СУХОЙ ПРОГОН" if SUHO else ""))
    print("файл:", FAJL)
    print()
    if not FAJL.exists():
        print("!! файла нет — запускать из корня репы")
        return
    txt = FAJL.read_text(encoding="utf-8")
    if MARKER in txt:
        print("Уже стоит. Ничего не меняю.")
        return

    novy, sdelano = txt, []
    for imya, st, nv in (("излом не будит", STAROE_IZLOM, NOVOE_IZLOM),
                         ("волна 1 не будит", STAROE_VOLNA, NOVOE_VOLNA),
                         ("откат не будит", STAROE_OTKAT, NOVOE_OTKAT),
                         ("точка не будит", STAROE_TOCHKA, NOVOE_TOCHKA)):
        n = novy.count(st)
        if n != 1:
            print(f"  {imya}: пропускаю — якорь встречается {n} раз(а)")
            continue
        novy = novy.replace(st, nv, 1)
        sdelano.append(imya)

    if not sdelano:
        print("Ни одного якоря — файл не тронут.")
        return

    try:
        ast.parse(novy)
    except SyntaxError as e:
        print("!! после правки синтаксис сломан — ничего не записал:", e)
        return
    for s in sdelano:
        print(f"  {s}: сделано")
    print("  синтаксис после правки — валиден")

    if SUHO:
        print()
        print("Сухой прогон: на диске ничего не изменилось.")
        return
    shutil.copy2(FAJL, FAJL.with_suffix(".py.bak_klyuch3"))
    FAJL.write_text(novy, encoding="utf-8")
    print()
    print("Готово. Бэкап: council.py.bak_klyuch3")
    print("Будит некрон и своё. Волны и изломы считаются, но молчат.")
    print()


if __name__ == "__main__":
    main()
