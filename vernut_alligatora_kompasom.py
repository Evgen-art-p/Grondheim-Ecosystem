import shutil
import sys
from pathlib import Path

MARKER = "ALLIGATOR_DLYA_NAPRAVLENIYA_V1"
SUHO = "--suho" in sys.argv

_REPO = Path(__file__).resolve().parent
SLOTY = _REPO / "GRONDHEIM_CITY" / "Биржа" / "цеха" / "торговый_хаос" / "слоты"

STAROE_LINII = """**Три линии — Аллигатор.** Синяя челюсть, красные зубы, зелёные губы.
На твоём уровне ими НЕ ПОЛЬЗУЮТСЯ и на них НЕ ССЫЛАЮТСЯ. Всё, что
они могли бы сказать про твой бар, уже стоит внутри формулы
разворотного бара. А сами по себе они читаются только в масштабе,
где ход виден целиком, — и на случайном кадре говорят не про рынок.
Не строй на них ни отказа, ни входа: ни «линии переплелись», ни
«Аллигатор спит» доводом не считается."""

NOVOE_LINII = """**Три линии — Аллигатор.** Синяя челюсть, красные зубы, зелёные губы.
Они у тебя ровно для одного — понять, КУДА ИДЁТ ЦЕНА:

    цена выше всех трёх линий — считай, цена растёт
    цена ниже всех трёх       — считай, цена падает

Переплетены линии или разошлись веером — не важно, правило то же.

И только для этого. Судить по ним СВОЙ БАР нельзя: ни «линии
переплелись», ни «разворотник в пасти», ни «Аллигатор спит» доводом
не считается. Отрыв бара от линий уже проверен внутри формулы, а
пасть и угол читаются другим масштабом и на другом уровне. Аллигатор
тебе компас, а не судья места."""

STAROE_NAPR = """**Направление.** Куда идёт цена: растёт, падает. Видно глазами,
раньше всего остального. Бьёт ли она новые края — уходит дальше
прошлого предела или уже не может."""

NOVOE_NAPR = """**Направление.** Куда идёт цена. Смотришь, где она относительно
Аллигатора: выше всех трёх линий — растёт, ниже — падает. Это и есть
твой компас, других вопросов к линиям нет.

Про тренд добавляется одно: **обновляет ли цена экстремумы** — уходит
дальше прошлого предела или уже не может.

Направление нужно, чтобы знать, КАКОЙ ход кончается — с чем ты шёл и
что именно выдохлось. Разворот против него — это и есть твоя работа:
шёл с ходом вверх, он выдохся, дивер и приседающие на месте — на
некроне разворачиваешься. Конец хода всегда против того хода, который
кончается."""


def _pravka(slot: str) -> int:
    p = SLOTY / slot / "промпт.md"
    if not p.exists():
        print(f"  {slot}: файла нет")
        return 0
    txt = p.read_text(encoding="utf-8")
    if MARKER in txt:
        print(f"  {slot}: уже стоит")
        return 0
    if "TRI_CHASTI_PERVOGO_UROVNYA_V1" not in txt:
        print(f"  {slot}: ОТКАЗ — сперва postavit_tri_chasti.py")
        return -1

    novy, sdelano = txt, []
    for imya, staroe, novoe in (("линии — компас", STAROE_LINII, NOVOE_LINII),
                                ("направление", STAROE_NAPR, NOVOE_NAPR)):
        n = novy.count(staroe)
        if n != 1:
            print(f"  {slot}: ! «{imya}» — якорь встречается {n} раз(а)")
            continue
        novy = novy.replace(staroe, novoe, 1)
        sdelano.append(imya)

    if not sdelano:
        return 0
    novy = novy.rstrip("\n") + f"\n\n<!-- {MARKER} -->\n"
    if not SUHO:
        shutil.copy2(p, p.with_suffix(".md.bak_kompas"))
        p.write_text(novy, encoding="utf-8")
    print(f"  {slot}: {'готово' if SUHO else 'поправлено'} — "
          + "; ".join(sdelano))
    return 1


def main():
    print()
    print("АЛЛИГАТОР — КОМПАС НАПРАВЛЕНИЯ"
          + ("  · СУХОЙ ПРОГОН" if SUHO else ""))
    print("корень:", _REPO)
    print()
    if not SLOTY.exists():
        print("!! слотов нет — запускать из корня репы")
        return
    vsego = 0
    for s in ("A06", "A07", "A08"):
        r = _pravka(s)
        if r < 0:
            return
        vsego += r
    print()
    if SUHO:
        print("Сухой прогон: на диске ничего не изменилось.")
    else:
        print(f"Тронуто бумаг: {vsego}. Бэкапы — .bak_kompas")
    print("Выше линий — растёт, ниже — падает. Больше вопросов к ним нет.")
    print()


if __name__ == "__main__":
    main()
