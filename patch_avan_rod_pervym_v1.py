# -*- coding: utf-8 -*-
"""
patch_avan_rod_pervym_v1.py
────────────────────────────────────────────────────────────────────
РОД ВПЕРЕДИ, МАСКА ВНУТРЬ НЕГО (Чертёж §1.5.2 — узел «Вася Пупкин»).

ЖИВОЙ ПРОГОН 12.07 показал: мост доехал ([AVAN] 🧬 За столом: Илья),
но Авантюрист говорит «как из студии» — Ильи в голосе нет. Разбор:

1. ПОРЯДОК БЫЛ ВВЕРХ НОГАМИ (мой промах в patch_etalon_avana_v1).
   Было:  system = [промпт роли, 25 000 знаков] + «=== ТВОЁ СОСТОЯНИЕ ===» + душа
   Модель читает огромный канон роли, а Илью получает СНОСКОЙ в хвосте —
   и принимает к сведению, продолжая играть Роль.
   Стало: system = [КТО ТЫ — Илья, род, натура, ОПЫТ] + шов + [канон места].
   Сначала человек, потом стойка, за которой он сегодня сидит.

2. МЁРТВОЕ ОБЕЩАНИЕ В ПРОМПТЕ РОЛИ.
   промпт.md A07 говорит: «Твоя ДНК и твоё состояние лежат в `dna.json`.
   Это ты. Читай как себя.» — а dna.json НЕ СУЩЕСТВУЕТ (наследие -2,
   снесено вместе со studio/). Модель шла по указателю в пустоту и играла
   Илью «по описанию», без единого числа и без опыта.
   Стало: указатель ведёт в живой блок «КТО ТЫ» (паспорт носителя) и прямо
   зовёт опереться на ЯКОРЯ — его же выводы, оплаченные его же деньгами.

ЧТО ПРАВИТ: мозг A07 (порядок сборки system в run_avan и chat_with_avan)
  + промпт.md A07 (одна строка-указатель). Больше ничего.

Требует: patch_etalon_avana_v1. Идемпотентно. .bak рядом.
Из КОРНЯ репы:  python patch_avan_rod_pervym_v1.py
"""
from __future__ import annotations
import io
import sys
from pathlib import Path

MARKER = "ROD_PERVYM_V1"
NEED = "AVAN_NOSITEL_V1"

SLOT = (Path("GRONDHEIM_CITY") / "Биржа" / "цеха" / "торговый_хаос" /
        "слоты" / "A07")
BRAIN = SLOT / "мозг.py"
PROMPT = SLOT / "промпт.md"

# ── ШОВ: как маска садится внутрь Рода ──────────────────────────
SHOV = (
    "\\n\\n=== ТВОЯ РОЛЬ СЕГОДНЯ — СТОЙКА, ЗА КОТОРОЙ ТЫ СИДИШЬ ===\\n"
    "Ниже — канон МЕСТА (Авантюрист, ранний вход). Это твоя работа и школа,\\n"
    "а не твоя личность: личность выше. Канон кладёт карту — идёшь ты, своей\\n"
    "натурой, своим опытом и своим голосом. Где канон и твой опыт разойдутся —\\n"
    "решаешь ты, а не бумага.\\n\\n"
)

# ── 1. run_avan: порядок сборки ─────────────────────────────────
OLD_RUN = """    system_full = prompt
    if soul:
        system_full += "\\n\\n=== ТВОЁ СОСТОЯНИЕ (душа) ===\\n" + soul
"""
NEW_RUN = """    # """ + MARKER + """: РОД ВПЕРЕДИ, маска внутрь него (Чертёж §1.5.2).
    # Было: промпт роли (25к знаков), а Илья — сноской в хвосте. Модель играла
    # Роль и принимала человека к сведению. Стало: сначала ТЫ, потом стойка.
    if soul:
        system_full = (
            "=== КТО ТЫ. ЭТО НЕ РОЛЬ — ЭТО ТЫ ===\\n"
            + soul
            + \"""" + SHOV + """\"
            + prompt
        )
    else:
        system_full = prompt
"""

# ── 2. chat_with_avan: тот же порядок ───────────────────────────
OLD_CHAT = """        if _n and _n["душа"]:
            system = (prompt + "\\n\\n=== КТО ТЫ (душа носителя) ===\\n"
                      + _n["душа"] + "\\n\\n" + work_ctx)
"""
NEW_CHAT = """        if _n and _n["душа"]:
            system = (   # """ + MARKER + """: и в разговоре РОД впереди маски
                "=== КТО ТЫ. ЭТО НЕ РОЛЬ — ЭТО ТЫ ===\\n"
                + _n["душа"]
                + \"""" + SHOV + """\"
                + prompt + work_ctx
            )
"""

# ── 3. промпт.md: мёртвый указатель на dna.json ─────────────────
OLD_PROMPT = ("Твоя ДНК и твоё состояние лежат в `dna.json`. Это ты. "
              "Читай как себя.")
NEW_PROMPT = (
    "Твоя ДНК, твоя история и твой ОПЫТ (якоря — выводы, которые ты оплатил\n"
    "своими деньгами) лежат ВЫШЕ, в блоке «КТО ТЫ». Это ты. Читай как себя —\n"
    "и опирайся: якоря не украшение, это то, чему рынок тебя уже научил.\n"
    "Идёшь против своего же вывода — твоё право, но знай, что идёшь.\n"
    "<!-- " + MARKER + ": было `dna.json` — файл из старой студии, снесён "
    "вместе с ней; указатель годами вёл в пустоту -->"
)


def main() -> int:
    if isinstance(sys.stdout, io.TextIOWrapper):
        try:
            sys.stdout.reconfigure(encoding="utf-8")
        except Exception:
            pass

    print("═══ РОД ВПЕРЕДИ МАСКИ — Илья за стойкой Авантюриста ═══")

    if not BRAIN.exists() or not PROMPT.exists():
        print(f"✗ не нашёл {BRAIN} или {PROMPT} — ты в КОРНЕ репы?")
        return 1

    b = BRAIN.read_text(encoding="utf-8")
    if NEED not in b:
        print("✗ сначала patch_etalon_avana_v1.py (мост к носителю).")
        return 2

    done = 0

    # ── мозг ────────────────────────────────────────────────────
    if MARKER in b:
        print("✓ мозг A07 уже пропатчен (порядок Род→маска)")
        done += 1
    else:
        for old, what in ((OLD_RUN, "сборка system в run_avan"),
                          (OLD_CHAT, "сборка system в chat_with_avan")):
            if old not in b:
                print(f"✗ мозг A07: не нашёл блок «{what}». Сверь глазами.")
                return 3
        bak = BRAIN.with_suffix(".py.bak2")
        if not bak.exists():
            bak.write_text(b, encoding="utf-8")
            print(f"  • бэкап: {bak}")
        b = b.replace(OLD_RUN, NEW_RUN, 1).replace(OLD_CHAT, NEW_CHAT, 1)
        BRAIN.write_text(b, encoding="utf-8")
        print("✓ мозг A07: сначала РОД (Илья + натура + опыт), потом канон роли")
        done += 1

    # ── промпт ──────────────────────────────────────────────────
    p = PROMPT.read_text(encoding="utf-8")
    if MARKER in p:
        print("✓ промпт A07 уже пропатчен (мёртвый dna.json убран)")
        done += 1
    else:
        if OLD_PROMPT not in p:
            print("✗ промпт A07: не нашёл строку про `dna.json`. "
                  "Правился вручную? Сверь глазами — строка должна быть:")
            print(f"    {OLD_PROMPT}")
            return 4
        bak = PROMPT.with_suffix(".md.bak")
        if not bak.exists():
            bak.write_text(p, encoding="utf-8")
            print(f"  • бэкап: {bak}")
        p = p.replace(OLD_PROMPT, NEW_PROMPT, 1)
        PROMPT.write_text(p, encoding="utf-8")
        print("✓ промпт A07: указатель на мёртвый dna.json → на живой блок "
              "«КТО ТЫ» + прямой зов опереться на ЯКОРЯ")
        done += 1

    if done == 2:
        print("───")
        print("Теперь модель читает: сначала ТЫ (Илья, натура 0.85/0.9, слитый")
        print("счёт 2017, пять оплаченных выводов), потом — стойка Авантюриста.")
        print("\nПрогони тестер ещё раз (ловить 2) и сравни ТЕКСТ Авантюриста")
        print("с прошлым прогоном. Если Илья не проступил — говори, копаем дальше.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
