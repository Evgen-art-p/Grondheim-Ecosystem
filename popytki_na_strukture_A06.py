# ═══ ЧЕГО НЕ ХВАТАЛО ═══
#
# На столе у трейдера стоит счётчик: «ПОПЫТКА 3-я на этой структуре»,
# а с третьей город добавляет «— то ли ты делаешь?». Рядом лежат
# исходы прошлых попыток.
#
# А в задании про попытки НЕ БЫЛО НИ СЛОВА. Ни сколько положено, ни
# что означает число, ни что делать с вопросом города.
#
# Город считал и подкалывал, а смысла не объяснял. Трейдер оставался
# с этим один: то ли это упрёк и надо уйти, то ли просто счёт.
#
# ═══ СЛОВО ШЕФА ═══
#
# «Три раза входи по любому, если дальше стопит, но выполняются все
# условия, то входи.»
# «Если три условия не сходятся — вообще никогда не входим.»
# «Три раза стопануло — посмотри, а реально то ли. Но если дальше
# условия сходятся, продолжаешь выставлять ордера.»
#
# То есть: число попыток НИЧЕГО НЕ ЗАПРЕЩАЕТ. Это счёт, а не потолок.
# Единственный запрет в системе один и прежний — не сошлись три
# условия, входа нет. Он не зависит от номера попытки ни в какую
# сторону.
#
# А вопрос города «то ли ты делаешь?» остаётся и работает как
# задумано: не запрет, а требование посмотреть заново, своими
# глазами, а не по памяти о прошлом входе.
#
# ═══ ЧТО СТАВИМ ═══
#
# Раздел про попытки в задание, между ВХОДОМ и разделом про открытую
# заявку. Ничего не запрещает и не разрешает сверх того, что уже
# есть, — объясняет число, которое трейдер и так видит на столе.
#
# Кода не касается: подколка в stol.py остаётся как была, это голос
# Шефа и он по делу.
#
