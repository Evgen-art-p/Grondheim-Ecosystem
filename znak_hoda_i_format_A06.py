# Кладётся в КОРЕНЬ репозитория, рядом с main.py.
# Запуск из PowerShell, из корня:
#     python znak_hoda_i_format_A06.py
#
# ВАЖНО: идёт после popytki_na_strukture_A06.py.
#
# ═══ ДВЕ ПОЛОМКИ, ОБЕ ОТ ПРЕДЫДУЩИХ ПРАВОК БРАТА ═══
#
# ── 1. ЗНАК ХОДА ПЕРЕВЁРНУТ ──
#
# Брат написал «ход смотрится первым» и объяснил, где искать дивер,
# но НЕ СКАЗАЛ, что ход идёт ПРОТИВ входа. Трейдер достроил сам — и
# достроил наоборот. Её слова из прогона:
#
#   «Восходящий ход выдыхается, есть дивергенция AO и разворотный бар
#    с приседающим. НО ФРАКТАЛЫ ПОКА НЕ ПОКАЗЫВАЮТ ЧЁТКОГО
#    НИСХОДЯЩЕГО ДВИЖЕНИЯ. Жду подтверждения по фракталам для входа
#    в SHORT»
#   «Я не вижу всех трёх условий для входа в SHORT, ПОТОМУ ЧТО
#    ФРАКТАЛЫ НЕ ПОДТВЕРЖДАЮТ НИСХОДЯЩИЙ ХОД»
#   «цена падала… не время для входа, ПОТОМУ ЧТО НЕТ ЧЁТКОГО
#    ВОСХОДЯЩЕГО ХОДА»
#
# То есть для шорта она ждёт, пока рынок УЖЕ развернётся вниз. А
# разворотник ловит КОНЕЦ хода: шортят вершину растущего рынка. Ход
# всегда против входа — иначе разворачивать нечего.
#
# Отсюда же и «жду подтверждения», которое никак не уходило: она
# ждала не подтверждения вообще, а разворота, который уже случился.
#
# ── 2. ФОРМАТ СЛЕТЕЛ ──
#
# Когда слово про руку уехало в самый конец, требование «выдай строго
# JSON» осталось в середине. Рука встала на место, а формат потерялся:
# в прогоне 27 раз «ответ не JSON». Она отвечает прозой или пишет
# что-то похожее на JSON, но без кавычек у ключей и без скобок:
#
#   narrative: На графике EURUSD D1 цена достигла нового максимума…
#   diary_entry: {input: "…", action: "…", result: null}
#
# Разборщик вылавливает дневник, приказа не находит, город
# переспрашивает. Лечится тем, что формат И рука стоят в ОДНОМ
# последнем блоке, с живым образцом.
#
# ═══ ЧТО СТАВИМ ═══
#
# 1. В задание (промпт.md) — знак хода, прямо и с обеих сторон.
# 2. В мозг.py, в самый конец — образец ответа рядом с рукой.
#
# Только A06.
#
# БЕЗОПАСНО. Правит два файла, готовит оба и пишет только если сошлись
# оба. Рядом кладёт копии. Запускать можно сколько угодно раз.

import ast
import shutil
import sys
from pathlib import Path

KOREN = Path(__file__).resolve().parent
MARKER_P = "<!-- ZNAK_HODA_V1 -->"
MARKER_M = "ZNAK_HODA_I_FORMAT_V1"
NUZHEN_P = "<!-- POPYTKI_NA_STRUKTURE_V1 -->"

PROMPT = (KOREN / "GRONDHEIM_CITY" / "Биржа" / "цеха" / "торговый_хаос"
          / "слоты" / "A06" / "промпт.md")
MOZG = (KOREN / "GRONDHEIM_CITY" / "Биржа" / "цеха" / "торговый_хаос"
        / "слоты" / "A06" / "мозг.py")

# ── 1. знак хода в задание ──
P_STAROE = (
    "Не знаешь направления — сравнивать нечего. Не «трудно решить», а\n"
    "нечего даже посмотреть: неизвестно, вершины брать или впадины.\n"
)
P_NOVOE = (
    "Не знаешь направления — сравнивать нечего. Не «трудно решить», а\n"
    "нечего даже посмотреть: неизвестно, вершины брать или впадины.\n"
    "\n"
    "**ХОД ИДЁТ ПРОТИВ ТВОЕГО ВХОДА. ВСЕГДА.** Некрон будит тебя на\n"
    "КОНЦЕ хода, а не на его начале. Ты продаёшь вершину растущего\n"
    "рынка и покупаешь дно падающего — иначе разворачивать нечего.\n"
    "\n"
    "    ход ВВЕРХ  → сравниваешь ВЕРШИНЫ → дивер → вход SHORT\n"
    "    ход ВНИЗ   → сравниваешь ВПАДИНЫ → дивер → вход LONG\n"
    "\n"
    "Для шорта нужен восходящий ход. НЕ нисходящий. Ждать, пока\n"
    "фракталы пойдут вниз, и только потом продавать — значит ждать\n"
    "разворота, который уже случился. Тогда разворачивать нечего, и\n"
    "ты опоздал.\n"
    "\n"
    "Узнай свои слова — так ломается:\n"
    "\n"
    "- «восходящий ход выдыхается… но фракталы не показывают чёткого\n"
    "  нисходящего движения, жду подтверждения для входа в SHORT» —\n"
    "  восходящий ход и есть условие для шорта. Ждать нечего.\n"
    "- «нет всех трёх условий для SHORT, потому что фракталы не\n"
    "  подтверждают нисходящий ход» — они и не должны. Ход вверх —\n"
    "  условие выполнено.\n"
    "- «цена падала… не время для входа, нет чёткого восходящего\n"
    "  хода» — падение и есть условие для LONG.\n"
)

# ── 2. образец ответа рядом с рукой ──
M_STAROE = (
    '        "Третьего нет. Не позвал руку — ничего не произошло, и в "\n'
    '        "истории это останется разговором."\n'
)
M_NOVOE = (
    '        "Третьего нет. Не позвал руку — ничего не произошло, и в "\n'
    '        "истории это останется разговором.\\n"\n'
    '        # ZNAK_HODA_I_FORMAT_V1: когда слово про руку уехало в\n'
    '        # конец, требование формата осталось в середине — и\n'
    '        # слетело: 27 ответов прозой за прогон. Теперь формат и\n'
    '        # рука стоят вместе, последними, с живым образцом.\n'
    '        "\\nИ ФОРМАТ — ЗДЕСЬ ЖЕ. Рассказ отдаёшь НАСТОЯЩИМ JSON, "\n'
    '        "а не текстом, похожим на него. Ключи в кавычках, скобки "\n'
    '        "на месте, ничего лишнего вокруг. Вот образец целиком:\\n"\n'
    '        \'\\n{"narrative": "твой голос, одно-три предложения", \'\n'
    '        \'"diary_entry": {"input": "что видел", "action": "что \'\n'
    '        \'сделал и почему", "result": null}}\\n\'\n'
    '        "\\nНЕ ТАК: строчки вида narrative: ... и diary_entry: "\n'
    '        "{input: ...} без кавычек — это проза, а не JSON, и она "\n'
    '        "не читается.\\n"\n'
    '        "Рассказ этим JSON, решение — рукой. Оба, каждый раз."\n'
)


def podozhdat():
    """Чтобы окно не захлопнулось при запуске двойным кликом."""
    try:
        input("\nГотово. Нажми Enter, чтобы закрыть окно.")
    except Exception:
        pass


def nayti(pryamo, imya):
    """Ищет файл сам. Руками путь прописывать не надо."""
    if pryamo.exists():
        return pryamo
    musor = ("_ARCHIVE", "_OLD", "_АРХИВ", "_УБОРКА", ".bak")
    nashlos = [p for p in KOREN.rglob(imya)
               if "A06" in str(p) and not any(m in str(p) for m in musor)]
    if len(nashlos) == 1:
        return nashlos[0]
    if len(nashlos) > 1:
        print(f"Нашёл несколько {imya}:")
        for nomer, p in enumerate(nashlos, 1):
            print(f"  {nomer}. {p}")
        otvet = input("Какой правим? номер: ").strip()
        if otvet.isdigit() and 1 <= int(otvet) <= len(nashlos):
            return nashlos[int(otvet) - 1]
    return None


def main():
    prompt = nayti(PROMPT, "промпт.md")
    mozg = nayti(MOZG, "мозг.py")
    if prompt is None or mozg is None:
        print("✗ не нашёл задание или мозг A06 —")
        print("  запускай из корня репозитория")
        return 1

    tp = prompt.read_text(encoding="utf-8")
    tm = mozg.read_text(encoding="utf-8")

    if MARKER_P in tp and MARKER_M in tm:
        print("· уже сделано")
        return 0

    if NUZHEN_P not in tp:
        print("✗ сперва накати popytki_na_strukture_A06.py.")
        print("  Ничего не тронул.")
        return 1

    if tp.count(P_STAROE) != 1:
        print(f"✗ задание: нашёл {tp.count(P_STAROE)} мест вместо одного.")
        print("  Ничего не тронул ни в одном файле.")
        return 1
    if tm.count(M_STAROE) != 1:
        print(f"✗ мозг: нашёл {tm.count(M_STAROE)} мест вместо одного.")
        print("  Ничего не тронул ни в одном файле.")
        return 1

    np_ = tp.replace(P_STAROE, P_NOVOE, 1).rstrip("\n") + "\n" + MARKER_P + "\n"
    nm = tm.replace(M_STAROE, M_NOVOE, 1)

    try:
        ast.parse(nm)
    except SyntaxError as beda:
        print(f"✗ мозг поломался после правки (строка {beda.lineno}): "
              f"{beda.msg}")
        print("  Ничего не записал, оригиналы целы.")
        return 1

    for put, novyy, hvost in ((prompt, np_, ".bak_znak"),
                              (mozg, nm, ".bak_znak")):
        kopiya = put.with_suffix(put.suffix + hvost)
        if not kopiya.exists():
            shutil.copy2(put, kopiya)
            print(f"  (копия старого: {kopiya.name})")
        put.write_text(novyy, encoding="utf-8")

    print("✓ поправлено:")
    print("    · ход идёт ПРОТИВ входа — сказано прямо, с обеих сторон")
    print("    · ход вверх → SHORT, ход вниз → LONG")
    print("    · три её перевёрнутые фразы названы дословно")
    print("    · образец JSON встал рядом с рукой, в самом конце")
    print()
    print("Перезапусти Кабинет (main.py) и запусти прогон.")
    print("Смотреть два числа: строчек «ответ не JSON» и «[ПЕРЕСПРОС]»")
    print("быть не должно. В прошлом прогоне 27 и 54.")
    return 0


if __name__ == "__main__":
    kod = main()
    podozhdat()
    sys.exit(kod)
