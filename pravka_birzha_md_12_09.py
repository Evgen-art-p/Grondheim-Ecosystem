def main() -> int:
    if not FAYL.exists():
        print(f"✗ не нашёл {FAYL} — запускать из корня репозитория")
        return 1

    with open(FAYL, "r", encoding="utf-8", newline="") as f:
        tekst = f.read()
    crlf = "\r\n" in tekst
    ishodnyy = tekst

    def vid(s: str) -> str:
        return s.replace("\n", "\r\n") if crlf else s

    sdelano, uzhe, ne_nashlos = 0, 0, 0

    # блоки
    for bylo, stalo, zachem in BLOKI:
        b, s = vid(bylo), vid(stalo)
        if b in tekst:
            tekst = tekst.replace(b, s, 1)
            print(f"✓ {zachem}")
            sdelano += 1
        elif s in tekst:
            print(f"· уже сделано — {zachem}")
            uzhe += 1
        else:
            print(f"✗ не нашёл место — {zachem}")
            ne_nashlos += 1

    # строки таблицы
    perevod = "\r\n" if crlf else "\n"
    stroki = tekst.split(perevod)
    for nachalo, novaya, zachem in STROKI:
        nashli = False
        for i, st in enumerate(stroki):
            if st.startswith(nachalo):
                nashli = True
                if st == novaya:
                    print(f"· уже сделано — {zachem}")
                    uzhe += 1
                else:
                    stroki[i] = novaya
                    print(f"✓ {zachem}")
                    sdelano += 1
                break
        if not nashli:
            print(f"✗ не нашёл строку — {zachem}")
            ne_nashlos += 1
    tekst = perevod.join(stroki)

    # новый раздел
    b, s = vid(YAKOR_UROK), vid(NOVOE)
    if "Сверка 12.09 (по живым файлам репы)" in tekst:
        print("· уже сделано — раздел сверки 12.09")
        uzhe += 1
    elif b in tekst:
        tekst = tekst.replace(b, s, 1)
        print("✓ добавлен раздел сверки 12.09")
        sdelano += 1
    else:
        print("✗ не нашёл место для раздела сверки 12.09")
        ne_nashlos += 1

    if tekst != ishodnyy:
        kopiya = FAYL.with_suffix(FAYL.suffix + ".bak_12_09")
        if not kopiya.exists():
            shutil.copy2(FAYL, kopiya)
            print(f"  (копия старого: {kopiya.name})")
        with open(FAYL, "w", encoding="utf-8", newline="") as f:
            f.write(tekst)

    print()
    print(f"ИТОГ: правок {sdelano}, было уже в порядке {uzhe}, "
          f"не нашлось мест {ne_nashlos}")
    return 1 if ne_nashlos else 0


if __name__ == "__main__":
    sys.exit(main())
