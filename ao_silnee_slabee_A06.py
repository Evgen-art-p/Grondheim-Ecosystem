# -*- coding: utf-8 -*-
# ao_silnee_slabee_A06.py — из описания AO на кадре убрана геометрия
# «выше/ниже», остаётся только сила «сильнее/слабее».
#
# Кладётся в КОРЕНЬ репозитория. Запуск из PowerShell, из корня:
#   python ao_silnee_slabee_A06.py
#
# Найдено 15.09 (Шеф): «какой горб выше прошлого» само по себе не
# симметрично. Для ямы нужен самый ГЛУБОКИЙ провал, а не «выше» —
# «выше» у ямы как раз значит «мельче», обратный знак. Мой прошлый
# патч (ao_gorby_i_yamy_A06.py) назвал горбы и ямы отдельно, но
# оставил геометрию («выше/мельче») — тот же порок в новой форме.
#
# Правильная модель, универсальная для обеих сторон: сильный участок
# → слабее прежнего. Не «выше/ниже», просто сила. AO.md (знания) уже
# так и написан («самый выраженный», «уже меньше прежнего») — эта
# правка просто подтягивает короткую строку промпта под тот же язык.
#
# Идёт ПОСЛЕ ao_gorby_i_yamy_A06.py и заменяет собой его правку.
# Если тот скрипт ещё не запускался — этот всё равно сработает.
#
# Ничего не удаляет. Кладёт рядом копию промпт.md.bak_ao_silnee.
# Запускать можно сколько угодно раз.

import shutil
import sys
from pathlib import Path

KOREN = Path(__file__).resolve().parent
PROMPT_PATH = (KOREN / "GRONDHEIM_CITY" / "Биржа" / "цеха" / "торговый_хаос"
               / "слоты" / "A06" / "промпт.md")

# состояние после ao_gorby_i_yamy_A06.py
BYLO_POSLE_YAM = (
    "**Нижняя полоса — AO.** Столбики над нулём и под нулём. Гребни над\n"
    "нулём — горбы, гребни под нулём — ямы. Смотри не на цифру, а на то,\n"
    "какой горб или яма выше/мельче прошлого и куда в это время шла\n"
    "цена.\n"
)

# исходное состояние (если ao_gorby_i_yamy_A06.py не запускался)
BYLO_ISHODNOE = (
    "**Нижняя полоса — AO.** Столбики над нулём и под нулём. Их гребни и\n"
    "есть горбы: смотри не на цифру, а на то, какой горб выше прошлого и\n"
    "куда в это время шла цена.\n"
)

STALO = (
    "**Нижняя полоса — AO.** Столбики над нулём и под нулём — горбы и\n"
    "ямы. Не «выше/ниже» — сила: следующий участок слабее прежнего,\n"
    "цена при этом продолжает тот же ход — толчок ослаб.\n"
)


def main() -> int:
    if not PROMPT_PATH.exists():
        print(f"✗ нет файла {PROMPT_PATH} — запускать из корня репозитория")
        return 1

    tekst = PROMPT_PATH.read_text(encoding="utf-8")

    if "Не «выше/ниже» — сила" in tekst:
        print("· уже сделано")
        return 0

    if BYLO_POSLE_YAM in tekst:
        tekst = tekst.replace(BYLO_POSLE_YAM, STALO, 1)
        istochnik = "поверх ao_gorby_i_yamy_A06.py"
    elif BYLO_ISHODNOE in tekst:
        tekst = tekst.replace(BYLO_ISHODNOE, STALO, 1)
        istochnik = "с исходного состояния"
    else:
        print("✗ не нашёл ожидаемое место — промпт мог измениться, "
              "скажи Брату, поправим по месту")
        return 1

    kopiya = PROMPT_PATH.with_suffix(PROMPT_PATH.suffix + ".bak_ao_silnee")
    if not kopiya.exists():
        shutil.copy2(PROMPT_PATH, kopiya)
        print(f"  (копия старого: {kopiya.name})")
    PROMPT_PATH.write_text(tekst, encoding="utf-8")
    print(f"✓ AO на кадре: сила вместо геометрии ({istochnik})")
    print()
    print("Перезапусти Кабинет (main.py) — правка не подхватится на лету.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
