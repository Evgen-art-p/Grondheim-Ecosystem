# ═══ ЧТО НАШЛОСЬ ═══
#
# Прогон 17.09, H4: 62 входа, 50 стопов из 54 закрытий, −43R.
#
# Сверил её числа с краями разворотного бара:
#
#     отступ стопа за край бара:
#       медиана           1 пункт
#       ровно на краю     9 входов из 62
#       один-два пункта   51 вход
#
# То есть стоп стоит НЕ ЗА краем, а НА краю. Спредов нет вовсе.
#
# Край разворотного бара — самый заметный уровень на кадре, рынок
# возвращается к нему постоянно: обычный ретест, он ничего не
# отменяет. Цена подходит, касается, идёт дальше в её сторону — а
# стоп уже снят, потому что стоял ровно там.
#
# На дневках это сходило: бар крупный, ретест до самого края обычно
# не доходит. На H4 бар мелкий — доходит почти всегда.
#
# ═══ ГЛАВНОЕ: КАНОН НЕ НАРУШЕН, ОН ПРОСТО НЕ ПРОЧИТАН ═══
#
# Город УЖЕ считает всё правильно и кладёт готовой строкой на стол:
#
#     ВХОД: Sell Stop @ 1.06589   стоп 1.07017
#           (бар: H 1.06997 / L 1.06599)   (спред терминала)
#
# По тени, не по телу. Сверху два спреда, снизу один. Ровно канон.
#
# А её заявка 1.06599 — это ровно low бара, стоп 1.06997 — ровно
# high. Голые края. Она берёт числа С КАРТИНКИ ГЛАЗАМИ, а не со
# стола, где они уже посчитаны.
#
# И сходится с другим: стол рукой она открыла лишь 129 раз из 279.
# В остальных этих чисел просто не видела.
#
# ═══ ЧТО СТАВИМ ═══
#
# В раздел ВХОД — прямо и коротко: числа заявки и стопа КОПИРУЮТСЯ
# со строки ВХОД на столе. Нет стола перед глазами — возьми его
# рукой ДО того, как отдавать ENTER. Край бара — не стоп.
#
# С её же цифрами, чтобы узнала свою ошибку.
#
# Только A06. Правится текст задания, ни строчки кода.
#
# БЕЗОПАСНО. Рядом кладёт промпт.md.bak_chisla.
# Запускать можно сколько угодно раз.

import shutil
import sys
from pathlib import Path

KOREN = Path(__file__).resolve().parent
MARKER = "<!-- CHISLA_SO_STOLA_V1 -->"

PUT = (KOREN / "GRONDHEIM_CITY" / "Биржа" / "цеха" / "торговый_хаос"
       / "слоты" / "A06" / "промпт.md")

STAROE = (
    "Края и готовые цены тебе дают прямо в сообщении — считать нечего.\n"
    "Правило за ними такое: сверху бара платим **два спреда**, снизу —\n"
    "**один**. Неважно, заявка это или стоп: покупка идёт по другой\n"
    "стороне котировки, оттого сверху дороже.\n"
)

NOVOE = (
    "**ЧИСЛА БЕРУТСЯ СО СТОЛА. НЕ С ГЛАЗА.** На столе есть готовая\n"
    "строка — в ней уже посчитано всё:\n"
    "\n"
    "    ВХОД: Sell Stop @ 1.06589   стоп 1.07017\n"
    "          (бар: H 1.06997 / L 1.06599)\n"
    "\n"
    "Эти две цены ты **копируешь** в приказ. Не пересчитываешь, не\n"
    "прикидываешь по картинке, не берёшь края бара как есть.\n"
    "\n"
    "Стола перед глазами нет — возьми его рукой `stol_na_etazhe` ДО\n"
    "того, как отдавать ENTER. Войти, не посмотрев числа, нельзя:\n"
    "картинка показывает форму, а цену называет стол.\n"
    "\n"
    "Правило, по которому стол их считает: окружаем **по теням**, не по\n"
    "телу. Сверху бара платим **два спреда**, снизу — **один**.\n"
    "Неважно, заявка это или стоп: покупка идёт по другой стороне\n"
    "котировки, оттого сверху дороже.\n"
    "\n"
    "**КРАЙ БАРА — ЭТО НЕ СТОП.** Стоп стоит ЗА краем, на спред\n"
    "дальше. Рынок возвращается к краю разворотного бара постоянно —\n"
    "это обычный ретест, он ничего не отменяет. Стоп, поставленный\n"
    "ровно на край, снимает такой откат, и сделка гибнет там, где\n"
    "была права.\n"
    "\n"
    "Узнай свою ошибку: в одном прогоне из 62 входов **шестьдесят**\n"
    "имели стоп ровно на краю бара или в одном пункте от него, а\n"
    "девять — точно на уровне края. Спредов не было ни в одном. Это\n"
    "значит, числа брались с картинки, а не со стола.\n"
)


def podozhdat():
    try:
        input("\nГотово. Нажми Enter, чтобы закрыть окно.")
    except Exception:
        pass


def nayti():
    if PUT.exists():
        return PUT
    musor = ("_ARCHIVE", "_OLD", "_АРХИВ", "_УБОРКА", ".bak")
    nashlos = [p for p in KOREN.rglob("промпт.md")
               if "A06" in str(p) and not any(m in str(p) for m in musor)]
    if len(nashlos) == 1:
        print(f"Нашёл: {nashlos[0]}")
        return nashlos[0]
    if len(nashlos) > 1:
        print("Нашёл несколько заданий A06:")
        for nomer, p in enumerate(nashlos, 1):
            print(f"  {nomer}. {p}")
        otvet = input("Какое правим? номер: ").strip()
        if otvet.isdigit() and 1 <= int(otvet) <= len(nashlos):
            return nashlos[int(otvet) - 1]
    return None


def main():
    put = nayti()
    if put is None:
        print("✗ не нашёл задание A06 — запускай из корня репозитория")
        return 1

    tekst = put.read_text(encoding="utf-8")

    if MARKER in tekst:
        print("· уже сделано")
        return 0

    if tekst.count(STAROE) != 1:
        print(f"✗ нашёл {tekst.count(STAROE)} мест вместо одного.")
        print("  Ничего не тронул. Скажи Брату, поправим по месту.")
        return 1

    novyy = tekst.replace(STAROE, NOVOE, 1)
    novyy = novyy.rstrip("\n") + "\n" + MARKER + "\n"

    kopiya = put.with_suffix(put.suffix + ".bak_chisla")
    if not kopiya.exists():
        shutil.copy2(put, kopiya)
        print(f"  (копия старого: {kopiya.name})")
    put.write_text(novyy, encoding="utf-8")

    print("✓ числа теперь со стола:")
    print("    · заявка и стоп копируются из строки ВХОД")
    print("    · нет стола — взять рукой ДО приказа")
    print("    · «край бара — это не стоп» сказано прямо")
    print("    · её собственные 62 входа приведены как ошибка")
    print()
    print("Перезапусти Кабинет (main.py) и запусти прогон.")
    print("Проверка простая: стоп должен отстоять от края бара на")
    print("спред-другой, а не на один пункт. И стол она должна брать")
    print("перед каждым входом.")
    return 0


if __name__ == "__main__":
    kod = main()
    podozhdat()
    sys.exit(kod)
