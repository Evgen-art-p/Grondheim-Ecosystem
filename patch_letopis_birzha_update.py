def main():
    if not TARGET.exists():
        print(f"НЕ НАЙДЕН: {TARGET} (запусти из корня Grondheim-Ecosystem)")
        sys.exit(1)

    src = TARGET.read_text(encoding="utf-8")

    if "БИРЖА.md" in src and "09.07, новое): мозг слота" in src:
        print("Уже применено — идемпотентность держит, ничего не меняю.")
        return

    backup = TARGET.with_suffix(f".md.bak_{datetime.now():%Y%m%d_%H%M%S}")
    shutil.copy2(TARGET, backup)
    print(f"Бэкап: {backup}")

    missing = []
    for old, new in EDITS:
        if old not in src:
            missing.append(old[:60])
            continue
        src = src.replace(old, new, 1)

    if missing:
        print("⚠️  Не нашёл фрагменты (файл менялся с момента диагностики):")
        for m in missing:
            print("   ", m)
        print("Применяю то, что нашлось; остальное правь руками при желании.")

    TARGET.write_text(src, encoding="utf-8")
    print("Готово: летопись обновлена до v4.2 (09.07).")


if __name__ == "__main__":
    main()
