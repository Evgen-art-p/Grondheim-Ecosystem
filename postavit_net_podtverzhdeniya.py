# -*- coding: utf-8 -*-
# NET_PODTVERZHDENIYA_V1
"""
УБРАТЬ ЛАЗЕЙКУ «ЖДУ ПОДТВЕРЖДЕНИЯ» И ПОЧИНИТЬ ПОВИСШУЮ ССЫЛКУ.

═══ ЧТО НАШЛОСЬ В ЖИВОМ РАЗГОВОРЕ 09.09 ═══

Механику входа трейдер знает: закон входа на месте (по рынку не
входим, всегда отложенная заявка, LONG выше цены, SHORT ниже), спреды
считает, стоп за бар знает. Место после патча `IDTI_S_HODOM_V1` тоже
знает — конец хода.

А заявку не поставил НИ РАЗУ за весь разговор.

Он сам сказал: падение выдыхается, дивергенция есть, приседающий есть,
медведи слабеют. И каждый раз — «жду подтверждения разворота или
отката», WAIT.

**Подтверждения не будет никогда.** Рынок его не даёт — это весь
сегодняшний канон. Конец хода И ЕСТЬ то, чего он ждёт; заявка за
разворотный бар и есть проверка, а стоп — её цена. Ждать «чёткого
сигнала» — старая привычка искать сигнал вместо того, чтобы идти с
ходом.

Дверь в эту лазейку открыли мы сами, написав «промолчать — законный и
самый частый ответ». Для флэта это верно и остаётся. А когда ход
выдохся и некрон стоит — это уже отговорка.

═══ ЧТО ПАТЧ ДЕЛАЕТ (3 правки в три бумаги) ═══

**1. Разводит два «жду».** Оставляет законным «работы не видно» и
прямо закрывает «жду подтверждения разворота»: подтверждения не будет,
конец хода и есть то, чего ждал.

**2. Чинит повисшую ссылку.** В бумаге осталось «в знаниях расписано,
что ты ждёшь и чем платишь за каждый — читай там», а те знания уехали
в `знания/ведение/` патчем `POLKA_PO_MOMENTU_V1`. Ссылка вела в
пустоту — теперь указывает на руку `razbor_struktury` и говорит, что
это для ведения, а не для входа.

**3. Ставит различение прямо в закон входа** — коротким абзацем:
некрон есть и ход выдохся → называй цену; ход в разгаре → спи. Чтобы
не искать это по всей бумаге.

═══ ЧЕГО ПАТЧ НЕ ДЕЛАЕТ ═══

Не заставляет входить. «Работы не вижу» остаётся полноценным и частым
ответом — убирается только отговорка «жду, когда станет яснее», потому
что яснее не станет.

Не трогает закон входа, спреды, стоп, формат ответа, правило трёх.

Запускать из корня репозитория:
    python postavit_net_podtverzhdeniya.py

Идемпотентен (маркер NET_PODTVERZHDENIYA_V1). Рядом .bak.
"""
from __future__ import annotations
from pathlib import Path

MARKER = "NET_PODTVERZHDENIYA_V1"
BAZA = "GRONDHEIM_CITY/Биржа/цеха/торговый_хаос/слоты"
SLOTY = ("A06", "A07", "A08")


# ── 1) два разных «жду» ─────────────────────────────────────────────
ZHDU_OLD = """Промолчать — законный и самый частый ответ. Работы не видно — так и
скажи."""

ZHDU_NEW = """Промолчать — законный и самый частый ответ. Работы не видно — так и
скажи.

**Но «жду подтверждения разворота» — не ответ.** Подтверждения не
будет: рынок его не даёт и не обещал. Конец хода И ЕСТЬ то, чего ты
ждал. Если ход выдохся и разворотный бар стоит — называй цену заявки;
она и есть твоя проверка, а стоп — её цена. Не взяло — значит ход ещё
не кончился, и это не ошибка.

Разница простая:
· **ходить не с чем** — работы нет, спи. Это честно.
· **ход в разгаре** — конца ждать рано, спи. Тоже честно.
· **ход выдохся и некрон стоит** — это твоё место. Ждать больше
  нечего."""


# ── 2) повисшая ссылка на уехавшие знания ───────────────────────────
SSYLKA_OLD = """Чем раньше вход, тем дороже и тем больше нужно смелости; чем
позже, тем дешевле и тем меньше остаётся хода. В знаниях расписано, что
ты ждёшь и чем платишь за каждый — читай там."""

SSYLKA_NEW = """Чем раньше вход, тем дороже и тем больше нужно смелости; чем
позже, тем дешевле и тем меньше остаётся хода. Подробный разбор с
номерами волн лежит отдельно и достаётся рукой `razbor_struktury` —
это инструмент ВЕДЕНИЯ, для входа он не нужен."""


# ── 3) различение прямо в законе входа ──────────────────────────────
ZAKON_OLD = """## ЗАКОН ВХОДА

Входа по рынку в этой системе нет."""

ZAKON_NEW = """## ЗАКОН ВХОДА

**Когда называть цену.** Ход выдохся — горбы AO мельчают, а цена всё
лезет за край, — и стоит разворотный бар: вот и место, называй цену
заявки. Ход в разгаре — некрон посреди него это передышка, спи. Ходить
не с чем — работы нет.

Третьего состояния «подожду, пока станет яснее» не бывает: яснее не
станет.

Входа по рынку в этой системе нет."""


PRAVKI = [
    ("два разных «жду»", ZHDU_OLD, ZHDU_NEW),
    ("повисшая ссылка на знания", SSYLKA_OLD, SSYLKA_NEW),
    ("различение в законе входа", ZAKON_OLD, ZAKON_NEW),
]


def main() -> None:
    root = Path(__file__).resolve().parent
    fayly = [(root / BAZA / s / "промпт.md", s) for s in SLOTY]

    net = [f for f, _ in fayly if not f.exists()]
    if net:
        print("НЕ НАШЁЛ файлы (запускать из корня репозитория):")
        for f in net:
            print("   ", f)
        return

    plan, uzhe, bracket = [], [], []
    for f, slot in fayly:
        t = f.read_text(encoding="utf-8")
        if MARKER in t:
            uzhe.append(slot)
            continue
        novyy, ploho = t, None
        for imya, old, new in PRAVKI:
            if novyy.count(old) != 1:
                ploho = f"«{imya}» — совпадений {novyy.count(old)} (нужно 1)"
                break
            novyy = novyy.replace(old, new, 1)
        if ploho:
            bracket.append((slot, ploho))
            continue
        plan.append((f, slot, t, novyy.rstrip("\n") + f"\n\n<!-- {MARKER} -->\n"))

    if uzhe and not plan and not bracket:
        print("уже накачен во всех бумагах — ничего не трогаю")
        return

    if bracket:
        print("⚠ Файлы отличаются от ожидаемого — НИЧЕГО не меняю:")
        for slot, prichina in bracket:
            print(f"   {slot}: {prichina}")
        print("\nПришли Брату эти бумаги — доведу под них.")
        return

    for f, slot, staroe, novoe in plan:
        bak = f.with_suffix(f.suffix + ".bak_net_podtverzhdeniya")
        if not bak.exists():
            bak.write_text(staroe, encoding="utf-8")
        f.write_text(novoe, encoding="utf-8")
        print(f"✔ {slot}/промпт.md — 3 правки легли")

    if uzhe:
        print("(пропущены, уже накачены: " + ", ".join(uzhe) + ")")

    print("\nЧто должно измениться:")
    print("  Раньше он на выдохшемся ходе говорил «жду подтверждения»")
    print("  и не ставил заявку НИ РАЗУ. Теперь на том же месте должен")
    print("  назвать цену — или честно сказать, что ход ещё в разгаре.")
    print("\n«Работы не вижу» остаётся законным ответом. Убрана только")
    print("отговорка «подожду, пока станет яснее» — яснее не станет.")


if __name__ == "__main__":
    main()
