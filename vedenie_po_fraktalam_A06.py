# -*- coding: utf-8 -*-
# vedenie_po_fraktalam_A06.py — ведению позиции даётся правило, не
# только список имён действий.
#
# Кладётся в КОРЕНЬ репозитория (рядом с папками Биржа/ и
# GRONDHEIM_CITY/). Запуск из PowerShell, из корня:
#   python vedenie_po_fraktalam_A06.py
#
# Найдено 13.09 на живом прогоне: раздел «ЕСЛИ У ТЕБЯ УЖЕ ЕСТЬ ЗАЯВКА
# ИЛИ ПОЗИЦИЯ» называл четыре действия (HOLD/MOVE_STOP/ADD/CLOSE), но
# ни слова не говорил, когда каким пользоваться. За весь прогон —
# 42 раза HOLD, ни разу MOVE_STOP. Хороший ход шёл, стоп всё это
# время стоял там же, где на входе, — рынок откатил, стоп поймал то,
# что уже было отыграно.
#
# Правило берёт то же самое, что трейдер уже смотрит для хода
# (TREND_PO_TSENE.md, фракталы) — и применяет его к стопу: сложился
# новый фрактал в твою сторону — подтягиваешь стоп за него. Не новый
# прибор, тот же самый, только для другого вопроса.
#
# Ничего не удаляет. Кладёт рядом копию промпт.md.bak_vedenie_fraktal.
# Запускать можно сколько угодно раз.

import shutil
import sys
from pathlib import Path

KOREN = Path(__file__).resolve().parent
PROMPT_PATH = (KOREN / "GRONDHEIM_CITY" / "Биржа" / "цеха" / "торговый_хаос"
               / "слоты" / "A06" / "промпт.md")

BYLO = (
    "## ЕСЛИ У ТЕБЯ УЖЕ ЕСТЬ ЗАЯВКА ИЛИ ПОЗИЦИЯ\n"
    "\n"
    "Тогда вопрос другой: не «входить ли», а что делать с открытым. Второй\n"
    "раз в то же место не входят — рука такой приказ и не примет.\n"
    "\n"
    "Можно **держать** (HOLD), **подтянуть стоп** (MOVE_STOP), **долить**\n"
    "на новом фрактале по тренду (ADD) или **закрыть** своей волей (CLOSE).\n"
)

STALO = (
    "## ЕСЛИ У ТЕБЯ УЖЕ ЕСТЬ ЗАЯВКА ИЛИ ПОЗИЦИЯ\n"
    "\n"
    "Тогда вопрос другой: не «входить ли», а что делать с открытым. Второй\n"
    "раз в то же место не входят — рука такой приказ и не примет.\n"
    "\n"
    "Можно **держать** (HOLD), **подтянуть стоп** (MOVE_STOP), **долить**\n"
    "на новом фрактале по тренду (ADD) или **закрыть** своей волей (CLOSE).\n"
    "\n"
    "**Стоп двигаешь по фракталам — тем же, что уже смотришь для хода.**\n"
    "Сложился новый фрактал в твою сторону (после входа) — подтягивай\n"
    "стоп сразу за него: LONG — под свежий фрактал-лой, SHORT — над\n"
    "свежим фрактал-хай. Не под последний бар — под фрактал, он уже\n"
    "подтверждён двумя барами с каждой стороны, случайный шум в него не\n"
    "попадёт.\n"
    "\n"
    "Стоп двигаешь только в свою пользу. Никогда не отодвигаешь дальше\n"
    "входа.\n"
    "\n"
    "Фрактала в твою сторону ещё не сложилось — держишь (HOLD), ничего\n"
    "не выдумываешь.\n"
)


def main() -> int:
    if not PROMPT_PATH.exists():
        print(f"✗ нет файла {PROMPT_PATH} — запускать из корня репозитория")
        return 1

    tekst = PROMPT_PATH.read_text(encoding="utf-8")

    if "Стоп двигаешь по фракталам" in tekst:
        print("· уже сделано")
        return 0
    elif BYLO in tekst:
        tekst = tekst.replace(BYLO, STALO, 1)
        kopiya = PROMPT_PATH.with_suffix(
            PROMPT_PATH.suffix + ".bak_vedenie_fraktal")
        if not kopiya.exists():
            shutil.copy2(PROMPT_PATH, kopiya)
            print(f"  (копия старого: {kopiya.name})")
        PROMPT_PATH.write_text(tekst, encoding="utf-8")
        print("✓ ведение позиции: стоп по фракталам, правило дописано")
        print()
        print("Перезапусти Кабинет (main.py) — правка не подхватится "
              "на лету.")
        return 0
    else:
        print("✗ не нашёл ожидаемое место — промпт мог измениться иначе, "
              "скажи Брату, поправим по месту")
        return 1


if __name__ == "__main__":
    sys.exit(main())
