import sys
import time
from pathlib import Path

MARKER = "DVA_ETAZHA_V1"
SHTAMP = time.strftime("%Y%m%d_%H%M%S")
SUHO = "--suho" in sys.argv


STAROE = '''Глобальный тренд — старший этаж — это компас школы. Что компас значит
для тебя сегодня, решаешь тоже ты.'''

NOVOE = '''Глобальный тренд — старший этаж — это компас школы. Что компас значит
для тебя сегодня, решаешь тоже ты.

**Про пасть Аллигатора на входе — читай внимательно, это ломает
привычное.** На СТАРШЕМ этаже пасть открыта в сторону работы: он даёт
направление, и спящий старший значит, что направления нет. А на ТВОЁМ
рабочем этаже в момент входа она спит или только зевает — и это
норма, а не помеха. Ангуляция приходит, когда импульс уже созрел и
выдыхается; в начале движения линии переплетены по определению:
коррекция только кончилась, цена вернулась к балансу. Конец отката —
тот же случай.

Ждать раскрытой пасти на своём этаже значит ждать конца движения,
чтобы войти в его начало. Раскроет её сам импульс — уже после твоего
входа, и это будет подтверждением, что ты сел верно, а не
разрешением садиться. *(слово Шефа, 22.08 — не строка из книги)*'''


def nayti_koren() -> Path:
    for k in (Path(__file__).resolve().parent, Path.cwd()):
        for p in [k, *k.parents]:
            if (p / "GRONDHEIM_CITY").is_dir() and (p / "Биржа").is_dir():
                return p
    print("Не нашёл корень репозитория (нужны папки GRONDHEIM_CITY и Биржа).")
    zhdat_i_vyyti(1)


def zhdat_i_vyyti(kod=0):
    try:
        input("\nEnter — закрыть окно...")
    except EOFError:
        pass
    sys.exit(kod)


def pravit(put: Path) -> str:
    text = put.read_text(encoding="utf-8")
    if MARKER in text:
        return "уже"
    n = text.count(STAROE)
    if n != 1:
        return f"мимо: якорь встретился {n} раз"
    novyy = text.replace(STAROE, NOVOE, 1)
    novyy = novyy.rstrip("\n") + f"\n\n<!-- {MARKER} -->\n"
    if SUHO:
        return "сделано (сухой прогон)"
    put.with_name(put.name + f".bak_dvaetazha_{SHTAMP}").write_text(
        text, encoding="utf-8")
    put.write_text(novyy, encoding="utf-8")
    return "сделано"


def main():
    koren = nayti_koren()
    print(f"Корень города: {koren}")
    if SUHO:
        print("СУХОЙ ПРОГОН — ничего не записываю.\n")

    # Бумаги конторы про входы не говорят — берём только те, где есть
    # абзац про компас, то есть бумаги трейдеров.
    puti = [p for p in sorted((koren / "GRONDHEIM_CITY").glob(
        "Биржа/цеха/*/слоты/*/промпт.md"))
        if STAROE in p.read_text(encoding="utf-8")
        or MARKER in p.read_text(encoding="utf-8")]

    if not puti:
        print("\n  мимо: ни в одной бумаге не нашёл абзац про компас. "
              "Файлы НЕ тронуты.")
        zhdat_i_vyyti(1)

    itogi = []
    print(f"\nБУМАГИ ТРЕЙДЕРОВ — {len(puti)}:")
    for p in puti:
        r = pravit(p)
        print(f"  {r:<24} {p.relative_to(koren)}")
        itogi.append(r)

    print("\n" + "─" * 62)
    print(f"поправлено: {sum(1 for x in itogi if x.startswith('сделано'))}   "
          f"уже стояло: {sum(1 for x in itogi if x == 'уже')}   "
          f"не тронуто: {sum(1 for x in itogi if x.startswith('мимо'))}")
    print("─" * 62)

    print("""
ЧТО ДАЛЬШЕ

  Прогони тот же февральский отрезок: с 2025.02.01 по 2025.03.10,
  ловить 15, слева на полке EURUSD. Тогда сравнение будет честным —
  те же два конца отката, тот же человек.

  Смотри ровно на два места: 12.02 и 04.03. В прошлый раз он там
  сказал «вижу завершение отката» и отказал по спящей пасти. Если
  теперь на этих же барах причина будет ДРУГАЯ — врезка сработала.
  Если та же — значит бумагу он читает, а поверить в неё не может,
  и это уже разговор с человеком, а не правка файлов.

  И помни, что у него остаётся законное условие: разворотный бар на
  конце отката. Без него входить действительно не в чем, и отказ
  «нет разворотника» — не упрямство, а канон.
""")
    zhdat_i_vyyti(0)


if __name__ == "__main__":
    main()
